"""Headless Claude Code harness: run claude -p with the plugin, parse stream-json."""
import json  # O(1)
import os  # O(1)
import subprocess  # O(1)
from dataclasses import dataclass, field  # O(1)
from pathlib import Path  # O(1)

REPO_ROOT = Path(__file__).resolve().parents[2]  # O(1)
SCRUB = ("CLAUDE_CODE_SESSION_ID", "CLAUDE_CODE_MESSAGING_SOCKET", "CLAUDE_CODE_MESSAGING_TOKEN",  # O(1)
         "CLAUDE_CODE_BRIDGE_SESSION_ID", "CLAUDE_CODE_CHILD_SESSION", "CLAUDE_CODE_ENTRYPOINT",  # O(1)
         "CLAUDE_CODE_PLUGIN_DIRS", "SUPERLITE_SESSION_ID", "SUPERLITE_STATE_DIR", "CLAUDE_ENV_FILE")  # O(1)


class HarnessError(RuntimeError):  # O(1)
    pass  # O(1)


@dataclass  # O(1)
class Session:  # O(1)
    init: dict = field(default_factory=dict)  # O(1)
    hooks: list = field(default_factory=list)  # O(1)
    events: list = field(default_factory=list)  # O(1)
    result: dict = field(default_factory=dict)  # O(1)
    cost_usd: float = 0.0  # O(1)
    text: str = ""  # O(1)
    skipped: int = 0  # O(1)

    def hook_outputs(self, event: str) -> list:  # O(h)
        return [h.get("output", "") for h in self.hooks if h.get("hook_event") == event]  # O(h)


def scrubbed_env(extra: dict | None = None) -> dict:  # O(e)
    env = {k: v for k, v in os.environ.items() if k not in SCRUB}  # O(e)
    env.update(extra or {})  # O(x)
    return env  # O(1)


def parse_stream(lines: list, stderr: str = "") -> Session:  # O(n)
    s = Session()  # O(1)
    for line in lines:  # O(n)
        try:  # O(1)
            ev = json.loads(line)  # O(len)
        except ValueError:  # O(1)
            s.skipped += 1  # O(1)
            continue  # O(1)
        if not isinstance(ev, dict):  # O(1)
            s.skipped += 1  # O(1)
            continue  # O(1)
        s.events.append(ev)  # O(1)
        if ev.get("type") == "system" and ev.get("subtype") == "init":  # O(1)
            s.init = ev  # O(1)
        elif ev.get("type") == "system" and ev.get("subtype") == "hook_response":  # O(1)
            s.hooks.append(ev)  # O(1)
        elif ev.get("type") == "result":  # O(1)
            s.result = ev  # O(1)
    if not s.result:  # O(1)
        raise HarnessError("no result event; stderr tail: " + stderr[-500:])  # O(1)
    s.cost_usd = float(s.result.get("total_cost_usd") or 0)  # O(1)
    s.text = s.result.get("result") or ""  # O(1)
    return s  # O(1)


def run_headless(prompt: str, *, cwd: Path, model: str = "haiku", allowed_tools: list = (),  # O(1)
                 settings: dict | None = None, env: dict | None = None, max_turns: int = 6,  # O(1)
                 timeout: int = 300) -> Session:  # O(1)
    cmd = ["claude", "-p", prompt, "--output-format", "stream-json", "--verbose",  # O(1)
           "--include-hook-events", "--setting-sources", "", "--plugin-dir", str(REPO_ROOT),  # O(1)
           "--model", model, "--max-turns", str(max_turns)]  # O(1)
    if settings is not None:  # O(1)
        path = Path(cwd) / ".e2e-settings.json"  # O(1)
        path.write_text(json.dumps(settings))  # O(s)
        cmd += ["--settings", str(path)]  # O(1)
    if allowed_tools:  # O(1)
        cmd += ["--allowedTools", *allowed_tools]  # O(t)
    p = subprocess.run(cmd, stdin=subprocess.DEVNULL, capture_output=True, text=True,  # O(out)
                       timeout=timeout, cwd=cwd, env=scrubbed_env(env))  # O(out)
    return parse_stream(p.stdout.splitlines(), p.stderr)  # O(n)
