import itertools  # O(1)
import json  # O(1)
import os  # O(1)
import re  # O(1)
import shlex  # O(1)
import subprocess  # O(1)
import time  # O(1)
from pathlib import Path  # O(1)

REPO_ROOT = Path(__file__).resolve().parents[2]  # O(1)
_COUNTER = itertools.count()  # O(1)
ISOLATE = ["CLAUDE_CODE_SESSION_ID", "CLAUDE_CODE_MESSAGING_SOCKET", "CLAUDE_CODE_MESSAGING_TOKEN", "CLAUDE_CODE_BRIDGE_SESSION_ID", "CLAUDE_CODE_CHILD_SESSION", "CLAUDE_CODE_ENTRYPOINT", "CLAUDE_CODE_PLUGIN_DIRS", "SUPERLITE_SESSION_ID", "SUPERLITE_STATE_DIR", "SUPERLITE_FLEET_WORKER", "SUPERLITE_FLEET_AGENT", "CLAUDE_ENV_FILE"]  # O(1)
SUMMARY_KEYS = {"timer_fired": r"\[AgentSummary\] Timer fired", "forking": r"Forking for summary", "notes": r"Asking (?:\S+ )?for summary from", "stopped": r"Stopping summarization"}  # O(1)


class TuiError(RuntimeError):  # O(1)
    pass  # O(1)


def needs_trust(pane: str) -> bool:  # O(n)
    return "I trust this folder" in pane  # O(n)


def is_ready(pane: str) -> bool:  # O(n)
    prompt = re.search(r"^─{10,}\s*\n❯", pane, re.M) is not None  # O(n)
    return ("? for shortcuts" in pane or prompt) and not needs_trust(pane)  # O(n)


def summary_counts(log: str) -> dict:  # O(n)
    return {key: len(re.findall(pattern, log)) for key, pattern in SUMMARY_KEYS.items()}  # O(n)


class TuiSession:  # O(1)
    def __init__(self, cwd: Path, *, model: str = "haiku", allowed_tools: list = (), env: dict = None, ready_timeout: int = 90):  # O(1)
        self.cwd = Path(cwd)  # O(1)
        self.model = model  # O(1)
        self.allowed_tools = list(allowed_tools)  # O(1)
        self.env = dict(env or {})  # O(1)
        self.ready_timeout = ready_timeout  # O(1)
        self.socket = f"sl-e2e-{os.getpid()}-{next(_COUNTER)}"  # O(1)
        self.marker_path = self.cwd / "marker.txt"  # O(1)
        self.debug_path = self.cwd / "debug.log"  # O(1)
        self.settings_path = self.cwd / ".e2e-settings.json"  # O(1)

    @staticmethod  # O(1)
    def settings_json(marker_path: Path) -> dict:  # O(1)
        def hook(name: str) -> list:  # O(1)
            return [{"hooks": [{"type": "command", "command": f'echo {name} >> "$E2E_MARKER"'}]}]  # O(1)
        return {"hooks": {"Stop": hook("STOPPED"), "SubagentStop": hook("SUBAGENT_STOPPED")}}  # O(1)

    def _tmux(self, *args: str) -> subprocess.CompletedProcess:  # O(1)
        return subprocess.run(["tmux", "-L", self.socket, *args], capture_output=True, text=True, timeout=30)  # O(1)

    def start(self) -> None:  # O(t)
        self.cwd.mkdir(parents=True, exist_ok=True)  # O(1)
        self.marker_path.touch()  # O(1)
        self.settings_path.write_text(json.dumps(self.settings_json(self.marker_path)))  # O(1)
        self._tmux("kill-server")  # O(1)
        prefix = ["env"] + [x for v in ISOLATE for x in ("-u", v)] + [f"E2E_MARKER={self.marker_path}"] + [f"{k}={v}" for k, v in self.env.items()]  # O(1)
        cmd = prefix + ["claude", "--model", self.model, "--plugin-dir", str(REPO_ROOT), "--setting-sources", "", "--settings", str(self.settings_path), "--debug-file", str(self.debug_path)]  # O(1)
        if self.allowed_tools:  # O(1)
            cmd += ["--allowedTools", *self.allowed_tools]  # O(1)
        shell = " ".join(shlex.quote(c) for c in cmd) + "; sleep 2"  # O(1)
        made = self._tmux("new-session", "-d", "-x", "180", "-y", "50", "-c", str(self.cwd), shell)  # O(1)
        if made.returncode != 0:  # O(1)
            raise TuiError(f"tmux new-session failed: {made.stderr}")  # O(1)
        deadline = time.time() + self.ready_timeout  # O(1)
        pane = ""  # O(1)
        while time.time() < deadline:  # O(t)
            pane = self.pane()  # O(1)
            if needs_trust(pane):  # O(1)
                self._tmux("send-keys", "Down")  # O(1)
                self._tmux("send-keys", "Enter")  # O(1)
            elif is_ready(pane):  # O(1)
                return  # O(1)
            time.sleep(1)  # O(1)
        raise TuiError(f"claude not ready after {self.ready_timeout}s; last pane:\n{pane}")  # O(1)

    def send(self, prompt: str) -> None:  # O(1)
        self._tmux("set-buffer", prompt)  # O(1)
        self._tmux("paste-buffer", "-p")  # O(1)
        time.sleep(1)  # O(1)
        self._tmux("send-keys", "Enter")  # O(1)

    def wait_marker(self, line: str, min_seconds: int = 0, timeout: int = 240) -> bool:  # O(t)
        begin = time.time()  # O(1)
        while time.time() - begin < timeout:  # O(t)
            lines = self.marker_path.read_text().splitlines() if self.marker_path.exists() else []  # O(n)
            if line in (x.strip() for x in lines) and time.time() - begin >= min_seconds:  # O(n)
                return True  # O(1)
            time.sleep(2)  # O(1)
        return False  # O(1)

    def pane(self) -> str:  # O(1)
        return self._tmux("capture-pane", "-p").stdout  # O(1)

    def debug_log(self) -> str:  # O(n)
        return self.debug_path.read_text(errors="replace") if self.debug_path.exists() else ""  # O(n)

    def close(self) -> None:  # O(1)
        try:  # O(1)
            self._tmux("send-keys", "C-c")  # O(1)
            self._tmux("send-keys", "C-c")  # O(1)
        except Exception:  # O(1)
            pass  # O(1)
        finally:  # O(1)
            self._tmux("kill-server")  # O(1)

    def __enter__(self) -> "TuiSession":  # O(t)
        try:  # O(1)
            self.start()  # O(t)
        except BaseException:  # O(1)
            self.close()  # O(1)
            raise  # O(1)
        return self  # O(1)

    def __exit__(self, *exc) -> None:  # O(1)
        self.close()  # O(1)
