"""probes/dismiss.py: dismissal records for probe_run results (#417)."""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
DISMISS = ROOT / "skills" / "subagent-driven-development" / "probes" / "dismiss.py"

HEADER = ('"""Generated by probe_run.py: deep crash (crash|BadInput|src/a.py:12).\n'
          'Minimal input shrunk from 900; probe deep/nested_list. Fix the code, keep this test."""\n')

R = {"failures": [{"group_id": "g1", "key": "crash|BadInput|src/a.py:12", "category": "deep", "kind": "crash",
                   "probes": ["deep/nested_list", "deep/long_string"],
                   "regression_test": "tests/regression/test_probe_deep_1.py",
                   "incident": {"file": "src/a.py", "line": 12}}]}
REC_G1 = {"id": "g1", "category": "deep", "kind": "crash", "sig": "crash|BadInput|src/a.py",
          "probes": ["deep/nested_list", "deep/long_string"], "test": "tests/regression/test_probe_deep_1.py",
          "incident": {"file": "src/a.py", "line": 12}}


@pytest.fixture(scope="module")
def d():
    spec = importlib.util.spec_from_file_location("dismiss_under_test", DISMISS)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_sig(d):
    assert d.sig("crash|BadInput|src/a.py:12") == "crash|BadInput|src/a.py"
    assert d.sig("hang|deep/call") == "hang|deep/call"


@pytest.mark.parametrize("ident", ["test_probe_deep_1", "test_probe_deep_1.py",
                                   "tests/regression/test_probe_deep_1.py"])
def test_resolve_test_name_forms(d, tmp_path, ident):
    rec = d.resolve(ident, R, tmp_path)
    assert rec == {**REC_G1, "id": "test_probe_deep_1"}


def test_resolve_group_and_probe_id(d, tmp_path):
    assert d.resolve("g1", R, tmp_path) == REC_G1
    assert d.resolve("deep/long_string", R, tmp_path) == {**REC_G1, "id": "deep/long_string"}
    assert d.resolve("numeric/huge", {}, tmp_path) == {
        "id": "numeric/huge", "category": "numeric", "kind": None, "sig": None,
        "probes": ["numeric/huge"], "test": None, "incident": None}


def test_resolve_unknown_is_none(d, tmp_path):
    assert d.resolve("g9", R, tmp_path) is None
    assert d.resolve("nonsense", R, tmp_path) is None


def test_resolve_from_test_header(d, tmp_path):
    reg = tmp_path / "tests" / "regression"
