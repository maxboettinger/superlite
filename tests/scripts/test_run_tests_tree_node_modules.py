def git(root, *args):
    return subprocess.run(["git", "-C", str(root), *args], check=True, capture_output=True, text=True).stdout


def spec(command=CMD, setup=""):
    return {"language": "typescript", "python": False, "isolate": True, "junit": "", "env": {},
            "setup": setup, "source": "test", "command": command}


@pytest.fixture
def repo(tmp_path, monkeypatch):
    for k in ("SUPERLITE_FLEET_ROLE", "SUPERLITE_FLEET_PARENT_DIR", "SUPERLITE_STATE_DIR"):
        monkeypatch.delenv(k, raising=False)
    git(tmp_path, "init", "-q")
    git(tmp_path, "config", "user.email", "t@t")
    git(tmp_path, "config", "user.name", "t")
    (tmp_path / ".git" / "info").mkdir(exist_ok=True)
    (tmp_path / ".git" / "info" / "exclude").write_text(".superlite/\n")
    (tmp_path / "package.json").write_text(json.dumps({"devDependencies": {"vitest": "1"}}))
    (tmp_path / ".gitignore").write_text("node_modules/\n")
    (tmp_path / "src").mkdir()
    (tmp_path / "src" / "a.test.ts").write_text("// t\n")
    (tmp_path / "plan.md").write_text(PLAN)
    (tmp_path / "node_modules").mkdir()
    (tmp_path / "node_modules" / "marker.txt").write_text("root")
    git(tmp_path, "add", ".")
    git(tmp_path, "commit", "-qm", "base")
    (tmp_path / ".superlite").mkdir(exist_ok=True)
    monkeypatch.chdir(tmp_path)
    monkeypatch.setattr(testcmd, "resolve", lambda root=".", paths=(): spec())
    return tmp_path


def tree_of(repo):
    return repo / ".superlite" / "trees" / "T1"


def test_task_tree_links_root_node_modules(repo):
    assert run_tests.main(ARGS) == 0
    link = tree_of(repo) / "node_modules"
    assert link.is_symlink()
    assert os.readlink(link) == "../../../node_modules"
    assert (tree_of(repo) / "seen.txt").read_text() == "root"


def test_second_run_keeps_link(repo):
    assert run_tests.main(ARGS) == 0
    assert run_tests.main(ARGS) == 0
    assert os.readlink(tree_of(repo) / "node_modules") == "../../../node_modules"


def test_stale_link_replaced(repo):
    assert run_tests.main(ARGS) == 0
    link = tree_of(repo) / "node_modules"
    link.unlink()
    os.symlink(str(repo / "gone"), link)
    (tree_of(repo) / "seen.txt").unlink()
    assert run_tests.main(ARGS) == 0
    assert os.readlink(link) == "../../../node_modules"
    assert (tree_of(repo) / "seen.txt").read_text() == "root"


def test_real_tree_node_modules_kept(repo):
    assert run_tests.main(ARGS) == 0
    link = tree_of(repo) / "node_modules"
    link.unlink()
    link.mkdir()
    (link / "marker.txt").write_text("tree")
    assert run_tests.main(ARGS) == 0
    assert link.is_dir() and not link.is_symlink()
    assert (tree_of(repo) / "seen.txt").read_text() == "tree"


