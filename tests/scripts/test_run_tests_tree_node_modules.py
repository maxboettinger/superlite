@pytest.mark.skipif(os.name == "nt", reason="posix symlink and sh script")
def test_link_failure_tree_guard_names_tree(repo, monkeypatch, capsys):
    (repo / "bun.lock").write_text("")
    git(repo, "add", "bun.lock")
    git(repo, "commit", "-qm", "lock")
    bindir = repo.parent / "fakebin"
    bindir.mkdir(exist_ok=True)
    npm = bindir / "npm"
    npm.write_text("#!/bin/sh\necho ran > ran.txt\n")
    npm.chmod(0o755)
    monkeypatch.setenv("PATH", f"{bindir}{os.pathsep}{os.environ['PATH']}")
    monkeypatch.setattr(testcmd, "resolve", lambda root=".", paths=(): spec("npm test"))

    def boom(*a, **k):
        raise OSError("no symlinks")
    monkeypatch.setattr(os, "symlink", boom)
    assert run_tests.main(ARGS) == 2
    text = f"node_modules missing in {repo.resolve() / '.superlite/trees/T1'}: run bun install --frozen-lockfile first"
    assert f"run_tests: {text}" in capsys.readouterr().err
    assert json.loads((repo / ".superlite/test-summary.json").read_text())["error"] == text
    log = repo / ".superlite" / "incidents.jsonl"
    body = log.read_text() if log.exists() else ""
    assert "test-failure" not in body and "no-result" not in body
    assert not (tree_of(repo) / "ran.txt").exists()


def test_trees_clean_keeps_root_node_modules(repo):
    assert run_tests.main(ARGS) == 0
    trees.clean(repo)
    assert (repo / "node_modules" / "marker.txt").read_text() == "root"


def test_usage_error_shape(tmp_path, capsys):
    a = argparse.Namespace(summary=str(tmp_path / "s.json"), run_id=None)
    assert run_tests.usage_error(a, "fast", "boom") == 2
    cap = capsys.readouterr()
    assert cap.err.strip() == "run_tests: boom"
    assert cap.out.strip() == "0 0 0 0.0"
    assert json.loads(Path(a.summary).read_text())["error"] == "boom"


@pytest.mark.skipif(os.name == "nt", reason="posix symlinks")
def test_symlink_loop_in_tree_is_replaced(repo):
    tree = repo / "tree"
    tree.mkdir()
    os.symlink("node_modules", tree / "node_modules")  # points at itself
    assert run_tests.link_node_modules(repo, tree, {"setup": ""}) is True
    assert (tree / "node_modules" / "marker.txt").read_text() == "root"
    assert (repo / "node_modules" / "marker.txt").read_text() == "root"
