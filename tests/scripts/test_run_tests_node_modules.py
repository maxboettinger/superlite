@posix
def test_background_parent_refuses(tmp_path):
    root = project(tmp_path)
    r = rt(root, "--full", "--background")
    assert r.returncode == 2
    assert "summary:" not in r.stdout
    assert not (root / ".superlite" / "test-summary.latest").exists()


def test_peer_dependencies_only_no_check(tmp_path):
    project(tmp_path, pkg={"scripts": {"test": "vitest"}, "peerDependencies": {"react": "1"}})
    assert run_tests.node_install_line(tmp_path, spec()) is None


def test_background_resolve_crash_still_starts(tmp_path, monkeypatch):
    project(tmp_path)
    monkeypatch.chdir(tmp_path)
    started = []
    monkeypatch.setattr(run_tests.testcmd, "resolve", lambda *a, **k: (_ for _ in ()).throw(RuntimeError("boom")))
    monkeypatch.setattr(run_tests, "start_background", lambda a, argv: started.append(1) or 0)
    assert run_tests.main(["--full", "--background"]) == 0
    assert started == [1]
