#!/usr/bin/env python3
"""Check one MCP server before a fleet worker gets it (#576).

`xcode` (or a `mcpbridge` command) needs the macOS desktop session; a stdio server must answer an MCP `initialize` and `tools/list`
handshake. Results are cached per run for 10 minutes. Library: check, probe. Stdlib only.
"""
# Complexity notation:
#   n = lines the server prints, d = size of the definition, c = cache entries
import hashlib  # O(1)
import json  # O(1)
import os  # O(1)
import queue  # O(1)
import shutil  # O(1)
import signal  # O(1)
import subprocess  # O(1)
import sys  # O(1)
import threading  # O(1)
import time  # O(1)
from pathlib import Path  # O(1)

import gui_session  # O(1)

CHECK_TIMEOUT_S = 15.0  # seconds one handshake may take | O(1)
CHECK_TTL_S = 600  # seconds a cached result holds | O(1)
CACHE = "mcp-check.json"  # under <sd>/fleet/ | O(1)
PROTOCOL = "2025-06-18"  # O(1)


def _read_lines(stream, q) -> None:  # reader thread: stdout lines into the queue, None at EOF | O(n)
    try:  # O(1)
        for line in stream:  # O(n)
            q.put(line)  # O(1)
    except (OSError, ValueError):  # O(1)
        pass  # O(1)
    q.put(None)  # O(1)


def _send(proc, obj: dict) -> bool:  # one JSON line to the server, False when its stdin is closed | O(d)
    try:  # O(1)
        proc.stdin.write(json.dumps(obj) + "\n")  # O(d)
        proc.stdin.flush()  # O(1)
        return True  # O(1)
    except (OSError, ValueError):  # O(1)
        return False  # O(1)


def _reply(proc, q, want: int, deadline: float) -> tuple[str, dict | None]:  # ("ok"|"eof"|"timeout", the id reply) | O(n)
    while True:  # O(n)
        left = deadline - time.monotonic()  # O(1)
        if left <= 0:  # O(1)
            return "timeout", None  # O(1)
        try:  # O(1)
            line = q.get(timeout=left)  # O(1)
        except queue.Empty:  # O(1)
            return "timeout", None  # O(1)
        if line is None:  # O(1)
            return "eof", None  # O(1)
        try:  # O(1)
            msg = json.loads(line)  # O(1)
        except ValueError:  # O(1)
            continue  # O(1)
        if isinstance(msg, dict) and msg.get("id") == want and ("result" in msg or "error" in msg):  # O(1)
            return "ok", msg  # O(1)


def _signal(proc, sig) -> None:  # signal the whole process group (POSIX), else only the child | O(1)
    try:  # O(1)
        if hasattr(os, "killpg"):  # O(1)
            os.killpg(proc.pid, sig)  # O(1)
        elif sig == signal.SIGTERM:  # O(1)
            proc.terminate()  # O(1)
        else:  # O(1)
            proc.kill()  # O(1)
    except OSError:  # O(1)
        pass  # O(1)


def _stop(proc) -> None:  # SIGTERM the group, wait 2 s, SIGKILL it; stdout is left to the daemon reader | O(1)
    _signal(proc, signal.SIGTERM)  # O(1)
    try:  # O(1)
        proc.wait(timeout=2)  # O(1)
    except subprocess.TimeoutExpired:  # O(1)
        pass  # O(1)
    _signal(proc, getattr(signal, "SIGKILL", signal.SIGTERM))  # a wrapper that exited may leave a grandchild | O(1)
    try:  # O(1)
        proc.wait(timeout=2)  # O(1)
    except subprocess.TimeoutExpired:  # O(1)
        pass  # O(1)
    try:  # O(1)
        proc.stdin.close()  # O(1)
    except (OSError, ValueError):  # O(1)
        pass  # O(1)


def _err(msg: dict) -> str:  # the message of an error reply | O(d)
    e = msg.get("error")  # O(1)
    return str(e.get("message", e)) if isinstance(e, dict) else str(e)  # O(d)


def probe(definition: dict, cwd=None, timeout: float = CHECK_TIMEOUT_S) -> str | None:  # None when the server answers tools/list, else why not | O(n)
    env = {**os.environ, **{str(k): str(v) for k, v in (definition.get("env") or {}).items()}}  # O(d)
    cmd = str(definition.get("command", ""))  # O(1)
    path = shutil.which(cmd, path=env.get("PATH")) if cmd else None  # O(path)
    if not path:  # O(1)
        return f"command {cmd} not found"  # O(1)
    args = [str(a) for a in definition.get("args") or []]  # O(d)
    try:  # O(1)
        proc = subprocess.Popen([path, *args], stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                                cwd=cwd, env=env, text=True, start_new_session=os.name != "nt")  # O(1)
    except OSError as e:  # O(1)
        return f"could not start {cmd}: {e.strerror or e}"  # O(1)
    try:  # O(1)
        q: queue.Queue = queue.Queue()  # O(1)
        threading.Thread(target=_read_lines, args=(proc.stdout, q), daemon=True).start()  # O(1)
        deadline = time.monotonic() + timeout  # O(1)
        init = {"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {
            "protocolVersion": PROTOCOL, "capabilities": {}, "clientInfo": {"name": "superlite-fleet", "version": "1"}}}  # O(1)
        _send(proc, init)  # O(1)
        for want, method in ((1, "initialize"), (2, "tools/list")):  # O(1)
            if want == 2:  # O(1)
                _send(proc, {"jsonrpc": "2.0", "method": "notifications/initialized"})  # O(1)
                _send(proc, {"jsonrpc": "2.0", "id": 2, "method": "tools/list"})  # O(1)
            state, msg = _reply(proc, q, want, deadline)  # O(n)
            if state == "timeout":  # O(1)
                return f"did not answer tools/list in {timeout:g} s"  # O(1)
            if state == "eof":  # O(1)
                try:  # O(1)
                    code = proc.wait(timeout=2)  # O(1)
                except subprocess.TimeoutExpired:  # O(1)
                    code = "?"  # O(1)
                return f"exited before answering tools/list (exit {code})"  # O(1)
            if "error" in msg:  # O(1)
                return f"{method} error: {_err(msg)}"  # O(d)
        return None  # O(1)
    finally:  # O(1)
        _stop(proc)  # O(1)


def _gui_reason(name: str, definition: dict) -> str | None:  # the xcode server needs the desktop session | O(d)
    args = [str(a) for a in definition.get("args") or []]  # O(d)
    if not (name == "xcode" or "mcpbridge" in args) or sys.platform != "darwin":  # O(d)
        return None  # O(1)
    kind = gui_session.session_kind()  # O(1)
    if kind in (None, "Aqua"):  # O(1)
        return None  # O(1)
    return f"no macOS GUI session (launchctl managername: {kind}, not Aqua)"  # O(1)


def _load(path: Path) -> dict:  # the cache, {} when missing or not a JSON object | O(c)
    try:  # O(1)
        data = json.loads(path.read_text())  # O(c)
    except (OSError, ValueError):  # O(1)
        return {}  # O(1)
    return data if isinstance(data, dict) else {}  # O(1)


def _store(path: Path, data: dict) -> None:  # atomic write, an OSError is ignored | O(c)
    try:  # O(1)
        path.parent.mkdir(parents=True, exist_ok=True)  # O(1)
        tmp = path.with_name(f"{path.name}.{os.getpid()}.tmp")  # O(1)
        tmp.write_text(json.dumps(data))  # O(c)
        os.replace(tmp, path)  # O(1)
    except OSError:  # O(1)
        pass  # O(1)


def check(name: str, definition: dict, sd=None, cwd=None) -> str | None:  # None when the server is usable, else one reason | O(n)
    if os.environ.get("SUPERLITE_MCP_CHECK") == "0":  # O(1)
        return None  # O(1)
    why = _gui_reason(name, definition)  # O(d)
    if why:  # O(1)
        return why  # O(1)
    if definition.get("url") or definition.get("type") in ("http", "sse"):  # O(1)
        return None  # O(1)
    key = name + ":" + hashlib.sha1(json.dumps(definition, sort_keys=True).encode()).hexdigest()[:12]  # O(d)
    path = Path(sd) / "fleet" / CACHE if sd else None  # O(1)
    cache = _load(path) if path else {}  # O(c)
    hit = cache.get(key)  # O(1)
    if isinstance(hit, dict) and isinstance(hit.get("at"), (int, float)) and 0 <= time.time() - hit["at"] < CHECK_TTL_S:  # O(1)
        return hit.get("why")  # O(1)
    why = probe(definition, cwd)  # O(n)
    if path:  # O(1)
        cache[key] = {"why": why, "at": time.time()}  # O(1)
        _store(path, cache)  # O(c)
    return why  # O(1)
