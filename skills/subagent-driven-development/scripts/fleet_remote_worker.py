#!/usr/bin/env python3
"""A fleet worker on a saved Herdr machine: spawn, send a brief, read the states, stop (research, final-reviewer, implementer, fixer and package-reviewer roles).

The worker runs in its own tree on the host (`fleet_remote.push`) and loads superlite from a tree of this checkout's commit
(`claude --plugin-dir`); every Herdr call for it runs inside `herdr_client.on(machine)`. Its worker record carries `machine`
and `remote` (label, tree, sd, name, plugin, project, offset, tr); stop records and transcripts are mirrored by `fleet_remote.sync`.
"""
# Complexity notation:
# w = workers, a = agents of a machine, p = path pairs, l = length of a message
import os  # O(1)
import re  # O(1)
import shlex  # O(1)
import subprocess  # O(1)
import sys  # O(1)
import time  # O(1)
from pathlib import Path  # O(1)

sys.path.insert(0, str(Path(__file__).resolve().parent))  # O(1)
import fleet  # noqa: E402 | O(1)
import fleet_io as fio  # noqa: E402 | O(1)
import fleet_remote as fr  # noqa: E402 | O(1)
import fleet_remote_account as fra  # noqa: E402 | O(1)
import fleet_report  # noqa: E402 | O(1)
import fleet_roles  # noqa: E402 | O(1)
import fleet_state as fs  # noqa: E402 | O(1)
import herdr_client as hc  # noqa: E402 | O(1)
import plan_tools as pt  # noqa: E402 | O(1)
import remote_apply as ra  # noqa: E402 | O(1)
import routing  # noqa: E402 | O(1)
import trees  # noqa: E402 | O(1)

WRITE_ROLES = ("implementer", "fixer", "package-reviewer")  # a write worker takes one task or brief; its tree comes home as a snapshot | O(1)
ROLES = ("research", "final-reviewer") + WRITE_ROLES  # O(1)
GIT_TIMEOUT_S = 30  # bound of each git call of the working-state listing | O(1)
PLUGIN_MAX_AGE_S = 86400  # an unused plugin tree is dropped only when its commit is older than this | O(1)
REMOTE_START_MS = 90000  # wait for a new remote agent to be idle before the first prompt | O(1)
REMOTE_PROMPT_MS = 60000  # wait for a remote agent to start working after a prompt | O(1)
STATUS_MSG = "timed out waiting for agent status"  # herdr's error for a first prompt whose agent never reported a status in time | O(1)
SIGNED_OUT = "account_signed_out"  # the error code of a prompt the host's account answered with a sign-in or /login line | O(1)
SNAPSHOT_MS = 30000  # the stop hook's snapshot bound: a write worker's stop record can lag this much longer | O(1)
SYNC_POLL_S = 2  # seconds between two mirror syncs of the brief-taken check (each sync is a remote read) | O(1)
SUPERLITE_ROOT = str(Path(__file__).resolve().parents[3])  # the checkout whose commit the host loads | O(1)


def _blocked(label, why):  # O(1)
    print(f"BLOCKED: fleet spawn: machine {label}: {why}")  # O(1)
    raise SystemExit(3)  # O(1)


def spawn(sd, role, tier, project, label, cfg=None, task=None, plan=None, brief=None):  # O(w + f) plus remote and herdr calls
    sd, project = Path(sd), Path(project)  # O(1)
    if role not in ROLES:  # O(1)
        raise ValueError(f"role {role} cannot run on a remote machine yet; remote roles: {', '.join(ROLES)}")  # O(1)
    why = fr.check(label)  # O(1)
    if why:  # no pane, no worker id for a machine that is down | O(1)
        _blocked(label, why)  # O(1)
    launch = fleet_roles.launch(role, tier, cfg or routing.load_cfg(), brief=bool(brief))  # a ValueError reaches the caller | O(file)
    prime = "prime-haiku.md" if launch["model"] == "haiku" else "prime.md"  # O(1)
    if launch["prime"] and not (sd / prime).is_file():  # no pane, account or worker id for a worker that cannot read its prime | O(1)
        _blocked(label, f"no {sd.resolve() / prime}; run build_prime --plan PLAN first, or pass --brief FILE for a brief-only task")  # O(1)
    wid = fs.next_id(sd)  # O(w)
    name_, write = fr.tree_name(sd, wid), role in WRITE_ROLES  # O(l)
    start_ref = f"refs/superlite/remote/{name_}/start"  # O(1)
    snap_ref = f"refs/superlite/remote/{name_}/stop"  # O(1)
    owns = None  # O(1)
    try:  # O(1)
        plugin = fr.plugin(label, SUPERLITE_ROOT)  # O(1)
        _prune(sd, label, plugin)  # O(w + trees)
        home = fr.remote_home(plugin)  # O(l)
        tree = f"{home}/.maxapp/trees/{_repo_name(project)}/{name_}"  # the project's own store, as `maxapp remote tree` names it | O(1)
        account, cdir = fra.pick(sd, label, launch["model"] or "sonnet", dict(os.environ), home)  # a SystemExit(3) prints its own BLOCKED line | O(a * e + w)
        base = trees.base_commit(project)  # O(1)
        mapped = _mapper(sd, project, tree, plugin, plan)  # O(p log p)
        blobs = {}  # O(1)
        if launch["prime"]:  # O(1)
            blobs[f".superlite/{prime}"] = mapped((sd / prime).read_bytes())  # O(b)
        if plan:  # O(1)
            blobs[f".superlite/{Path(plan).name}"] = mapped(Path(plan).read_bytes())  # O(b)
        for extra in ("test-cmd.json", "stable.json"):  # O(1)
            if (sd / extra).is_file():  # O(1)
                blobs[f".superlite/{extra}"] = mapped((sd / extra).read_bytes())  # O(b)
        if brief:  # the mapped brief rides in the start commit | O(1)
            rel = Path(brief).resolve().relative_to(project.resolve())  # ValueError: outside the project | O(1)
            blobs[rel.as_posix()] = mapped(Path(brief).read_bytes())  # O(b)
        if task and plan and role == "implementer":  # the task's own changes only | O(1)
            owns = list(pt.Plan.load(str(plan)).by_id[task].owns)  # KeyError for an unknown task | O(L)
            copy, delete = trees.own_changes(str(project), base, owns)  # O(f * o)
            files = copy + delete  # O(f)
        else:  # O(1)
            files = _working_files(project, base)  # O(f)
        start = ra.start_commit(str(project), base, files, blobs, start_ref)  # O(f + b)
        pushed = fr.push(label, str(project), name_, start, [])  # O(1)
        if pushed != tree:  # the mapped prime names the predicted tree | O(1)
            raise fr.RemoteError(f"tree of {name_} is {pushed}, expected {tree}")  # O(1)
    except (fr.RemoteError, RuntimeError, OSError, ValueError, KeyError) as e:  # a git failure or timeout is a BLOCKED line | O(1)
        _drop(label, project, sd, wid)  # O(1)
        _blocked(label, str(e) if not isinstance(e, KeyError) else f"no task {e} in the plan")  # O(1)
    name = fs.agent_name(sd, wid)  # O(1)
    argv = ["--plugin-dir", plugin] + fleet_roles.skills_read(fleet.lean_argv(launch["argv"]), plugin.rstrip("/") + "/skills")  # O(n)
    env = {**fleet.worker_env(sd, wid, launch["agent"], "", {}), **fleet_roles.env(role)}  # O(1)
    env.pop("CLAUDE_CONFIG_DIR", None)  # the host's default account unless `pick` names a folder | O(1)
    if cdir:  # O(1)
        env["CLAUDE_CONFIG_DIR"] = cdir  # O(1)
    env["SUPERLITE_STATE_DIR"] = f"{tree}/.superlite"  # O(1)
    if write:  # the stop hook snapshots a write worker's tree under this ref | O(1)
        env["SUPERLITE_REMOTE_SNAPSHOT"] = snap_ref  # O(1)
    remote = {"label": label, "tree": tree, "sd": f"{tree}/.superlite", "name": name_, "plugin": plugin, "project": str(project), "offset": 0, "tr": {},  # O(1)
              "write": write, "start": start, "snapshot_ref": snap_ref if write else None, "owns": [*owns, "tests/regression/**"] if owns is not None else None}
    record = {"name": name, "account": account, "agent": launch["agent"], "tier": tier or launch["model"], "state": "starting", "task": None, "role": role,  # O(1)
              "one_turn": launch["one_turn"], "launch": {"argv": argv, "env": env, "cwd": tree}, "machine": label, "remote": remote,
              "state_dir": str(sd / "remote" / wid)}
    try:  # O(1)
        pane = fleet.open_pane(sd, wid, tree, env, record, machine=label)  # O(w + p)
    except hc.HerdrError as e:  # O(1)
        _drop(label, project, sd, wid)  # O(1)
        fleet._blocked(sd, wid, account, f"startup: {e.message or e.code}")  # O(1)
    ask, screen = f"Read {tree}/.superlite/{prime}, then reply READY", ""  # O(1)
    try:  # O(1)
        with hc.on(label):  # O(1)
            try:  # O(1)
                fleet.start_on_shell(name, pane, argv)  # O(1)
            except hc.HerdrError as e:  # a one-turn worker may stand on the trust dialog at start | O(s)
                if e.code != "agent_not_ready" or fleet.TRUST not in hc.read_screen(name, fleet.SCREEN_ROWS):  # O(s)
                    raise  # O(1)
                fleet._accept_trust(name)  # O(1)
            hc.wait_state(name, ["idle", "done"], REMOTE_START_MS)  # O(1)
            seen = hc.read_screen(name, fleet.SCREEN_ROWS)  # O(s)
            if fra.login_screen(seen):  # O(s)
                return _signed_out(sd, wid, label, account, pane, project)  # O(1)
            if fleet._trust_open(seen):  # a one-turn worker may stand on the trust dialog | O(s)
                fleet._accept_trust(name)  # O(1)
            if launch["prime"]:  # an implementer with a plan reads its prime first | O(1)
                hc.prompt(name, ask, ["idle", "done", "blocked"], 180000)  # O(1)
                screen = hc.read_screen(name, fleet.SCREEN_ROWS)  # O(s)
                if fra.login_screen(screen):  # O(s)
                    return _signed_out(sd, wid, label, account, pane, project)  # O(1)
            fleet._store_session(sd, wid, name)  # O(w)
    except hc.HerdrError as e:  # O(1)
        fs.set_state(sd, wid, "blocked")  # O(w)
        with hc.on(label), _quiet():  # O(1)
            hc.close_pane(pane)  # O(1)
        _drop(label, project, sd, wid)  # O(1)
        fleet._blocked(sd, wid, account, f"startup: {e.code}: {e.message}")  # O(1)
    fs.set_state(sd, wid, "ready")  # O(w)
    fleet._launch_line(sd, wid, launch["agent"], launch["model"], account, pane)  # O(1)
    print(f"{wid} account={account} pane={pane} agent={launch['agent']} role={role} machine={label}")  # O(1)
    return {"id": wid, "account": account, "pane_id": pane, "agent": launch["agent"], "model": launch["model"], "role": role, "machine": label}  # O(1)


def _foreign_agents(sd, label):  # names of live `sl-` agents on the host that are not this run's workers; other runs share the host's plugin store | O(w + a)
    own = {fs.name_of(sd, wid, w) for wid, w in fs.workers(sd).items() if w.get("machine") == label and w.get("state") != "stopped"}  # O(w)
    with hc.on(label):  # O(1)
        listed = hc.agent_states()  # O(a)
    return sorted(n for n in listed if n.startswith("sl-") and n not in own)  # O(a log a)


def _prune(sd, label, plugin):  # drop the host's old plugin trees, only on a host with no other superlite agent; a failure is one stderr line | O(w + a + trees)
    try:  # O(1)
        if _foreign_agents(sd, label):  # another run may still use an older plugin tree: skip this time, no line | O(w + a)
            return  # O(1)
        keep = {plugin} | {(v.get("remote") or {}).get("plugin") for v in fs.workers(sd).values() if v.get("state") != "stopped"}  # O(w)
        for t in fr.trees(label, SUPERLITE_ROOT):  # O(trees)
            if str(t.get("name", "")).startswith("plugin/") and t.get("path") not in keep and _stale(t.get("base")):  # O(1)
                fr.drop(label, SUPERLITE_ROOT, t["name"])  # O(1)
    except (fr.RemoteError, hc.HerdrError, OSError, ValueError) as e:  # O(1)
        print(f"plugin trees kept on {label}: {e}", file=sys.stderr)  # O(1)


def _committed(base):  # committer time of a commit in the superlite root; None when unknown | O(1)
    if not base:  # O(1)
        return None  # O(1)
    try:  # O(1)
        out = subprocess.run(["git", "-C", SUPERLITE_ROOT, "show", "-s", "--format=%ct", str(base)], capture_output=True, text=True, timeout=GIT_TIMEOUT_S)  # O(1)
        return int(out.stdout.strip()) if out.returncode == 0 else None  # O(1)
    except (OSError, ValueError, subprocess.TimeoutExpired):  # O(1)
        return None  # O(1)


def _stale(base):  # True when the tree's base commit is known and older than PLUGIN_MAX_AGE_S; other runs may still use a younger one | O(1)
    ct = _committed(base)  # O(1)
    return ct is not None and time.time() - ct > PLUGIN_MAX_AGE_S  # O(1)


def _prompt(name, msg, account=""):  # fio._prompt with the remote wait: a new remote agent takes longer to start working | O(len msg)
    try:  # O(1)
        hc.prompt(name, msg, ["working"], REMOTE_PROMPT_MS)  # O(len msg)
        return  # O(1)
    except hc.HerdrError as e:  # O(1)
        _login_after_prompt(name, account)  # O(s)
        text = str(getattr(e, "message", "") or e)  # O(len)
        if getattr(e, "code", "") == fio.STALLED:  # O(1)
            pass  # O(1)
        elif fio.SLOW_MSG in text:  # O(len)
            try:  # O(1)
                state = hc.agent_state(name)  # O(1)
            except hc.HerdrError:  # O(1)
                state = None  # O(1)
            if state == "working":  # the prompt landed | O(1)
                return  # O(1)
        elif getattr(e, "code", "") == "timeout" or STATUS_MSG in text:  # the first prompt of a fresh host agent: resend only an idle agent with an empty prompt (#931) | O(len)
            if not _status_resend_ok(name, msg):  # O(s)
                if _state_of(name) == "working":  # the prompt landed late | O(1)
                    return  # O(1)
                raise  # O(1)
        else:  # O(1)
            raise  # O(1)
    hc.prompt(name, msg, ["working"], REMOTE_PROMPT_MS)  # resent once; a second failure propagates | O(len msg)


def _state_of(name):  # the agent state, None when unreadable | O(1)
    try:  # O(1)
        return hc.agent_state(name)  # O(1)
    except hc.HerdrError:  # O(1)
        return None  # O(1)


def _status_resend_ok(name, msg):  # idle or done, and the first 40 characters of the prompt's first line are not on the screen | O(s)
    if _state_of(name) not in ("idle", "done"):  # O(1)
        return False  # O(1)
    try:  # O(1)
        screen = hc.read_screen(name, fleet.SCREEN_ROWS)  # O(s)
    except hc.HerdrError:  # O(1)
        return False  # O(1)
    first = (msg.strip().splitlines() or [""])[0][:40]  # O(l)
    return not first or first not in screen  # O(s)


def _login_after_prompt(name, account=""):  # an account signed out on the host starts fine and answers the first prompt with a /login line: a resend cannot help | O(s)
    try:  # O(1)
        screen = hc.read_screen(name, fleet.SCREEN_ROWS)  # O(s)
    except hc.HerdrError:  # an unreadable screen leaves the caller's own handling | O(1)
        return  # O(1)
    if fra.login_screen(screen):  # O(s)
        who = f"account {account.split('@')[0]} is not signed in on {account.split('@')[1]}" if "@" in account else "the account is signed out on this machine"  # O(1)
        raise hc.HerdrError(SIGNED_OUT, f"{who}; run /login for it there")  # O(1)


def _signed_out(sd, wid, label, account, pane, project):  # the pane closes, the tree goes, the spawn is BLOCKED | O(1)
    fs.set_state(sd, wid, "blocked")  # O(w)
    with _quiet():  # O(1)
        hc.close_pane(pane)  # O(1)
    _drop(label, project, sd, wid)  # O(1)
    _blocked(label, f"account {account.split('@')[0]} is not signed in on {label}")  # O(1)


def _mapper(sd, project, tree, plugin, plan):  # bytes -> bytes: every local path of the run names its host copy | O(p log p)
    pairs = [(str(project), tree), (str(project.resolve()), tree), (SUPERLITE_ROOT, plugin)]  # O(1)
    sdr = Path(sd).resolve()  # O(1)
    if sdr != project.resolve() / ".superlite":  # an sd outside the project maps to the host's state dir | O(1)
        pairs.append((str(sdr), f"{tree}/.superlite"))  # O(1)
    if plan:  # O(1)
        pairs += [(str(Path(plan).resolve()), f"{tree}/.superlite/{Path(plan).name}"), (str(plan), f"{tree}/.superlite/{Path(plan).name}")]  # O(1)
    text = fr.mapper(list(dict.fromkeys(pairs)))  # O(p log p)
    return lambda data: text(data.decode("utf-8", "surrogateescape")).encode("utf-8", "surrogateescape")  # O(l)


def _git_lines(project, *args):  # NUL-separated git output as a list, bounded by a timeout | O(output)
    try:  # O(1)
        p = subprocess.run(["git", "-C", str(project), *args], capture_output=True, timeout=GIT_TIMEOUT_S)  # O(output)
    except subprocess.TimeoutExpired:  # O(1)
        raise fr.RemoteError(f"git {args[0]} in {project} timed out after {GIT_TIMEOUT_S} s") from None  # O(1)
    except OSError as e:  # O(1)
        raise fr.RemoteError(f"git {args[0]} in {project}: {e}") from None  # O(1)
    if p.returncode:  # O(1)
        raise fr.RemoteError(f"git {args[0]} in {project} failed: {p.stderr.decode('utf-8', 'replace').strip()}")  # O(1)
    return [x for x in p.stdout.decode("utf-8", "replace").split("\0") if x]  # O(output)


def _repo_name(project):  # the repository name max-core's remote_tree derives from the git common dir | O(1)
    d = _git_lines(project, "rev-parse", "--git-common-dir")[0].rstrip("\n")  # O(1)
    d = os.path.normpath(os.path.join(str(project), d)).rstrip("/")  # absolute and normalised | O(1)
    base = os.path.basename(d)  # O(1)
    if base == ".git":  # O(1)
        base = os.path.basename(os.path.dirname(d))  # O(1)
    elif base.endswith(".git"):  # O(1)
        base = base[:-4]  # O(1)
    base = re.sub(r"[^A-Za-z0-9._]", "-", base)  # O(1)
    if not base:  # O(1)
        return "repo"  # O(1)
    return "repo" + base if base[0] in "-." else base  # O(1)


def _working_files(project, base):  # the run's uncommitted state, as paths relative to the project: files changed since base and untracked ones | O(f)
    names = _git_lines(project, "diff", "--name-only", "-z", "--relative", base) + _git_lines(project, "ls-files", "-z", "--others", "--exclude-standard")  # O(f)
    return [n for n in dict.fromkeys(names) if not n.startswith(".superlite/")]  # a deleted file is removed in the start commit  # O(f)


def _drop(label, project, sd, wid):  # the tree of a worker that never started goes; a host that cannot be reached keeps it | O(1)
    try:  # O(1)
        fr.drop(label, str(project), fr.tree_name(sd, wid))  # O(1)
    except fr.RemoteError:  # O(1)
        pass  # O(1)


class _quiet:  # swallow a HerdrError of a cleanup call | O(1)
    def __enter__(self):  # O(1)
        return self  # O(1)

    def __exit__(self, et, ev, tb):  # O(1)
        return et is not None and issubclass(et, hc.HerdrError)  # O(1)


def _took(sd, wid, name, sent_ms, write=False):  # False when the pane went idle after the send with no turn of its own; a failed wait counts as taken | O(SETTLE_MS / SYNC_POLL_S * (m + w))
    try:  # O(1)
        hc.wait_state(name, ["idle", "done"], fio.TOOK_MS)  # O(1)
    except hc.HerdrError:  # a timeout means it is still working | O(1)
        return True  # O(1)
    end = fio.now_ms() + fio.SETTLE_MS + (SNAPSHOT_MS if write else 0)  # O(1)
    while True:  # O(SETTLE_MS / SYNC_POLL_S)
        try:  # O(1)
            fr.sync(sd, wid)  # O(m + B)
        except Exception:  # nothing new mirrored | O(1)
            pass  # O(1)
        if fio.latest_stop(sd, wid, sent_ms) is not None:  # O(m + w)
            return True  # O(1)
        if fio.now_ms() >= end:  # O(1)
            return False  # O(1)
        fio.sleep(SYNC_POLL_S)  # O(1)


def send_brief(sd, wid, brief, label=""):  # O(w + l) plus remote and herdr calls
    sd = Path(sd)  # O(1)
    w = fs.load(sd)["workers"][wid]  # KeyError for an unknown worker | O(w)
    rec, role = w["remote"], w.get("role") or "research"  # O(1)
    project = Path(rec.get("project") or fleet.state.git_root(sd) or sd.parent).resolve()  # O(d)
    path = Path(brief).resolve()  # O(1)
    if not path.is_file():  # O(1)
        raise FileNotFoundError(str(brief))  # O(1)
    try:  # O(1)
        path.relative_to(project)  # O(1)
    except ValueError:  # O(1)
        raise OSError(f"brief {brief} must be inside {project} for a remote worker") from None  # O(1)
    pairs = [(str(project), rec["tree"])]  # O(1)
    with_sd = sd.resolve()  # O(1)
    if with_sd != project / ".superlite":  # an sd outside the project maps to the remote state dir too | O(1)
        pairs.append((str(with_sd), rec["sd"]))  # O(1)
    home = (with_sd if with_sd.is_relative_to(project) else project / ".superlite") / "remote" / wid / "briefs"  # the mapped copies stay inside the project | O(1)
    sources = [path]  # O(1)
    if path.name == "review-packet.md" and path.with_name("review-packet-tests.md").is_file():  # the packet's tests ride along | O(1)
        sources.append(path.with_name("review-packet-tests.md"))  # O(1)
    copies = {src: home / src.name for src in sources}  # O(1)
    pairs += [(str(src), f"{rec['tree']}/{dst.relative_to(project).as_posix()}") for src, dst in copies.items()]  # the prompt and the packet name the remote copies | O(1)
    mapped = fr.mapper(pairs)  # O(p log p)
    home.mkdir(parents=True, exist_ok=True)  # O(1)
    for src, dst in copies.items():  # the text a remote worker opens names remote paths only | O(1)
        dst.write_text(mapped(src.read_text(encoding="utf-8", errors="surrogateescape")), encoding="utf-8", errors="surrogateescape")  # O(l)
    try:  # O(1)
        fr.push(rec["label"], str(project), rec["name"], None, [str(dst.relative_to(project)) for dst in copies.values()])  # O(files)
    except fr.RemoteError as e:  # O(1)
        raise OSError(str(e)) from None  # O(1)
    msg = mapped(fleet_report.brief_message(role, str(path)))  # O(l)
    label = label or path.stem  # O(1)
    sent = fio.now_ms()  # O(1)
    name = fs.name_of(sd, wid, w)  # O(1)
    first = bool(w.get("one_turn")) and not w.get("sent")  # O(1)
    with hc.on(rec["label"]):  # O(1)
        _prompt(name, msg, w.get("account") or "")  # O(l)
        if first and not _took(sd, wid, name, sent, bool(rec.get("write"))):  # O(SETTLE_MS)
            print(f"{wid}: brief not taken (the pane went idle with no turn); resending once", file=sys.stderr)  # O(1)
            sent = fio.now_ms()  # O(1)
            _prompt(name, msg, w.get("account") or "")  # O(l)
            if not _took(sd, wid, name, sent, bool(rec.get("write"))):  # O(SETTLE_MS)
                raise hc.HerdrError("brief_not_taken", "brief not taken after one resend")  # O(1)
        fio._busy(sd, wid, label, sent, str(path))  # O(w)
        fio.pane_label(sd, wid, fio.pane_title(sd, wid, label))  # O(w)
    print(f"{wid} {label} sent")  # O(1)
    return label  # O(1)


def states(sd, sync=True):  # O(w + a) plus herdr calls; sync=False lists without mirroring stop records (#996)
    sd = Path(sd)  # O(1)
    live = {k: v for k, v in fs.workers(sd).items() if v.get("machine") and v.get("state") != "stopped"}  # O(w)
    for wid, w in live.items():  # a busy worker's stop records are mirrored before its state is read | O(w)
        if sync and w.get("state") == "busy":  # O(1)
            fr.sync(sd, wid)  # O(m + B)
    out = {}  # O(1)
    for m in sorted({v["machine"] for v in live.values()}):  # O(w)
        try:  # O(1)
            with hc.on(m):  # O(1)
                listed = hc.agent_states()  # O(a)
        except hc.HerdrError:  # an unreachable machine is unknown, never dead | O(1)
            listed = None  # O(1)
        for wid, w in live.items():  # O(w)
            if w["machine"] != m:  # O(1)
                continue  # O(1)
            name = fs.name_of(sd, wid, w)  # O(1)
            if listed is None:  # O(1)
                out[name] = None  # O(1)
            elif name in listed:  # O(1)
                out[name] = listed[name]  # O(1)
    return out  # O(w)


def stop(sd, wid):  # O(1) plus remote and herdr calls
    sd = Path(sd)  # O(1)
    w = fs.load(sd)["workers"][wid]  # KeyError for an unknown worker | O(w)
    rec, was = w["remote"], w.get("state")  # O(1)
    fr.sync(sd, wid)  # the last stop record and transcript stay on this machine | O(m + B)
    with hc.on(rec["label"]):  # O(1)
        with _quiet():  # O(1)
            hc.exit_agent(fs.name_of(sd, wid, w))  # O(1)
        with _quiet():  # O(1)
            hc.close_pane(w["pane_id"])  # O(1)
    fs.set_state(sd, wid, "stopped")  # O(w)
    if was != "stopped":  # O(1)
        import fleet  # noqa: PLC0415 | O(1) lazy
        fleet._tel_worker_stop(sd, w, "STOPPED")  # O(1)
    try:  # O(1)
        fr.drop(rec["label"], rec.get("project") or str(sd.resolve().parent), rec["name"])  # O(1)
    except fr.RemoteError as e:  # O(1)
        print(f"{wid} tree kept on {rec['label']}: {e}", file=sys.stderr)  # O(1)


def send_task(sd, wid, plan, tasks, sl_path):  # O(w + n + k*s) plus herdr calls
    sd = Path(sd)  # O(1)
    w = fs.load(sd)["workers"][wid]  # KeyError for an unknown worker | O(w)
    rec, project = w["remote"], Path(w["remote"]["project"])  # O(1)
    mapped = _mapper(sd, project, rec["tree"], rec["plugin"], plan)  # O(p log p)
    msg = mapped(fio.task_message(plan, tasks, sl_path, SUPERLITE_ROOT, w.get("tier", "sonnet")).encode("utf-8", "surrogateescape")).decode("utf-8", "surrogateescape")  # O(n + k*s)
    label, sent = ",".join(tasks), fio.now_ms()  # O(k)
    with hc.on(rec["label"]):  # O(1)
        _prompt(fs.name_of(sd, wid, w), msg, w.get("account") or "")  # O(l)
        fio._busy(sd, wid, label, sent)  # O(w)
        fio.pane_label(sd, wid, fio.pane_title(sd, wid, label))  # O(w)
    print(f"{wid} {label} sent")  # O(1)


def run_script(label, cwd, script, out, title):  # a Herdr workspace on the host runs `script` in cwd under sh; output and a final "exit N" line go to out; returns the workspace id | O(1)
    q = shlex.quote  # O(1)
    d = os.path.dirname(out) or "."  # O(1)
    full = f'mkdir -p {q(d)}; ( cd {q(cwd)} && {script} ) > {q(out + ".tmp")} 2>&1; echo "exit $?" >> {q(out + ".tmp")}; mv {q(out + ".tmp")} {q(out)}'  # a subshell: an `exit` of the script still leaves the exit line | O(1)
    with hc.on(label):  # O(1)
        ws, pane = hc.create_workspace(title, cwd, {})  # O(1)
        try:  # O(1)
            hc.run_in_pane(pane, f"sh -c {q(full)}")  # O(1)
        except hc.HerdrError:  # the caller never got the workspace id: close it here | O(1)
            with _quiet():  # O(1)
                hc.close_workspace(ws)  # O(1)
            raise  # O(1)
    return ws  # O(1)


def script_result(label, out):  # (exit code, output) once the script ended, None while out is absent or partial; a RemoteError propagates | O(B)
    parts, offset = [], 0  # O(1)
    while True:  # fr.read returns one chunk per offset: read until an empty chunk | O(B / chunk)
        data = fr.read(label, out, offset)  # O(chunk)
        if not data:  # O(1)
            break  # O(1)
        parts.append(data)  # O(1)
        offset += len(data)  # O(1)
    text = b"".join(parts).decode("utf-8", errors="replace").rstrip("\n")  # O(B)
    lines = text.split("\n")  # O(B)
    m = re.fullmatch(r"exit (\d+)", lines[-1]) if text else None  # O(1)
    if not m:  # O(1)
        return None  # O(1)
    return int(m.group(1)), "\n".join(lines[:-1])  # O(B)


def close_script(label, ws):  # close the script's workspace; a HerdrError is swallowed | O(1)
    with hc.on(label), _quiet():  # O(1)
        hc.close_workspace(ws)  # O(1)
