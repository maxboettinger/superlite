#!/usr/bin/env python3
"""Coordinator guard judge: names the project files a Bash or PowerShell command writes and applies the path policy.

Library: judge(command, cwd, project, mode) -> Verdict | None (None: the command is allowed).
CLI: `python3 -I guard_judge.py --mode idle|active|human --project DIR --sd STATE_DIR` reads the hook JSON on stdin, prints
the block message on stderr and exits 2 on a block; every other outcome, an internal error included, exits 0 (fail open,
after a `guard-error` incident); a command it allows, and an internal error, also print
`guard: ok [$SUPERLITE_GUARD_NONCE]` on stdout, which the hook requires before it trusts an exit 0. A NUL in a path or a
spent step or time budget makes the command unknown. Stdlib only.

The walk: `guard_lex.split` gives one Segment per simple command. A directory state (a small set of the directories the
shell may sit in) follows `cd`, `pushd`, `popd`, `cd -` through `&&`/`||` chains; a subshell, a substitution, `bash -c`
and a pipeline get a copy, `eval` and `source /dev/stdin` the shell's own state. Wrappers (env, sudo, nice, timeout,
command, exec, nohup, time, xargs, find -exec) are unwrapped. Targets come from `guard_files` and `guard_tools` and are
resolved against each possible directory, then judged by the path policy.
A readable `for NAME in WORDS; do ...; done` is walked once per word with NAME bound to it; the variable of every other
`for` or `select` loop is unknown. A block on an unknown target names the word the guard could not resolve.
A block's or group's heredoc, here-string or pipe reaches every command inside it (`done <<EOF`, `{ ...; } <<EOF`).
A variable's value is used only when bash would not split it (default IFS or the IFS the command sets) and a value with a
glob is judged as a glob in every mode; `~+`, `~-` and `~` follow PWD, OLDPWD and HOME, `~user` is unknown, and PWD is the
directory the current command runs in.
`rm -r` and `rmdir` also pass a folder that holds only untracked, unowned single-link files; every block prints a `Refused command:` line naming the innermost command it came from.
`NAME=(words)` is an array assignment: its words run nothing, its substitutions and redirects are judged, NAME is unknown.
A loop is walked again while its variables change (still changing after MAX_DIRS rounds: those variables are unknown), and
a name first assigned in a block or after `&&`/`||` is one possible value, not the value, once that block or chain ends;
the other possible value is the value before the command (unset, so empty, unless the environment holds the name).
`$TMPDIR` reads the hook's environment.
From an unknown shell directory a relative path under `.superlite/` passes (not after an unknown `$VAR/`).
A function definition is the literal `function` command word or a one-word `NAME` segment the text defines with `NAME() {`, so prose in a heredoc body is none.
"""
