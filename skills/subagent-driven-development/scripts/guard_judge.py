@dataclass
class Verdict:  # O(1)
    rel: str  # project-relative path, "." for the whole tree, "?" for an unknown target  | O(1)
    abs: str  # absolute path, same exceptions | O(1)
    kind: str  # "protected" | "human" | "code" | O(1)


class _Ctx:  # O(p)
    def __init__(self, command, project, mode):  # O(n + p)
        self.mode = mode  # O(1)
        self.enforce = mode in ("active", "human")  # O(1)
        self.projn = _clean(_winpath(project))  # O(p)
        self.projreal = os.path.realpath(self.projn)  # O(p)
        self.text = command  # O(1)
        low = command.lower()  # O(n)
        self.mentions = any(x in low for x in NAMES)  # a protected name in the text | O(n)
        self.kind = "human" if mode == "human" else "code"  # O(1)
        self.home = os.environ.get("HOME") or os.path.expanduser("~")  # O(1)
        self.cdpath = bool(os.environ.get("CDPATH")) or "cdpath" in low  # CDPATH may send a relative cd elsewhere | O(n)
        self.steps = 0  # O(1)
        self.deadline = time.monotonic() + MAX_SECONDS  # O(1)
        cache = os.environ.get("SUPERLITE_CACHE_DIR") or os.path.join(  # O(p)
            os.environ.get("XDG_CACHE_HOME") or os.path.join(self.home, ".cache"), "superlite")  # O(p)
        dirs = {cache, os.path.join(self.home, ".cache", "superlite")}  # the folder of the Python cache the hook trusts | O(1)
        dirs = {_clean(_winpath(d)) for d in dirs if "\0" not in d}  # O(p)
        self.cache_dirs = {x.lower() for d in dirs for x in (d, os.path.realpath(d))}  # as written and resolved | O(p)
        self.caches = {d.rstrip("/") + "/python" for d in self.cache_dirs}  # protected in every mode | O(1)


class _Unknown(Exception):  # O(1)
    """The command cannot be judged (a NUL in a path, the step or time budget spent): the whole command is unknown."""


def _tick(ctx):  # O(1) | one step of the walk; past the budget the whole command is unknown
    ctx.steps += 1  # O(1)
    if ctx.steps > MAX_STEPS or time.monotonic() > ctx.deadline:  # O(1)
        raise _Unknown("budget")  # O(1)


def _real(p):  # O(p) syscalls | os.path.realpath; a path the OS cannot take (a NUL in it) makes the command unknown
    try:  # O(1)
        return os.path.realpath(p)  # O(p)
    except ValueError:  # O(1)
        raise _Unknown("path") from None  # O(1)


class _State:  # O(1)
    """The shell: possible directories, previous directories, pushd stack, variables, dirs made by `mkdir -p`."""
    def __init__(self, dirs):  # O(1)
        self.dirs, self.old, self.stack, self.vars, self.made = tuple(dirs), tuple(dirs), [], {}, set()  # O(1)
        self.shared = {"disturbed": False, "written": set(), "scripts": {}}  # paths written so far; scripts made by heredoc | O(1)
        self.cond = False  # O(1)
        self.nested = False  # a shell's -c body: its cd lands where the guard cannot follow (the old guard's rule) | O(1)
        self.multi = {}  # variable -> its earlier values in this command (each is judged too) | O(1)

    def fork(self, dirs):  # O(v)
        s = _State(dirs)  # O(1)
        s.old, s.stack, s.vars, s.made = self.old, list(self.stack), dict(self.vars), set(self.made)  # O(v)
        s.multi = {k: list(v) for k, v in self.multi.items()}  # O(v)
        s.shared, s.cond, s.nested = self.shared, self.cond, self.nested  # O(1)
        return s  # O(1)


class _Cmd:  # O(1)
    """One simple command as walked: its segment, the directories it runs in, and the directories it leaves."""
    def __init__(self, seg, inn, persist, piped, docs, cond):  # O(1)
        self.seg, self.inn, self.persist, self.piped, self.docs, self.cond = seg, inn, persist, piped, docs, cond  # O(1)
        self.ok = self.fail = inn  # directories after the command succeeds / fails | O(1)


def _winpath(p):  # O(p)
    m = re.match(r"^([A-Za-z]):[\\/](.*)$", p)  # O(p)
    return "/" + m.group(1).lower() + "/" + m.group(2).replace("\\", "/") if m else p  # O(p)


def _clean(p):  # O(p) | lexically normalised, one leading slash
    n = os.path.normpath(p)  # O(p)
    return "/" + n.lstrip("/") if n.startswith("/") else n  # O(p)


def _union(*sets):  # O(d) | ordered union, (None,) when too many
    out = []  # O(1)
    for s in sets:  # O(1)
        for d in s:  # O(d)
            if d not in out:  # O(d)
                out.append(d)  # O(1)
    return tuple(out) if len(out) <= MAX_DIRS else (None,)  # O(1)


def _base(w):  # O(p) | command name: no folder, no .exe
    b = w.replace("\\", "/").rsplit("/", 1)[-1]  # O(p)
    return b[:-4] if b.lower().endswith(".exe") else b  # O(1)


def _unknown(ctx):  # O(1) | verdict for a target the guard cannot name; next to a protected name it may be that file
    if ctx.mentions:  # O(1)
        return Verdict("?", "?", "protected")  # O(1)
    return Verdict("?", "?", ctx.kind) if ctx.enforce else None  # O(1)


def _allowed(rel, mode):  # O(patterns) | may the coordinator write the project-relative path?
    return any(fnmatchcase(rel, pat) for pat in (HUMAN_OK if mode == "human" else ACTIVE_OK))  # O(patterns * p)


def _wt_rel(rel, projreal):  # O(depth) | the path below the deepest linked worktree root it lies in, or None
    r, pre, wrel = rel, "", None  # O(1)
    while "/" in r:  # O(depth)
        head, r = r.split("/", 1)  # O(p)
        pre = pre + "/" + head if pre else head  # O(p)
        gitf = os.path.join(projreal, pre, ".git")  # O(p)
        if not os.path.isfile(gitf):  # O(1)
            continue  # O(1)
        try:  # O(1)
            with open(gitf, encoding="utf-8", errors="replace") as f:  # O(1)
                line = f.readline()  # O(1)
        except OSError:  # O(1)
            continue  # O(1)
        if re.match(r"^gitdir:.*/worktrees/[^/]+$", line.strip().replace("\\", "/").rstrip("/")):  # a submodule's points into modules/ | O(p)
            wrel = r  # O(1)
    return wrel  # O(1)


def _rel(real, projreal):  # O(p) | project-relative (case-insensitive prefix), "" for the root, None outside
    a, b = real.lower(), projreal.lower()  # O(p)
    if a == b:  # O(p)
        return ""  # O(1)
    return real[len(projreal) + 1:] if a.startswith(b.rstrip("/") + "/") else None  # O(p)


def _isdir(p, base):  # O(1) | is p an existing folder from base?
    try:  # O(1)
        full = p if p.startswith("/") else (base + "/" + p if base else None)  # O(p)
        return full is not None and os.path.isdir(full)  # O(1)
    except (OSError, ValueError):  # O(1)
        return False  # O(1)


def _hardlinked(real):  # O(1) | an existing regular file with more than one name
    try:  # O(1)
        st = os.stat(real)  # O(1)
    except (OSError, ValueError):  # O(1)
        return False  # O(1)
    return stat.S_ISREG(st.st_mode) and st.st_nlink > 1  # O(1)


def _judge_path(path, base, ctx, name=None):  # O(p + depth) | the policy's verdict for one path from directory base
    p = _winpath(path)  # O(p)
    if p == "" or p.startswith("/dev/"):  # O(1)
        return None  # O(1)
    parts = p.replace("\\", "/").split("/")  # O(p)
    if "?" in parts:  # a path with an unknown part ("/tmp/s/?" for f"/tmp/s/{x}.json") | O(p)
        k = parts.index("?")  # O(p)
        prefix = "/".join(parts[:k]) or ("/" if p.startswith("/") else "")  # O(p)
        if not prefix or (base is None and not prefix.startswith("/")) or ".." in parts[k:]:  # O(p)
            return _unknown(ctx)  # O(1)
        real = _real(_clean(prefix if prefix.startswith("/") else base + "/" + prefix))  # O(p) syscalls
        rel = _rel(real, ctx.projreal)  # O(p)
        if real.lower() in ctx.cache_dirs:  # an unknown name in the Python cache folder may be the cache | O(p)
            return Verdict(real, real, "protected")  # O(1)
        if rel is None:  # outside: allowed unless the folder holds the project, where the unknown part may lead in | O(p)
            holds = (ctx.projreal.lower() + "/").startswith(real.lower().rstrip("/") + "/")  # O(p)
            return _unknown(ctx) if holds else None  # O(1)
        if ctx.mentions:  # the unknown part may be a protected name | O(1)
            return _unknown(ctx)  # O(1)
        if rel == "" and k == len(parts) - 1:  # the project's whole tree | O(1)
            return Verdict(".", ctx.projn, ctx.kind) if ctx.enforce else None  # O(1)
    if name is not None and p not in (".", "./") and (p.endswith("/") or _isdir(p, base)):  # a folder: the file lands inside | O(p)
        if name == "?" and ctx.mode == "human":  # an unknown file in the run folder (rsync dir/, tar -C, unzip -d) may be the human gate | O(p + depth)
            folder = p.rstrip("/") or "/"  # O(p)
            fb = _real(_clean(folder if folder.startswith("/") else base + "/" + folder)) if (base is not None or folder.startswith("/")) else None  # O(p)
            fr = _rel(fb, ctx.projreal) if fb is not None else _clean(folder).lstrip("/") if base is None else None  # O(p)
            if fr is not None and fr.lower().rstrip("/") == ".superlite":  # O(p)
                return Verdict(fr + "/?", ctx.projn + "/" + fr + "/?", "protected")  # O(p)
        p = p.rstrip("/") + "/" + name  # O(p)
    elif p.endswith("/") and len(p) > 1:  # O(1)
        p = p.rstrip("/")  # O(p)
    if base is None and not p.startswith("/"):  # the shell's directory is unknown: judged from the project root, strictly | O(1)
        if p.replace("\\", "/").rsplit("/", 1)[-1].lower() in NAMES:  # O(p)
            return Verdict(p, ctx.projn + "/" + p, "protected")  # O(p)
        if not ctx.enforce:  # O(1)
            return None  # O(1)
        parts = p.split("/")  # O(p)
        if ".." in parts or not (_allowed(p, ctx.mode) and _allowed("x/" + p, ctx.mode)):  # allowed only by its prefix: not sure | O(p)
            return Verdict(p, ctx.projn + "/" + p, ctx.kind)  # O(p)
        return None  # O(1)
    full = _clean(p if p.startswith("/") else base + "/" + p)  # O(p)
    real = _real(full)  # O(p) syscalls
    if real.lower() in ctx.caches:  # the Python cache the hook trusts: a fake interpreter there would pass everything | O(p)
        return Verdict(real, real, "protected")  # O(1)
    rel = _rel(real, ctx.projreal)  # O(p)
    if rel is None:  # outside the project | O(1)
        return None  # O(1)
    absolute = ctx.projn + "/" + rel if rel else ctx.projn  # O(p)
    if rel == "":  # the project root itself: a rewrite of the whole tree | O(1)
        return Verdict(".", absolute, ctx.kind) if ctx.enforce else None  # O(1)
    if rel.lower() in PROTECTED:  # O(p)
        return Verdict(rel, absolute, "protected")  # O(1)
    if ctx.enforce and _hardlinked(real):  # a second name for a file that may be code: a write here writes there | O(1)
        return Verdict(rel, absolute, ctx.kind)  # O(1)
    wt = _wt_rel(rel, ctx.projreal) if (ctx.enforce or rel.lower().endswith(NAMES)) else None  # O(depth)
    if wt is not None and wt.lower() in PROTECTED:  # also inside a linked worktree | O(p)
        return Verdict(rel, absolute, "protected")  # O(1)
    if not ctx.enforce or _allowed(rel, ctx.mode):  # O(patterns)
        return None  # O(1)
    if wt is not None and _allowed(wt, ctx.mode):  # judged from the worktree's root | O(patterns)
        return None  # O(1)
    return Verdict(rel, absolute, ctx.kind)  # O(1)


def _expand(text, st, ctx):  # O(p + v) | ~ and the variables the guard knows; unknown ones stay as written
    if text == "~" or text.startswith("~/"):  # O(1)
        text = ctx.home + text[1:]  # O(p)

    def sub(m):  # O(1)
        name = m.group(1) or m.group(2)  # O(1)
        if name in st.vars:  # O(1)
            return m.group(0) if st.vars[name] is None else st.vars[name]  # O(1)
        if name == "CLAUDE_PROJECT_DIR":  # O(1)
            return ctx.projn  # O(1)
        if name == "PWD" and len(st.dirs) == 1 and st.dirs[0]:  # O(1)
            return st.dirs[0]  # O(1)
        return m.group(0)  # O(1)
    return VAR.sub(sub, text) if "$" in text else text  # O(p)


def _is_glob(w):  # O(p) | does the text hold a glob: `*`, `?` or `[...]`
    return "*" in w or "?" in w or ("[" in w and "]" in w[w.index("[") + 1:])  # O(p)


def _braces(w, depth=0):  # O(MAX_BRACE * p) | bash brace expansion of w; None for a sequence {a..b}, too many words or groups
    if depth > MAX_BRACE:  # O(1)
        return None  # O(1)
    i = w.find("{")  # O(p)
    while i >= 0:  # O(p)
        lvl, j, commas = 0, i, []  # O(1)
        while j < len(w):  # the matching `}` and the commas at the group's own level | O(p)
            if w[j] == "{":  # O(1)
                lvl += 1  # O(1)
            elif w[j] == "}":  # O(1)
                lvl -= 1  # O(1)
                if lvl == 0:  # O(1)
                    break  # O(1)
            elif w[j] == "," and lvl == 1:  # O(1)
                commas.append(j)  # O(1)
            j += 1  # O(1)
        if j < len(w) and commas:  # O(1)
            out = []  # O(1)
            for a, b in zip([i] + commas, commas + [j]):  # each alternative, with the rest of the word expanded too | O(alts)
                sub = _braces(w[:i] + w[a + 1:b] + w[j + 1:], depth + 1)  # O(MAX_BRACE * p)
                if sub is None:  # O(1)
                    return None  # O(1)
                out.extend(x for x in sub if x not in out)  # O(MAX_BRACE^2)
                if len(out) > MAX_BRACE:  # O(1)
                    return None  # O(1)
            return out  # O(1)
        if j < len(w) and ".." in w[i + 1:j]:  # a sequence {1..9}: words the guard does not build | O(p)
            return None  # O(1)
        i = w.find("{", i + 1)  # a group without a comma is literal | O(p)
    return [w]  # O(1)


def _loose(w):  # O(MAX_BRACE * p) | every word a brace word may reach, a comma-less `{x}` read as `x` too
    s = w  # O(1)
    while True:  # O(p) rounds
        s2 = re.sub(r"\{([^{},]*)\}", r"\1", s)  # O(p)
        if s2 == s:  # O(p)
            break  # O(1)
        s = s2  # O(1)
    out = []  # O(1)
    for x in (w, s):  # O(1)
        for a in (_braces(x) or [x.replace("{", "").replace("}", "")]):  # O(MAX_BRACE * p)
            if a not in out:  # O(MAX_BRACE)
                out.append(a)  # O(1)
    return out  # O(1)


def _flags(seg):  # O(w) | word -> its glob/brace flag ("g", "b", "u"), for the flagged words of the segment
    return {w: f for w, f in zip(seg.words, seg.globs) if f}  # O(w)


def _flag_of(t, fl):  # O(w * p) | the flag of the word a target came from ("" for a literal)
    if not fl or not any(ch in t for ch in "*?[{"):  # O(p)
        return ""  # O(1)
    if t in fl:  # O(1)
        return fl[t]  # O(1)
    return next((f for w, f in fl.items() if t in w or w in t), "")  # a target cut from a word (of=, --out=) | O(w * p)


def _glob_check(t, inn, st, ctx, name=None, protect_only=False):  # O(d * p) | a glob target, from every directory
    """Protected when the glob may match a protected file (also `orch*` from inside .superlite), in every mode; else the
    glob's part of the path is unknown ("?"): `docs/plans/*` stays in docs/plans, `*/x` may be anywhere."""
    m = re.match(r"^\$(?:\{\w+\}|\w+)/+(.+)$", t)  # `$VAR/rest`: rest judged from an unknown directory | O(p)
    if m and "$" not in m.group(1) and "`" not in m.group(1):  # O(p)
        t, inn = m.group(1), (None,)  # O(1)
    p = _winpath(t).replace("\\", "/")  # O(p)
    parts = p.split("/")  # O(p)
    k = next((i for i, x in enumerate(parts) if _is_glob(x)), None)  # O(p)
    found = None  # O(1)
    for base in inn:  # O(d)
        full = p if p.startswith("/") else (base + "/" + p if base else p)  # O(p)
        full = _clean(full) if full.startswith("/") else full  # O(p)
        comps = [x for x in full.lower().split("/") if x not in ("", ".")]  # O(p)
        fpat, dpat = (comps[-1] if comps else ""), (comps[-2] if len(comps) > 1 else None)  # O(1)
        near = dpat is None or dpat == ".." or "$" in dpat or (dpat.startswith(".") and fnmatchcase(".superlite", dpat))  # O(p)
        if near and any(fnmatchcase(nm, fpat) for nm in NAMES):  # O(p)
            return Verdict(t, full, "protected")  # O(1)
        if full.startswith("/") and any(fnmatchcase(cf, full.lower()) for cf in ctx.caches):  # O(p)
            return Verdict(t, full, "protected")  # O(1)
        if protect_only:  # O(1)
            continue  # O(1)
        q = "/".join(parts[:k] + ["?"] + parts[k + 1:]) if k is not None else p  # O(p)
        v = _judge_path(q, base, ctx, name)  # O(p + depth)
        if v is not None and (found is None or v.kind == "protected"):  # O(1)
            found = v  # O(1)
    return found  # O(1)


def _check_flagged(t, inn, st, ctx, name, flag):  # O(MAX_BRACE * d * p) | a glob or brace target
    for a in _loose(t):  # a protected file reached through a glob or brace (orch*, {orchestrator.json}): every mode | O(alts)
        v = _glob_check(a, inn, st, ctx, name, True) if _is_glob(a) else _check(a, inn, st, ctx, name)  # O(d * p)
        if v is not None and v.kind == "protected":  # O(1)
            return v  # O(1)
    alts = [t] if flag == "g" else _braces(t) if flag == "b" else None  # O(MAX_BRACE * p)
    if alts is None:  # a brace the guard cannot expand ({1..9}, a quoted part, too many words): unknown | O(1)
        return _unknown(ctx)  # O(1)
    found = None  # O(1)
    for a in alts:  # a literal brace word: each word it expands to | O(alts)
        v = _glob_check(a, inn, st, ctx, name) if _is_glob(a) else _check(a, inn, st, ctx, name)  # O(d * p)
        if v is not None and (found is None or v.kind == "protected"):  # O(1)
            found = v  # O(1)
    return found  # O(1)


def _check(t, inn, st, ctx, name=None, flag=""):  # O(d * (p + depth)) | verdict for one target from every possible directory
    t = _expand(t, st, ctx)  # O(p + v)
    if flag:  # a glob or brace word: its text is a pattern, not the file | O(alts * d * p)
        return _check_flagged(t, inn, st, ctx, name, flag)  # O(MAX_BRACE * d * p)
    m = re.match(r"^\$(?:\{\w+\}|\w+)/+(.+)$", t)  # `$VAR/rest`: rest judged from an unknown directory | O(p)
    if m and "$" not in m.group(1) and "`" not in m.group(1):  # O(p)
        t, inn = m.group(1), (None,)  # O(1)
    if t == "?" or "$" in t or "`" in t:  # not a literal: unknown | O(p)
        return _unknown(ctx)  # O(1)
    found = None  # O(1)
    for base in inn:  # O(d)
        if base is not None or t.startswith("/"):  # a later mkdir or cd into this path is not sure | O(p)
            st.shared["written"].add(_clean(_winpath(t) if t.startswith("/") else base + "/" + t))  # O(p)
        v = _judge_path(t, base, ctx, name)  # O(p + depth)
        if v is not None and (found is None or v.kind == "protected"):  # protected wins | O(1)
            found = v  # O(1)
    return found  # O(1)


def _cd_to(dirs, target, cdpath=False):  # O(d * p) | each directory after `cd target`; None when unreadable
    if target is None or "$" in target or "`" in target:  # O(p)
        return tuple(None for _ in dirs[:1]) or (None,)  # O(1)
    out = []  # O(1)
    for d in dirs:  # O(d)
        if target.startswith("/"):  # O(1)
            n = _clean(_winpath(target))  # O(p)
        elif d is None or (cdpath and not target.startswith(("./", "../"))):  # CDPATH: unknown | O(1)
            n = None  # O(1)
        else:  # O(1)
            n = _clean(d + "/" + target)  # O(p)
        if n not in out:  # O(d)
            out.append(n)  # O(1)
    return tuple(out)  # O(d)


def _skip_opts(words, i, short_vals, long_vals):  # O(w) | index after the options of a wrapper, and the values found
    found, n = {}, len(words)  # O(1)
    while i < n:  # O(w)
        x = words[i]  # O(1)
        if x == "--":  # O(1)
            return i + 1, found  # O(1)
        if x.startswith("--"):  # O(1)
            if "=" in x:  # O(1)
                found[x[2:].split("=", 1)[0]] = x.split("=", 1)[1]  # O(p)
            elif x[2:] in long_vals and i + 1 < n:  # O(1)
                found[x[2:]] = words[i + 1]  # O(1)
                i += 1  # O(1)
        elif x.startswith("-") and len(x) > 1:  # O(1)
            for j in range(1, len(x)):  # a cluster: a value option takes the rest, or the next word | O(len)
                if x[j] in short_vals:  # O(1)
                    if x[j + 1:]:  # O(1)
                        found[x[j]] = x[j + 1:]  # O(1)
                    elif i + 1 < n:  # O(1)
                        found[x[j]] = words[i + 1]  # O(1)
                        i += 1  # O(1)
                    break  # O(1)
                found.setdefault(x[j], "")  # a flag | O(1)
        elif ASSIGN.match(x) and short_vals == WRAP["env"][0]:  # env NAME=value | O(1)
            pass  # O(1)
        else:  # O(1)
            break  # O(1)
        i += 1  # O(1)
    return i, found  # O(1)


def _unwrap(words, dyn, c, st, ctx):  # O(w) | (command words, dyn, directories, xargs?, shell-on-stdin?)
    inn, xargs, sh = c.inn, False, False  # O(1)
    while words:  # O(w) per wrapper
        base = _base(words[0])  # O(p)
        if base in ("uv", "poetry", "pipenv") and words[1:2] == ["run"]:  # O(1)
            i = 2  # O(1)
            while i < len(words) and words[i].startswith("-"):  # O(w)
                i += 2 if words[i] in UV_VAL else 1  # O(1)
            words, dyn = words[i:], dyn[i:]  # O(w)
            continue  # O(1)
        if base not in WRAP:  # O(1)
            break  # O(1)
        shorts, longs = WRAP[base]  # O(1)
        i, got = _skip_opts(words, 1, shorts, longs)  # O(w)
        if base == "command" and ("v" in got or "V" in got):  # a lookup, not a run | O(1)
            return [], [], inn, xargs, sh  # O(1)
        if base == "timeout" and i < len(words):  # the DURATION | O(1)
            i += 1  # O(1)
        if base in ("sudo", "env") and ("s" in got or "i" in got or "shell" in got or "login" in got) and base == "sudo":  # O(1)
            sh = i >= len(words)  # sudo -s / -i with no command runs a shell on stdin | O(1)
        chdir = got.get("C") if base == "env" else got.get("D")  # O(1)
        chdir = got.get("chdir", chdir)  # O(1)
        if chdir is not None:  # env -C and sudo -D change the directory of the command | O(1)
            inn = _cd_to(inn, _expand(chdir, st, ctx))  # O(d * p)
        split = got.get("S", got.get("split-string"))  # env -S STRING is a command line | O(1)
        rest, rdyn = words[i:], dyn[i:]  # O(w)
        if split is not None:  # O(1)
            segs = guard_lex.split(split)  # O(p)
            if segs:  # O(1)
                rest, rdyn = list(segs[0].words) + rest, list(segs[0].dyn) + rdyn  # O(w)
        xargs = xargs or base == "xargs"  # O(1)
        words, dyn = rest, rdyn  # O(1)
    if sh and not words:  # O(1)
        words, dyn = ["sh"], [False]  # O(1)
    return words, dyn, inn, xargs, sh  # O(1)


def _walk_text(text, st, ctx, depth, force_cond=False):  # O(n) | verdict for a command line of its own
    if depth > MAX_DEPTH:  # O(1)
        return _unknown(ctx)  # O(1)
    _tick(ctx)  # O(1)
    segs = guard_lex.split(text)  # O(n)
    for seg in segs:  # a heredoc whose delimiter line is missing: its body is judged as commands too | O(s)
        for r in seg.redirects:  # O(redirects)
            if r.op in ("<<", "<<-") and not re.search(r"(?m)^\t*" + re.escape(r.target) + r"[ \t]*\r?$", text):  # O(n)
                v = _walk_docs(seg.heredocs, _Cmd(seg, st.dirs, False, False, [], False), st, ctx, depth)  # O(n)
                if v is not None:  # O(1)
                    return v  # O(1)
    func = FUNC.search(text) is not None  # O(n)
    loop = func or any(s.words[:1] in (["for"], ["while"], ["until"], ["select"]) for s in segs)  # O(s)
    # `{ ...; } && cd x`: the lexer flattens the group and drops its `&&`, so every cd may not run | O(n)
    cond = force_cond or func or re.search(r"\}\s*(&&|\|\|)", text) is not None  # O(n)
    start = st.dirs  # O(1)
    v = _walk(segs, st, ctx, depth, cond)  # O(n)
    for _ in range(MAX_DIRS):  # a loop or a function runs its body again from where the last run left the shell | O(d * n)
        if v is not None or not loop:  # O(1)
            break  # O(1)
        dirs = _union(start, st.dirs)  # O(d)
        if dirs == start:  # O(d)
            break  # O(1)
        st.dirs = start = dirs  # O(1)
        v = _walk(segs, st, ctx, depth, cond)  # O(n)
    return v  # O(n)


def _walk_docs(docs, c, st, ctx, depth, shared=False):  # O(sum of docs) | judge heredoc programs as shell text
    for doc in docs:  # O(docs)
        st2 = st.fork(c.inn)  # O(v)
        v = _walk_text(doc, st2, ctx, depth + 1)  # O(doc)
        if v is not None:  # O(1)
            return v  # O(1)
        if shared:  # the shell's own state keeps the program's cd | O(1)
            c.ok = c.fail = st2.dirs  # O(1)
            st.vars.update(st2.vars)  # O(v)
    return None  # O(1)


def _is_sl(words):  # O(w) | an sl call: `$SL`, or a script that really lies in this scripts folder (a name alone proves nothing)
    def slish(w):  # O(p)
        if w in ("$SL", "${SL}"):  # O(1)
            return True  # O(1)
        if not w.startswith("/"):  # a relative path depends on the shell's directory: not trusted | O(1)
            return False  # O(1)
        try:  # O(1)
            real = os.path.realpath(w)  # O(p) syscalls
        except ValueError:  # O(1)
            return False  # O(1)
        return real.startswith(os.path.realpath(_HERE).rstrip("/") + "/")  # O(p)
    if not words:  # O(1)
        return False  # O(1)
    if slish(words[0]):  # O(1)
        return True  # O(1)
    if _base(words[0]) in SHELLS:  # the script operand | O(1)
        for w in words[1:]:  # O(w)
            if not w.startswith("-"):  # O(1)
                return slish(w)  # O(1)
    return False  # O(1)


def _shell(words, dyn, c, st, ctx, depth):  # O(n) | a shell's -c body, stdin program or process substitution
    i, n, body, bi, has_s = 1, len(words), None, -1, False  # O(1)
    while i < n:  # O(w)
        x = words[i]  # O(1)
        if x == "--":  # O(1)
            i += 1  # O(1)
            break  # O(1)
        if x in ("-o", "+o", "-O", "+O", "--rcfile", "--init-file"):  # O(1)
            i += 2  # O(1)
        elif x.startswith(("-", "+")) and not x.startswith("--") and len(x) > 1:  # O(1)
            has_s = has_s or "s" in x[1:]  # O(1)
            if "c" in x[1:] and x[0] == "-" and i + 1 < n:  # O(1)
                body, bi = words[i + 1], i + 1  # O(1)
                i += 1  # O(1)
            elif ("o" in x[1:] or "O" in x[1:]) and i + 1 < n:  # `-euo pipefail`: the option name is no script | O(1)
                i += 1  # O(1)
            i += 1  # O(1)
        elif x.startswith("--"):  # O(1)
            i += 1  # O(1)
        else:  # O(1)
            break  # O(1)
    if body is not None:  # O(1)
        text = _expand(body, st, ctx) if dyn[bi] else body  # O(p)
        st2 = st.fork(c.inn)  # O(v)
        st2.nested = True  # O(1)
        v = _walk_text(text, st2, ctx, depth + 1)  # O(n)
        if v is None and (dyn[bi] or STDIN_READ.search(text)):  # a body that runs its stdin takes the heredocs | O(n)
            v = _walk_docs(c.docs, c, st, ctx, depth)  # O(docs)
        return v  # O(1)
    script = words[i] if i < n else None  # O(1)
    if script is not None and (script.startswith(("<(", ">("))):  # process substitution: a program the guard cannot read | O(1)
        return _unknown(ctx)  # O(1)
    if script is not None and not has_s and script not in ("/dev/stdin", "/dev/fd/0", "-"):  # a script file | O(1)
        return None  # O(1)
    if c.docs:  # O(1)
        return _walk_docs(c.docs, c, st, ctx, depth)  # O(docs)
    return _unknown(ctx) if c.piped else None  # a program piped in: unknown | O(1)


def _source_or_eval(base, words, dyn, c, st, ctx, depth):  # O(n) | eval and source/. run in the shell's own state
    if base == "eval":  # O(1)
        parts = [_expand(w, st, ctx) if d else w for w, d in zip(words[1:], dyn[1:])]  # O(w * p)
        st2 = st.fork(c.inn)  # O(v)
        v = _walk_text(" ".join(parts), st2, ctx, depth + 1)  # O(n)
        if v is not None:  # O(1)
            return v  # O(1)
        c.ok = c.fail = st2.dirs  # O(1)
        if c.persist:  # O(1)
            st.vars.update(st2.vars)  # O(v)
        if any("$" in p or "`" in p for p in parts):  # a body the guard cannot read: it may cd, and may read the heredocs | O(w * p)
            c.ok = c.fail = (None,)  # O(1)
            return _walk_docs(c.docs, c, st, ctx, depth)  # O(docs)
        return None  # O(1)
    operand = words[1] if len(words) > 1 else None  # source / . | O(1)
    if operand is not None and operand.startswith(("<(", ">(")):  # O(1)
        return _unknown(ctx)  # O(1)
    if operand in ("/dev/stdin", "/dev/fd/0") or (operand is None and c.docs):  # O(1)
        if c.docs:  # O(1)
            return _walk_docs(c.docs, c, st, ctx, depth, shared=True)  # O(docs)
        return _unknown(ctx) if c.piped else None  # O(1)
    if operand is not None and ACTIVATE.search(operand):  # O(p)
        return None  # O(1)
    c.ok = c.fail = (None,)  # a script file may cd | O(1)
    return None  # O(1)


def _cd(base, words, c, st, ctx):  # O(d * p) | the directories after cd, pushd, popd
    if not c.persist:  # a cd in a pipeline or a background job does not move the shell | O(1)
        return  # O(1)
    inn = c.inn  # O(1)
    ops = [w for w in words[1:] if w not in ("-L", "-P", "-e", "-@", "--")]  # O(w)
    new = None  # O(1)
    if base == "popd":  # O(1)
        if not st.stack:  # fails: the directory stays | O(1)
            return  # O(1)
        new = st.stack.pop()  # O(1)
    elif base == "pushd" and not ops:  # swaps with the top of the stack | O(1)
        if not st.stack:  # O(1)
            return  # O(1)
        new = st.stack.pop()  # O(1)
        st.stack.append(inn)  # O(1)
    else:  # O(1)
        if len(ops) > 1:  # more than one operand: cd fails | O(1)
            return  # O(1)
        if base == "pushd":  # O(1)
            st.stack.append(inn)  # O(1)
        if not ops:  # O(1)
            new = _cd_to(inn, ctx.home)  # O(d * p)
        elif ops[0] == "-":  # O(1)
            new = st.old  # O(1)
        else:  # O(1)
            new = _cd_to(inn, _expand(ops[0], st, ctx), ctx.cdpath)  # O(d * p)
            if _flags(c.seg).get(ops[0]):  # `cd .superl*`: a glob or brace folder the guard cannot name | O(w)
                new = (None,)  # O(1)
        if ops and (ops[0] == "-" or ".." in ops[0].split("/")) and any(  # O(d * p)
                d is None or _rel(_real(d), ctx.projreal) is None for d in inn):  # `cd ..` / `cd -` from outside | O(d * p)
            new = (None,)  # the old guard's rule: a step back from outside lands nowhere it can name | O(1)
    if st.nested or st.shared.get("void"):  # a cd in a -c body, or after a cd spelled with quotes: unknown | O(1)
        new = (None,)  # O(1)
    if any(q and w in ("cd", "pushd", "popd") for w, q in zip(c.seg.words, c.seg.quoted)):  # c''d: later cds unknown | O(w)
        st.shared["void"] = True  # the old guard could not read such a cd; parity keeps every later cd unknown | O(1)
    sure = (not c.cond and not st.shared["disturbed"]  # O(d)
            and all(d is not None and d not in st.shared["written"]  # O(d)
                    and ((os.path.isdir(d) and os.access(_real(d), os.X_OK)) or d in st.made) for d in new))  # O(d) syscalls
    missing = any(d is not None and d not in st.made and not os.path.isdir(d) for d in new)  # O(d) syscalls
    st.old = inn  # O(1)
    c.ok = _union(new, inn) if c.cond else tuple(new)  # O(d)
    c.fail = () if sure else (_union(inn, (None,)) if missing else inn)  # after `cd nope;` the old guard knew no folder | O(d)


def _mkdir(words, c, st, ctx):  # O(t) | `mkdir -p X && cd X`: the folder exists after mkdir succeeds
    flags = [w for w in words[1:] if w.startswith("-")]  # O(w)
    if not c.persist or c.seg.sep != "&&" or not any(f == "--parents" or (not f.startswith("--") and "p" in f) for f in flags):  # O(w)
        return  # O(1)
    if any(f.startswith(("-m", "--mode")) or (not f.startswith("--") and "m" in f) for f in flags):  # a mode may lock it | O(w)
        return  # O(1)
    sure = not c.cond and not st.shared["disturbed"]  # O(1)
    for w in words[1:]:  # O(w)
        if not w.startswith("-"):  # O(1)
            for d in _cd_to(c.inn, _expand(w, st, ctx)):  # O(d * p)
                if d is None:  # O(1)
                    sure = False  # O(1)
                    continue  # O(1)
                written = st.shared["written"]  # O(1)
                if any(d == x or d.startswith(x.rstrip("/") + "/") for x in written):  # a file the command wrote | O(t * p)
                    sure = False  # O(1)
                    continue  # O(1)
                while d != "/" and not os.path.exists(d):  # each missing folder up to the nearest existing ancestor | O(depth)
                    st.made.add(d)  # O(1)
                    d = os.path.dirname(d) or "/"  # O(p)
                sure = sure and os.path.isdir(d) and os.access(d, os.W_OK | os.X_OK)  # O(1) syscalls
    if sure:  # mkdir -p cannot fail here: the chain goes on | O(1)
        c.fail = ()  # O(1)


def _source_name(w, t):  # O(w) | the file name a cp/mv/ln/install of the first source would give inside folder t
    for x in w[1:]:  # O(w)
        if not x.startswith("-") and x.rstrip("/") != t.rstrip("/"):  # O(1)
            if x.endswith("/") and w[0] in ("rsync", "cp") and len(x) > 1:  # `src/` copies its contents (rsync, BSD cp): any name | O(1)
                return "?"  # O(1)
            nm = x.rstrip("/").rsplit("/", 1)[-1]  # O(p)
            return nm if nm and not any(ch in nm for ch in "$`*?[") else "?"  # O(p)
    return "?"  # O(1)


def _find(words, c, st, ctx, depth):  # O(w * d) | find -delete, -fprint and -exec over the start paths
    i, n, starts = 1, len(words), []  # O(1)
    while i < n and words[i] in ("-H", "-L", "-P"):  # O(1)
        i += 1  # O(1)
    while i < n and not (words[i].startswith("-") or words[i] in ("(", "!", ")")):  # O(w)
        starts.append(words[i])  # O(1)
        i += 1  # O(1)
    starts = starts or ["."]  # O(1)
    reach = [p.rstrip("/") + "/" + v if p.rstrip("/") else "/" + v for p in starts for v in FIND_VARIANTS]  # O(w)
    fl = _flags(c.seg)  # O(w)
    j = i  # O(1)
    while j < n:  # O(w)
        tok = words[j]  # O(1)
        if tok == "-delete":  # O(1)
            for t in reach:  # O(w)
                v = _check(t, c.inn, st, ctx, None, _flag_of(t, fl))  # O(d * p)
                if v is not None:  # O(1)
                    return v  # O(1)
        elif tok in ("-fprint", "-fprint0", "-fls", "-fprintf") and j + 1 < n:  # O(1)
            v = _check(words[j + 1], c.inn, st, ctx, None, _flag_of(words[j + 1], fl))  # O(d * p)
            if v is not None:  # O(1)
                return v  # O(1)
        elif tok in ("-exec", "-execdir", "-ok", "-okdir"):  # O(1)
            k = j + 1  # O(1)
            while k < n and words[k] not in (";", "+"):  # O(w)
                k += 1  # O(1)
            cmd = words[j + 1:k]  # O(w)
            for t in reach:  # {} stands for a file below each start path | O(w)
                sub = [x.replace("{}", t) for x in cmd]  # O(w)
                c2 = _Cmd(c.seg, c.inn, False, False, [], c.cond)  # O(1)
                v = _run_words(sub, [False] * len(sub), c2, st, ctx, depth)  # O(t)
                if v is not None:  # O(1)
                    return v  # O(1)
            j = k  # O(1)
        j += 1  # O(1)
    return None  # O(1)


def _argv_sub(w):  # O(len(w) + code) | Python code with sys.argv[N] replaced by the N-th word after the code, when it is plain
    if "-c" not in w[1:] or w.index("-c", 1) + 1 >= len(w):  # O(w)
        return w  # O(1)
    k = w.index("-c", 1) + 1  # O(w)
    rest = w[k + 1:]  # O(w)

    def sub(m):  # O(1)
        n = int(m.group(1))  # O(1)
        a = rest[n - 1] if 1 <= n <= len(rest) else None  # O(1)
        return m.group(0) if a is None or any(ch in a for ch in "'\"\\\n$`") else repr(a)  # O(len(a))
    return w[:k] + [re.sub(r"\b(?:sys\.)?argv\[(\d+)\]", sub, w[k])] + rest  # O(code)


def _patch_dir(w):  # O(w) | the folder `patch -d DIR` works in, "." without -d
    for i, x in enumerate(w[1:], 1):  # O(w)
        if x in ("-d", "--directory") and i + 1 < len(w):  # O(1)
            return w[i + 1]  # O(1)
        if x.startswith("--directory="):  # O(1)
            return x.split("=", 1)[1]  # O(p)
        if x.startswith("-d") and len(x) > 2:  # O(1)
            return x[2:]  # O(p)
    return "."  # O(1)


def _script(w, inn, st):  # O(w * d) | (code, argv words) of a Python script file this command wrote by heredoc, else None
    i = 1  # O(1)
    while i < len(w) and w[i].startswith("-"):  # O(w)
        i += 2 if w[i] in ("-W", "-X") else 1  # O(1)
    if i >= len(w):  # O(1)
        return None  # O(1)
    p = w[i]  # O(1)
    for d in inn:  # O(d)
        full = _clean(_winpath(p)) if p.startswith("/") else (_clean(d + "/" + p) if d else None)  # O(p)
        if full in st.shared["scripts"]:  # O(1)
            return st.shared["scripts"][full], list(w[i + 1:])  # O(w)
    return None  # O(1)


def _link_hit(src, dests, inn, st, ctx):  # O(d * p) | protected verdict when a link's source is a protected file (or the run folder)
    cands = [src]  # a symbolic link's relative source is read from the link's folder, a hard link's from the shell's | O(1)
    if not src.startswith(("/", "~", "$")) and len(src) > 1 and src[1] != ":":  # O(1)
        for t in dests:  # O(t)
            if t != "?" and not t.endswith("?"):  # O(1)
                cands.append(t.rstrip("/") + "/../" + src if not t.endswith("/") else t + src)  # O(p)
                cands.append(t.rstrip("/") + "/" + src)  # O(p)
    for cand in cands:  # O(t)
        cand = _expand(cand, st, ctx)  # O(p + v)
        if cand == "?" or "$" in cand or "`" in cand:  # not a literal: unknown, protected only next to a protected name | O(1)
            if ctx.mentions:  # O(1)
                return Verdict(src, src, "protected")  # O(1)
            continue  # O(1)
        for a in (_loose(cand) if (_is_glob(cand) or "{" in cand) else [cand]):  # O(MAX_BRACE * p)
            if _is_glob(a):  # O(p)
                v = _glob_check(a, inn, st, ctx, None, True)  # O(d * p)
                if v is not None and v.kind == "protected":  # O(1)
                    return v  # O(1)
                continue  # O(1)
            for lit in (a, a.rstrip("/") + "/orchestrator.json"):  # the source, or a folder that holds the run file | O(1)
                for base in inn:  # O(d)
                    v = _judge_path(lit, base, ctx)  # O(p + depth)
                    if v is not None and (v.kind == "protected" or (lit == a and os.path.isfile(v.abs))):  # an existing code file: a hard link to it is a second way to write it | O(1)
                        return v  # O(1)
    return None  # O(1)


def _targets(words, dyn, base, xargs, c, st, ctx, depth):  # O(t * d * p) | judge the paths guard_files and guard_tools name
    base = "ln" if base == "link" else base  # `link A B` is `ln A B` | O(1)
    w = [base] + list(words[1:]) + (["?"] if xargs else [])  # xargs adds operands read from stdin | O(w)
    pairs = []  # (target, file name for a folder target) | O(1)
    if base in guard_files.COMMANDS:  # O(1)
        tg = guard_files.targets(w)  # O(w)
        for src in guard_files.link_sources(w):  # a link to a protected file is a way to write it | O(w)
            v = _link_hit(src, tg, c.inn, st, ctx)  # O(d * p)
            if v is not None:  # O(1)
                return v  # O(1)
        for t in tg:  # O(w)
            if base == "patch" and t == "?":  # the files named inside the patch: below the folder patch runs in | O(w)
                t = _patch_dir(w).rstrip("/") + "/?"  # O(w)
            pairs.append((t, None if base in REMOVE else _source_name(w, t)))  # O(w)
    flag = "-c"  # the flag that gives an interpreter inline code | O(1)
    m = INTERP.match(base)  # O(1)
    if m:  # O(1)
        flag = {"node": "-e", "nodejs": "-e", "bun": "-e", "perl": "-e", "ruby": "-e", "php": "-r"}.get(base, "-c")  # O(1)
    has_code = m is not None and (flag in w[1:] or (flag == "-c" and "-m" in w[1:]))  # O(w)
    script = _script(w, c.inn, st) if (m and flag == "-c" and not has_code and not c.docs) else None  # O(w * d)
    if base in guard_tools.COMMANDS or base.lower() in guard_tools.COMMANDS or m:  # O(1)
        progs = c.docs if (m and not has_code) else []  # a heredoc or here-string is the program | O(docs)
        if script is not None:  # a script this command wrote by heredoc: its code, with the words after it as argv | O(code)
            pairs.extend((t, "?") for t in guard_tools.targets(_argv_sub([base, "-c", script[0]] + script[1])))  # O(code)
        elif base == "git":  # git: from each directory, with the command's variables and the project as top | O(d * w)
            env = dict(st.vars)  # O(v)
            for x in c.seg.words:  # NAME=value words before git | O(w)
                if _base(x) == "git":  # O(1)
                    break  # O(1)
                if ASSIGN.match(x):  # O(1)
                    k, val = x.split("=", 1)  # O(p)
                    env[k.rstrip("+")] = None if ("$" in val or "`" in val) else val  # O(1)
            ts = []  # O(1)
            for d in (c.inn or (None,)):  # O(d)
                for t in guard_tools.targets(w, cwd=d, env=env, top=ctx.projn, text=ctx.text):  # O(w)
                    if t not in ts:  # O(t)
                        ts.append(t)  # O(1)
            if ts and any(x.startswith("--directory") or x == "--unsafe-paths" for x in w):  # apply --directory=DIR | O(w)
                ts.append("?")  # the patch lands below a folder git does not name as its cwd | O(1)
            pairs.extend((t, "?") for t in ts)  # O(t)
        elif progs:  # O(docs)
            for doc in progs:  # O(docs)
                k = w.index("-", 1) if "-" in w[1:] else len(w)  # O(w)
                w2 = _argv_sub(w[:k] + [flag, doc] + w[k + 1:])  # O(w + doc)
                pairs.extend((t, "?") for t in guard_tools.targets(w2))  # O(doc)
        elif m and not has_code and c.piped and (len(w) == 1 or "-" in w[1:]):  # a program piped in | O(w)
            pairs.append(("?", None))  # O(1)
        else:  # O(1)
            pairs.extend((t, "?") for t in guard_tools.targets(_argv_sub(w) if m and flag == "-c" else w))  # O(w)
    inn = c.inn  # O(1)
    if m and "chdir" in " ".join(w[1:]) + "".join(c.docs) + (script[0] if script else ""):  # the code moves: unknown | O(n)
        inn = (None,)  # O(1)
    fl = _flags(c.seg)  # O(w)
    for t, name in pairs:  # O(t)
        v = _check(t, inn, st, ctx, name, _flag_of(t, fl))  # O(d * p)
        if v is not None:  # O(1)
            return v  # O(1)
    return None  # O(1)


def _run_words(words, dyn, c, st, ctx, depth):  # O(n) | judge one command's words (after keywords and assignments)
    words, dyn, inn, xargs, _sh = _unwrap(list(words), list(dyn), c, st, ctx)  # O(w)
    if not words:  # O(1)
        return None  # O(1)
    c.inn = c.ok = c.fail = inn  # the wrapper may have changed the directory | O(1)
    words = [_expand(w, st, ctx) if d else w for w, d in zip(words, dyn)]  # the variables the guard knows | O(w * p)
    dyn = [d and ("$" in w or "`" in w) for w, d in zip(words, dyn)]  # O(w)
    base = _base(words[0])  # O(p)
    if _is_sl(words):  # O(w)
        return None  # O(1)
    if base in ("cd", "pushd", "popd"):  # O(1)
        _cd(base, words, c, st, ctx)  # O(d * p)
        return None  # O(1)
    if base == "mkdir":  # O(1)
        _mkdir(words, c, st, ctx)  # O(w)
    v = None  # O(1)
    fl = _flags(c.seg)  # O(w)
    if dyn[0] or fl.get(words[0]):  # a command word the guard cannot read ($(echo rm), ${RM:-rm}, /bin/r?) | O(w * d * p)
        for w in words[1:]:  # it may be rm or tee: every operand is a write target | O(w)
            if w.startswith("-") or w == "":  # O(1)
                continue  # O(1)
            v = _check(w, c.inn, st, ctx, None, fl.get(w, ""))  # O(d * p)
            if v is not None:  # O(1)
                break  # O(1)
    elif base in SHELLS:  # O(1)
        v = _shell(words, dyn, c, st, ctx, depth)  # O(n)
    elif base in ("eval", "source", "."):  # O(1)
        v = _source_or_eval(base, words, dyn, c, st, ctx, depth)  # O(n)
    elif base == "find":  # O(1)
        v = _find(words, c, st, ctx, depth)  # O(w * d)
    else:  # O(1)
        v = _targets(words, dyn, base, xargs, c, st, ctx, depth)  # O(t * d * p)
    if base in DISTURB or base in SHELLS or INTERP.match(base):  # a later cd into a folder this may remove is not sure | O(1)
        st.shared["disturbed"] = True  # O(1)
    if base in POISON:  # O(1)
        c.ok = c.fail = (None,)  # O(1)
    return v  # O(1)


def _run(c, st, ctx, depth):  # O(n) | one segment: nested bodies, redirects, then the command
    seg = c.seg  # O(1)
    _tick(ctx)  # O(1)
    for body in seg.bodies:  # substitutions run in a subshell | O(bodies)
        v = _walk_text(body, st.fork(c.inn), ctx, depth + 1)  # O(body)
        if v is not None:  # O(1)
            return v  # O(1)
    if seg.subshell is not None:  # O(1)
        v = _walk_text(seg.subshell, st.fork(c.inn), ctx, depth + 1)  # O(subshell)
        if v is not None:  # O(1)
            return v  # O(1)
    for r in seg.redirects:  # O(redirects)
        tgt = r.target  # O(1)
        if r.op not in WRITE_REDIRECTS or tgt in ("", "-") or tgt.startswith(("(", "<(", ">(")):  # O(1)
            continue  # O(1)
        if r.op == ">&" and (tgt.isdigit() or tgt.rstrip("-").isdigit()):  # an fd duplicate | O(1)
            continue  # O(1)
        tgt = tgt.lstrip(" \t")  # a target re-read from a decoded -c word keeps the space after `>` | O(p)
        v = _check(tgt, c.inn, st, ctx, None, r.glob)  # O(d * p)
        if v is not None:  # O(1)
            return v  # O(1)
        if seg.heredocs and seg.words and _base(seg.words[0]) == "cat" and r.op in (">", ">|", ">>"):  # O(p)
            t = _expand(tgt, st, ctx)  # a script written here may run later in the command | O(p)
            for d in c.inn:  # O(d)
                if t.startswith("/") or d:  # O(1)
                    st.shared["scripts"][_clean(_winpath(t) if t.startswith("/") else d + "/" + t)] = seg.heredocs[0]  # O(p)
    words, dyn, i = list(seg.words), list(seg.dyn), 0  # O(w)
    neg = False  # `! cmd`: success and failure swap | O(1)
    while i < len(words) and words[i] in LEAD_KW:  # O(w)
        neg = neg != (words[i] == "!" and not dyn[i])  # O(1)
        i += 1  # O(1)
    if i < len(words) and words[i] in NO_CMD_KW:  # O(1)
        return None  # O(1)
    assigns = []  # O(1)
    while i < len(words) and ASSIGN.match(words[i]):  # leading NAME=value words | O(w)
        assigns.append((words[i], dyn[i]))  # O(1)
        i += 1  # O(1)
    if i < len(words) and words[i] in DECLARE:  # export NAME=value | O(1)
        assigns = [(w, d) for w, d in zip(words[i + 1:], dyn[i + 1:]) if ASSIGN.match(w)]  # O(w)
        i = len(words)  # O(1)
    if i >= len(words):  # nothing but assignments: the shell's variables | O(1)
        if c.persist:  # O(1)
            for w, d in assigns:  # O(w)
                name, val = w.split("=", 1)  # O(p)
                name = name.rstrip("+")  # O(1)
                val = _expand(val, st, ctx) if d else val  # O(p)
                new = None if ("$" in val or "`" in val) else val  # O(p)
                old = st.vars.get(name, new)  # O(1)
                if old != new:  # reassigned: every value is judged (_alternatives) | O(1)
                    if old is None or new is None:  # O(1)
                        new = None  # O(1)
                    else:  # O(1)
                        st.multi.setdefault(name, []).append(old)  # O(1)
                st.vars[name] = new  # O(1)
        return None  # O(1)
    v = _run_words(words[i:], dyn[i:], c, st, ctx, depth)  # O(n)
    if neg:  # O(1)
        c.ok, c.fail = c.fail, c.ok  # O(1)
    return v  # O(1)


def _alternatives(seg, st):  # O(w * v) | (name, earlier value) for each reassigned variable the segment uses
    if not st.multi:  # O(1)
        return []  # O(1)
    text = " ".join(seg.words + [r.target for r in seg.redirects] + seg.heredocs + seg.bodies + [seg.subshell or ""])  # O(w)
    return [(k, val) for k, vals in st.multi.items() if re.search(r"\$\{?" + k + r"\b", text) for val in vals]  # O(w * v)


def _walk(segs, st, ctx, depth, force_cond=False):  # O(s * n) | judge the segments in order; st.dirs follows the cds
    n, i, ok, fail, depth_c = len(segs), 0, None, None, 0  # O(1)
    start = st.dirs  # O(1)
    while i < n:  # O(s)
        j = i  # O(1)
        while j < n - 1 and segs[j].sep == "|":  # a pipeline: every part runs in its own subshell | O(s)
            j += 1  # O(1)
        op = segs[i - 1].sep if i > 0 else ""  # O(1)
        sep = segs[j].sep  # O(1)
        if op in ("&&", "||") and ok is not None:  # O(1)
            inn = ok if op == "&&" else fail  # O(1)
        else:  # a new chain | O(1)
            inn, ok, fail, start = st.dirs, None, None, st.dirs  # O(1)
        u_ok = u_fail = inn  # O(1)
        for k in range(i, j + 1):  # O(pipeline)
            seg = segs[k]  # O(1)
            w0 = seg.words[0] if seg.words and not seg.dyn[0] else ""  # O(1)
            if w0 in OPEN_KW:  # O(1)
                depth_c += 1  # O(1)
            elif w0 in CLOSE_KW:  # O(1)
                depth_c = max(0, depth_c - 1)  # O(1)
            if not inn:  # a branch that cannot run | O(1)
                continue  # O(1)
            docs, m = list(seg.heredocs) + [r.target + "\n" for r in seg.redirects if r.op == "<<<"], k + 1  # O(docs)
            prev = segs[k - 1] if k > i else None  # O(1)
            if prev is not None and prev.words[:1] == ["cat"] and all(x.startswith("-") for x in prev.words[1:]):  # O(w)
                docs = list(prev.heredocs) + [r.target + "\n" for r in prev.redirects if r.op == "<<<"] + docs  # `cat <<EOF | sh` | O(docs)
            while m < n and not segs[m].words and segs[m].subshell is None:  # redirects of a closing group: `{ ...; } <<EOF` | O(s)
                docs += list(segs[m].heredocs) + [r.target + "\n" for r in segs[m].redirects if r.op == "<<<"]  # O(docs)
                m += 1  # O(1)
            persist = i == j and sep != "&"  # O(1)
            c = _Cmd(seg, inn, persist, k > 0 and segs[k - 1].sep == "|", docs, st.cond or force_cond or depth_c > 0)  # O(1)
            v = _run(c, st, ctx, depth)  # O(n)
            for name, val in (_alternatives(seg, st) if v is None else []):  # a reassigned variable: its earlier values | O(v * n)
                keep = st.vars.get(name)  # O(1)
                st.vars[name] = val  # O(1)
                v = _run(_Cmd(seg, c.inn, False, c.piped, docs, c.cond), st, ctx, depth)  # O(n)
                st.vars[name] = keep  # O(1)
                if v is not None:  # O(1)
                    break  # O(1)
            if v is not None:  # O(1)
                return v  # O(1)
            if i == j:  # O(1)
                u_ok, u_fail = c.ok, c.fail  # O(1)
        if ok is None:  # O(1)
            ok, fail = u_ok, u_fail  # O(1)
        elif op == "&&":  # O(1)
            ok, fail = u_ok, _union(fail, u_fail)  # O(d)
        else:  # O(1)
            ok, fail = _union(ok, u_ok), u_fail  # O(d)
        if sep not in ("&&", "||"):  # the chain ends: the shell may sit in any directory the chain can leave it | O(d)
            st.dirs = _union(ok, fail) or start  # O(d)
            ok = fail = None  # O(1)
        i = j + 1  # O(1)
    return None  # O(1)


def judge(command, cwd, project, mode):  # O(s * n * d) | Verdict for the first write the policy denies, else None
    ctx = _Ctx(command, project, mode)  # O(n + p)
    here = _clean(_winpath(cwd)) if cwd else ctx.projn  # O(p)
    if not here.startswith("/"):  # O(1)
        here = _clean(ctx.projn + "/" + here)  # O(p)
    try:  # O(1)
        return _walk_text(command, _State((here,)), ctx, 0)  # O(s * n * d)
    except _Unknown:  # a NUL in a path, or the step or time budget spent: blocks when the guard enforces | O(1)
        return _unknown(ctx)  # O(1)


