def _scratch_hint(project, sd):  # O(p) | the coordinator's throwaway-script folder: project-relative when the state folder lies in the project
    return sd[len(project) + 1:] + "/scratch" if sd.startswith(project + "/") else sd + "/scratch"  # O(p)


def _flat(s, limit=120):  # O(len) | one line, no control characters
    s = re.sub(r"[\r\n\t]", " ", s)  # O(len)
    return re.sub(r"[\x00-\x1f\x7f]", "", s)[:limit].strip()  # O(len)


def _incident(sd, kind, tool, target, rule=None, cwd=None):  # O(1) | append one incident line; never raises
    try:  # O(1)
        row = {"kind": kind, "agent": "coordinator", "tool": tool, "target": _flat(target, 400 if rule else 120)}  # O(len)
        if rule:  # a rule-block row names the rule and the directory | O(1)
            row.update(rule=rule, cwd=cwd)  # O(1)
        with open(os.path.join(sd, "incidents.jsonl"), "a", encoding="utf-8") as f:  # O(1)
            f.write(json.dumps(row) + "\n")  # O(len)
    except (OSError, TypeError, ValueError):  # O(1)
        pass  # O(1)


def _args(argv):  # O(a) | (mode, project, sd, owns or None)
    opts = {}  # O(1)
    it = iter(argv)  # O(1)
    for a in it:  # O(a)
        if a in ("--mode", "--project", "--sd", "--owns"):  # O(1)
            opts[a[2:]] = next(it)  # O(1)
        else:  # O(1)
            raise ValueError("unknown argument " + a)  # O(1)
    if opts.get("mode") not in ("idle", "active", "human") or "project" not in opts or "sd" not in opts:  # O(1)
        raise ValueError("--mode, --project and --sd are required")  # O(1)
    return opts["mode"], opts["project"], opts["sd"], opts.get("owns")  # O(1)


def _owns_ok(path, project, sd):  # O(p + owns) | may the coordinator write this file as the inline task's Owns? any doubt is no
    try:  # O(1)
        ctx = _Ctx("", project, "active", (sd,))  # O(p)
        if not ctx.inline or "\0" in path:  # O(1)
            return False  # O(1)
        full = _clean(path if path.startswith("/") else ctx.projn + "/" + path)  # O(p)
        real = _real(full)  # O(p)
        return bool(_rel(real, ctx.projreal)) and _owned(real, ctx) and _judge_path(path, ctx.projn, ctx) is None  # O(p + owns)
    except Exception:  # noqa: BLE001  O(1)
        return False  # O(1)


def _err(text):  # O(len) | print on stderr whatever the stream's encoding
    try:  # O(1)
        print(text, file=sys.stderr)  # O(len)
    except UnicodeEncodeError:  # O(1)
        print(text.encode("ascii", "replace").decode("ascii"), file=sys.stderr)  # O(len)


def _ack():  # O(1) | the allow line the hook waits for: an exit 0 without it was no judge (a fake cached Python)
    nonce = os.environ.get("SUPERLITE_GUARD_NONCE", "")  # O(1)
    print("guard: ok" + (" " + nonce if nonce else ""))  # O(1)


def main(argv=None):  # O(s * n * d) | hook entry: 2 blocks, 0 passes and every internal error
    try:  # O(1)
        mode, project, sd, owns = _args(sys.argv[1:] if argv is None else argv)  # O(a)
    except (ValueError, StopIteration):  # O(1)
        return 0  # O(1)
    if owns is not None:  # --owns PATH: exit 0 and the ack only for an active run's inline Owns file, else 1 | O(p)
        if mode == "active" and _owns_ok(owns, project, sd):  # O(p)
            _ack()  # O(1)
            return 0  # O(1)
        return 1  # O(1)
    tool, cmd = "", ""  # O(1)
    try:  # O(1)
        data = json.loads(sys.stdin.read())  # O(n)
        if not isinstance(data, dict):  # O(1)
            raise ValueError("hook input is not an object")  # O(1)
        tool = str(data.get("tool_name") or "")  # O(1)
        tin = data.get("tool_input")  # O(1)
        cmd = tin.get("command") if isinstance(tin, dict) else None  # O(1)
        if not isinstance(cmd, str):  # O(1)
            raise ValueError("no command in the hook input")  # O(1)
        cwd = data.get("cwd") if isinstance(data.get("cwd"), str) else None  # O(1)
        pd = os.environ.get("SUPERLITE_FLEET_PARENT_DIR")  # O(1)
        tp = data.get("transcript_path") if isinstance(data.get("transcript_path"), str) else None  # O(1)
        v = judge(cmd, cwd or project, project, mode, (sd, pd) if pd else (sd,), transcript=tp)  # O(s * n * d)
    except Exception as e:  # noqa: BLE001  fail open on anything | O(1)
        _incident(sd, "guard-error", tool, f"{type(e).__name__}: {e}")  # O(len)
        _ack()  # the judge ran and logged its own error | O(1)
        return 0  # O(1)
    if v is None:  # O(1)
        _ack()  # O(1)
        return 0  # O(1)
    named = v.rel not in ("?", ".")  # O(1)
    target = v.rel if named and not v.word else f"unresolved {_flat(v.word)} in: {cmd}" if v.word else cmd  # the word first: the incident cuts the rest | O(len)
    _incident(sd, "rule-block", tool, target, rule=v.kind, cwd=cwd or project)  # O(len)
    for line in MESSAGES[v.kind]:  # O(1)
        _err(line.replace("{scratch}", _scratch_hint(project, sd)))  # the scratch folder line (#690) names its folder | O(len)
    if v.cmd:  # the one command of the chain that was refused | O(1)
        _err(REFUSED.format(_flat(v.cmd, 300)))  # O(len)
    if v.kind != "protected":  # the protected message names no target | O(1)
        if v.why:  # why the target is no housekeeping, right after the refused line | O(len)
            _err(f"Not housekeeping: {_flat(v.why, 300)}")  # O(len)
        if v.word:  # the word the guard could not resolve | O(len)
            _err(UNRESOLVED_HINT)  # the supported way, right before the word so the last lines stay as before | O(len)
            _err(f"Unresolved word: {_flat(v.word, 500)}")  # O(len)
        if named:  # the absolute path on its own line; the last line stays `Blocked target: <rel>` as before | O(len)
            _err(f"Absolute target: {_flat(v.abs, 500)}")  # O(len)
            _err(f"Blocked target: {_flat(v.rel, 500)}")  # O(len)
        else:  # O(1)
            _err(f"Blocked command: {_flat(cmd)}")  # O(len)
    return 2  # O(1)


if __name__ == "__main__":  # O(1)
    sys.exit(main())  # O(1)
