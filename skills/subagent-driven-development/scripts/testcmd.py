SEGMENT_SPLIT = re.compile(r"(\|\||&&|;|\||&)")  # O(1)
DEST_FLAG = re.compile(r"\s+-destination\s+(?:'[^']*'|\"[^\"]*\"|[^\s'\"])+")  # O(1)
XCODEBUILD_WORD = re.compile(r"(?:^|[\s/])xcodebuild(?=\s|$)")  # O(1)
SWIFT_TEST_WORD = re.compile(r"(?:^|\s)swift\s+test(?=\s|$)")  # O(1)
PLATFORM_NAMES = ("iOS", "macOS", "tvOS", "watchOS", "visionOS", "macCatalyst")  # O(1)


def _segments(command: str) -> list[str]:  # the command split at unquoted | || && ; &, operators kept as their own items | O(n)
    out: list[str] = []  # O(1)
    buf: list[str] = []  # O(1)
    quote = ""  # O(1)
    i = 0  # O(1)
    while i < len(command):  # O(n)
        ch = command[i]  # O(1)
        if quote:  # O(1)
            buf.append(ch)  # O(1)
            quote = "" if ch == quote else quote  # O(1)
        elif ch in "'\"":  # O(1)
            quote = ch  # O(1)
            buf.append(ch)  # O(1)
        else:  # O(1)
            m = SEGMENT_SPLIT.match(command, i)  # O(1)
            if m and m.group(1) == "&" and (command[i - 1:i] in (">", "<") or command[i + 1:i + 2] == ">"):  # 2>&1, <&3 and &> are redirects | O(1)
                m = None  # O(1)
            if m:  # O(1)
                out.append("".join(buf))  # O(len)
                out.append(m.group(1))  # O(1)
                buf = []  # O(1)
                i += len(m.group(1))  # O(1)
                continue  # O(1)
            buf.append(ch)  # O(1)
        i += 1  # O(1)
    out.append("".join(buf))  # O(len)
    return out  # O(1)


def with_destination(command: str, dest: str) -> str | None:  # every xcodebuild segment run against dest only; None when no segment is xcodebuild | O(n)
    parts = _segments(command)  # O(n)
    hit = False  # O(1)
    for i in range(0, len(parts), 2):  # operators sit at the odd indexes | O(segments)
        if not XCODEBUILD_WORD.search(parts[i]):  # O(len)
            continue  # O(1)
        hit = True  # O(1)
        core = DEST_FLAG.sub("", parts[i].rstrip())  # O(len)
        parts[i] = core + " -destination " + shlex.quote(dest) + parts[i][len(parts[i].rstrip()):]  # trailing blanks stay before the operator | O(len)
    return "".join(parts) if hit else None  # O(n)


def destination_platform(dest: str) -> str | None:  # iOS, macOS, tvOS, watchOS, visionOS or macCatalyst of an xcodebuild destination, else None | O(len)
    m = re.search(r"platform=([^,]+)", dest)  # O(len)
    if not m:  # O(1)
        return None  # O(1)
    name = m.group(1).strip()  # O(1)
    if name == "macOS" and re.search(r"variant=Mac Catalyst", dest):  # O(len)
        return "macCatalyst"  # O(1)
    if name == "macOS" or name == "macCatalyst":  # O(1)
        return name  # O(1)
    first = name.split()[0] if name.split() else ""  # "iOS Simulator" -> iOS | O(1)
    first = "visionOS" if first == "xrOS" else first  # O(1)
    return first if first in PLATFORM_NAMES else None  # O(1)


def command_platforms(command: str) -> list[str]:  # platforms a test command builds for: swift test is macOS, xcodebuild by its -destination values | O(n)
    found: list[str] = []  # O(1)
    for seg in _segments(command)[::2]:  # O(segments)
        plats: list[str] = []  # O(1)
        if XCODEBUILD_WORD.search(seg):  # O(len)
            for m in re.finditer(r"-destination\s+('[^']*'|\"[^\"]*\"|(?:[^\s'\"])+)", seg):  # O(len)
                plat = destination_platform(m.group(1).strip("'\""))  # O(len)
                plats += [plat] if plat else []  # O(1)
        elif SWIFT_TEST_WORD.search(seg):  # O(len)
            plats = ["macOS"]  # O(1)
        found += [p for p in plats if p not in found]  # O(1)
    return found  # O(1)


def declared_platforms(root) -> list[str]:  # platforms in `platforms: [...]` of Package.swift files at the root and one or two folder levels below | O(entries)
    root = Path(root)  # O(1)
    files: list[Path] = [root / "Package.swift"]  # O(1)
    level = [root]  # O(1)
    for _ in range(2):  # O(1)
        nxt: list[Path] = []  # O(1)
        for d in level:  # O(dirs)
            try:  # O(1)
                kids = sorted(e for e in d.iterdir() if e.is_dir() and e.name not in SKIP_DIRS and not e.name.startswith("."))  # O(entries)
            except OSError:  # O(1)
                continue  # O(1)
            files += [k / "Package.swift" for k in kids]  # O(k)
            nxt += kids  # O(k)
        level = nxt  # O(1)
    found: set[str] = set()  # O(1)
    for f in files:  # O(dirs)
        try:  # O(1)
            code = strip_swift(f.read_text(encoding="utf-8", errors="replace"))  # O(file)
        except OSError:  # O(1)
            continue  # O(1)
        for m in re.finditer(r"\bplatforms\s*:\s*\[", code):  # O(file)
            depth, j = 1, m.end()  # O(1)
            while j < len(code) and depth:  # O(file)
                depth += (code[j] == "[") - (code[j] == "]")  # O(1)
                j += 1  # O(1)
            found.update(re.findall(r"\.(" + "|".join(PLATFORM_NAMES) + r")\b", code[m.end():j]))  # O(file)
    return sorted(found)  # O(1)


def merge_parsed(parts: list[tuple[str, dict]]) -> dict:  # one parse_output-shaped result from the per-destination ones | O(parts*o)
    names: list[str] = []  # O(1)
    for _, p in parts:  # O(parts)
        names += [n for n in p.get("names", []) if n not in names]  # O(names)
    counted = bool(parts) and all(p.get("counted") for _, p in parts)  # O(parts)
    bad = [p for _, p in parts if p.get("failed", 0) > 0] or [p for _, p in parts]  # O(parts)
    tail = [ln for p in bad for ln in p.get("tail", [])][-40:]  # O(parts*o)
    error = next((f"[{d}] {p['error']}" for d, p in parts if p.get("error")), "")  # O(parts)
    marker = next((p["marker"] for _, p in reversed(parts) if p.get("marker")), "")  # O(parts)
    empty = "" if any(p.get("counted") for _, p in parts) else next((p["empty"] for _, p in parts if p.get("empty")), "")  # O(parts)
    reasons: dict[str, tuple[str, int]] = {}  # the first part's value wins on a shared id | O(1)
    for _, p in parts:  # O(parts)
        for k, v in p.get("reasons", {}).items():  # O(names)
            reasons.setdefault(k, v)  # O(1)
    extra = {"reasons": reasons} if reasons else {}  # the key only when a part had ids: an exact-shape caller stays valid | O(1)
    return {"passed": sum(p.get("passed", 0) for _, p in parts), "failed": sum(p.get("failed", 0) for _, p in parts), "skipped": sum(p.get("skipped", 0) for _, p in parts),  # O(parts)
            "names": names[:50], "tail": tail, "empty": empty, "counted": counted, "error": error, "marker": marker, **extra}  # O(1)


def resolve(root=".", paths=(), notes: list | None = None):  # O(m + f)
    """-> {"language", "python": bool, "command": str|None, "junit": str, "env": {}, "setup": str, "source"} or None."""
    root = Path(root)  # O(1)
    cfg, src, origin = config_source(root)  # O(m + f)
    if cfg is None:  # O(1)
        return None  # O(1)
    lang = cfg.get("language") or "unknown"  # O(1)
    iso = cfg["isolate"] if isinstance(cfg.get("isolate"), bool) else lang in ISOLATE_LANGS  # explicit config wins | O(1)
    if cfg.get("test") is None and cfg.get("language") == "python":  # O(1)
        return {"language": "python", "python": True, "command": None, "junit": "", "env": {}, "setup": "", "source": src, "origin": origin, "isolate": iso, "lock": lock_enabled(cfg), "destinations": destinations(cfg), "not_code": not_code_globs(cfg), "paths_dropped": False}  # O(1)
    files = " ".join(f'"{p}"' if " " in p else p for p in paths)  # O(p)
    template = cfg.get("test_file") or cfg["test"]  # O(1)
    dropped = bool(paths) and not any(sl in template for sl in ("{files}", "{names}", "{only_testing}"))  # the command cannot take the paths | O(1)
    command = template.replace("{files}", files) if paths else cfg["test"]  # O(1)
    if paths and "{files}" not in template:  # a test_file without {files} runs everything | O(1)
        command = template  # O(1)
    unfiltered = False  # O(1)
    if "{names}" in command:  # O(1)
        swiftish = bool(paths) and (lang == "swift" or any(str(p).endswith(".swift") for p in paths))  # O(p)
        names = swift_names(root, list(paths)) if swiftish else None  # O(p*files)
        if swiftish and names is None:  # a path outside every test target | O(p)
            unfiltered = True  # O(1)
            note = f"{next((p for p in paths if str(p).endswith('.swift')), paths[0])} is not in a test target; running the unfiltered test command"  # O(p)
            if notes is not None:  # O(1)
                notes.append(note)  # O(1)
            else:  # O(1)
                print(f"testcmd: {note}", file=sys.stderr)  # O(1)
        else:  # O(1)
            text = "|".join(names) if names is not None else names_filter(paths)  # O(p)
            command = NAMES_SLOT.sub(lambda m: text if not text or _in_quotes(m.string[:m.start()]) else shlex.quote(text), command)  # quoted unless the template quotes it | O(len^2)
    if unfiltered:  # O(1)
        command = cfg["test"].replace("{names}", "").replace("{only_testing}", "")  # O(len)
    elif "{only_testing}" in command:  # only an Xcode template pays for suite detection and its warning | O(1)
        ids = only_testing(paths, root, notes)  # O(p)
        if ids is None:  # a path outside every test target: the unfiltered test command | O(1)
            command = cfg["test"].replace("{names}", "").replace("{only_testing}", "")  # O(len)
        else:  # O(1)
            if is_maxapp_command(command):  # maxapp takes --only Target/Suite pairs | O(p)
                ids = " ".join("--only " + shlex.quote(t.split(":", 1)[1]) for t in shlex.split(ids))  # O(p)
            command = command.replace("{only_testing}", ids)  # O(p)
    return {"language": lang, "isolate": iso, "python": False, "command": command, "junit": cfg.get("junit") or "",  # O(1)
            "env": cfg.get("env") or {}, "setup": cfg.get("setup") or "", "source": src, "origin": origin, "lock": lock_enabled(cfg), "destinations": destinations(cfg), "not_code": not_code_globs(cfg), "paths_dropped": dropped}  # O(1)


NAME_PATTERNS = [r"^--- FAIL: (\S+)", r"^test (\S+) \.\.\. FAILED", r"^\s*(?:FAIL|✗|×|✕)\s+(.+?)\s*$", r"^\s*Failed\s+(\S+)",  # O(1)
                 r"^\s*\d+\)\s+(.+?)\s*$"]
COUNT_PASSED = [r"(\d+)\s+passed", r"Passed!?.*?Passed:\s*(\d+)", r"test result: \w+\. (\d+) passed", r"^ok\s+\S+", ]  # O(1)


def _parse_xcode(lines: list, rc: int):  # Swift Testing + XCTest counts, summed; None when nothing printed | O(o)
    st_total = xc_total = xc_failed = xc_skipped = 0  # O(1)
    names: list[str] = []  # O(1)
    st_names: list[str] = []  # O(1)
    st_passed: dict[str, int] = {}  # distinct Swift Testing names that passed | O(t)
    st_skipped: dict[str, int] = {}  # O(t)
    ended: set[str] = set()  # every test that passed, failed or was skipped, in any launch | O(t)
    open_now: set[str] = set()  # started and not ended in this launch | O(t)
    crashed: dict[str, int] = {}  # started, then the process died | O(t)
    restarts = 0  # O(1)
    par_pass: dict[str, int] = {}  # parallel testing: `Test case 'X' passed on` | O(t)
    par_fail: dict[str, int] = {}  # O(t)
    seen = False  # O(1)
    after_top, top_seen, last_xc = False, False, (0, 0, 0)  # after_top: the next Executed line follows a top-level suite end | O(1)
    for ln in lines:  # O(o)
        m = re.search(r"Test run with (\d+) tests?", ln)  # one per bundle, summed | O(w)
        if m:  # O(1)
            st_total, seen = st_total + int(m.group(1)), True  # O(1)
            open_now.clear()  # the launch ended normally | O(t)
        if re.search(r"Test Suite '(?:All|Selected) tests' (?:passed|failed)", ln):  # O(w)
            after_top, top_seen = True, True  # O(1)
        m = re.match(r"\s*[✘✗] Test (?!run with)(.+?) failed after", ln)  # O(w)
        if m:  # O(1)
            n = re.sub(r" with \d+ test cases$", "", m.group(1))  # a parameterized test is one test | O(w)
            ended.add(n)  # O(1)
            open_now.discard(n)  # O(1)
            if n not in st_names:  # O(1)
                st_names.append(n)  # O(1)
        m = re.match(r"\s*✔ Test (?!run with)(.+?) passed after", ln)  # O(w)
        if m:  # O(1)
            n = re.sub(r" with \d+ test cases$", "", m.group(1))  # O(w)
            ended.add(n)  # O(1)
            open_now.discard(n)  # O(1)
            st_passed[n] = 1  # O(1)
        m = re.match(r"\s*━ Test (?!run with)(.+?) with \d+ test cases passed after", ln) or re.match(r"\s*━ Test (?!run with)(.+?) passed after", ln)  # known issues still pass | O(w)
        if m:  # O(1)
            ended.add(m.group(1))  # O(1)
            open_now.discard(m.group(1))  # O(1)
            st_passed[m.group(1)] = 1  # O(1)
        m = re.match(r"\s*[➜➠] Test (.+?) skipped", ln)  # O(w)
        if m:  # O(1)
            ended.add(m.group(1))  # O(1)
            open_now.discard(m.group(1))  # O(1)
            st_skipped[m.group(1)] = 1  # O(1)
        m = re.match(r"\s*◇ Test (?!run |case )(.+?) started", ln)  # O(w)
        if m:  # O(1)
            open_now.add(m.group(1))  # O(1)
        if ln.startswith("Restarting after unexpected exit"):  # the process died: what was still running is the culprit | O(1)
            restarts += 1  # O(1)
            for n in sorted(open_now):  # O(t)
                crashed[n] = 1  # O(1)
            open_now.clear()  # O(t)
        m = re.search(r"Executed (\d+) tests?, with (?:(\d+) tests? skipped and )?(\d+) failures?", ln)  # per-bundle top-level lines are summed | O(w)
        if m:  # O(1)
            last_xc, seen = (int(m.group(1)), int(m.group(3)), int(m.group(2) or 0)), True  # no top-level line at all: the last one wins | O(1)
            if after_top:  # O(1)
                xc_total, xc_failed, xc_skipped, after_top = xc_total + last_xc[0], xc_failed + last_xc[1], xc_skipped + last_xc[2], False  # O(1)
        m = re.match(r"\s*Test Case '-\[(?:\w+\.)?(\w+) (\w+)\]' failed", ln)  # O(w)
        if m and f"{m.group(1)}.{m.group(2)}" not in names:  # O(1)
            names.append(f"{m.group(1)}.{m.group(2)}")  # O(1)
        m = re.match(r"\s*Test case '(.+)' (passed|failed) on ", ln)  # parallel testing prints one line per test | O(w)
        if m:  # O(1)
            (par_fail if m.group(2) == "failed" else par_pass)[m.group(1)] = 1  # O(1)
    if not seen and (par_pass or par_fail):  # parallel run: distinct tests, a failure beats a pass | O(t)
        fails = list(dict.fromkeys(n for n in par_fail))  # O(t)
        passed = len([n for n in par_pass if n not in par_fail])  # O(t)
        return {"passed": passed, "failed": len(fails) or (1 if rc else 0), "skipped": 0, "names": fails[:50], "tail": lines[-40:], "empty": "", "counted": True, "reasons": {}, **_error_marker(lines)}  # O(t)
    if not seen and not st_passed and not st_names:  # O(1)
        return None  # O(1)
    if not top_seen:  # O(1)
        xc_total, xc_failed, xc_skipped = last_xc  # O(1)
    gone = [n for n in crashed if n not in ended]  # a bystander that later ran is not the culprit | O(t)
    skipped = len(st_skipped) + xc_skipped  # O(1)
    if restarts or (not st_total and (st_passed or st_names)):  # partial totals after a crash, or no run total at all: count the tests themselves | O(1)
        st_ok = len([n for n in st_passed if n not in st_names])  # O(t)
        fail = len(st_names) + len(gone) + xc_failed  # O(1)
        passed = st_ok + max(xc_total - xc_failed - xc_skipped, 0)  # O(1)
    else:  # O(1)
        fail = len(st_names) + xc_failed  # O(1)
        passed = max(st_total + xc_total - fail - skipped, 0)  # O(1)
    return {"passed": passed, "failed": fail or (1 if rc else 0), "skipped": skipped,  # O(1)
            "names": (st_names + [f"{n} (crashed)" for n in gone] + names)[:50], "tail": lines[-40:], "empty": "", "counted": True, "reasons": {}, **_error_marker(lines)}  # O(1)


def _error_marker(lines: list) -> dict:  # first compiler error line and the last ** ... ** marker | O(o)
    err = next((ln.strip() for ln in lines if re.search(r":\d+(?::\d+)?: error:", ln) and ": error: -[" not in ln), "")  # an XCTest assertion line is no compiler error  # O(o)
    mark = next((ln.strip() for ln in reversed(lines) if re.fullmatch(r"\s*\*\* [A-Z ]+ \*\*\s*", ln)), "")  # O(o)
    return {"error": err, "marker": mark}  # O(1)


PYTEST_SUMMARY = re.compile(r"^(?:=+ )?(\d+ [a-z]+(?:, \d+ [a-z]+)*) in \d+(?:\.\d+)?(?:s| seconds)(?: \(\d+:\d\d:\d\d\))?(?: =+)?$")  # pytest's final line, anchored so quoted summaries in failure output never match | O(1)
NOISE = re.compile(r"^job\.sh: waiting for a free job slot")  # the remote server's placement line is never test output | O(1)


def _reason_line(lines: list[str], tid: str) -> int:  # the last `<path>:<n>:` line in the id's failure section above the short summary, else 0 | O(o)
    path, _, rest = tid.partition("::")  # O(1)
    want = rest.replace("::", ".") if rest else f"ERROR collecting {path}"  # O(1)
    inside, line = False, 0  # O(1)
    for ln in lines:  # O(o)
        s = ln.strip()  # O(1)
        h = re.match(r"^_{3,} (.+?) _{3,}$", s)  # O(w)
        if h or re.match(r"^=+ .* =+$", s):  # O(w)
            inside = bool(h) and h.group(1) == want  # O(1)
        elif inside:  # O(1)
            m = re.match(rf"^{re.escape(path)}:(\d+):", s)  # O(w)
            line = int(m.group(1)) if m else line  # O(1)
    return line  # O(1)


def _parse_pytest(lines: list[str], rc: int) -> tuple[int, int, int, list[str], dict] | None:  # O(o)
    """Counts and short-summary ids from pytest's last summary line, or None when there is none."""
    idx = [i for i, ln in enumerate(lines) if PYTEST_SUMMARY.match(ln.strip())]  # O(o)
    if not idx:  # O(1)
        return None  # O(1)
    end = idx[-1]  # the last summary line wins | O(1)
    word = {}  # O(1)
    for n, w in re.findall(r"(\d+) ([a-z]+)", PYTEST_SUMMARY.match(lines[end].strip()).group(1)):  # O(1)
        word[w] = word.get(w, 0) + int(n)  # O(1)
    passed = word.get("passed", 0) + word.get("xpassed", 0)  # O(1)
    failed = word.get("failed", 0) + word.get("error", 0) + word.get("errors", 0)  # O(1)
    skipped = word.get("skipped", 0) + word.get("xfailed", 0)  # O(1)
    heads = [i for i in range(end) if re.match(r"^=+ short test summary info =+$", lines[i].strip())]  # O(o)
    names: list[str] = []  # O(1)
    start = heads[-1] + 1 if heads else end  # O(1)
    while not heads and start > 0 and re.match(r"^(?:FAILED|ERROR) ", lines[start - 1].strip()):  # no header: the FAILED/ERROR run right above the summary line | O(o)
        start -= 1  # O(1)
    reasons: dict[str, tuple[str, int]] = {}  # id -> (message, traceback line) | O(n)
    for ln in lines[start:end] if rc else []:  # O(o)
        m = re.match(r"^(?:FAILED|ERROR) (.+?)(?: - (.*))?$", ln.strip())  # O(w)
        if m and m.group(1) not in names and len(names) < 50:  # O(1)
            names.append(m.group(1)[:120])  # O(1)
            reasons[names[-1]] = ((m.group(2) or "").strip()[:160], _reason_line(lines[:start], m.group(1)))  # O(o)
    return passed, failed, skipped, names, reasons  # O(1)


def _int_key(d: dict, key: str) -> int | None:  # an int that is not a bool, else None | O(1)
    v = d.get(key)  # O(1)
    return v if isinstance(v, int) and not isinstance(v, bool) else None  # O(1)


def xcsift_summary(lines: list[str], rc: int) -> dict | None:  # counts, failing tests and sites from xcsift's JSON summary, else None | O(o^2)
    if not any('"passed_tests"' in ln or '"failed_tests"' in ln for ln in lines):  # O(o)
        return None  # O(1)
    cands = [i for i, ln in enumerate(lines) if ln.lstrip().startswith("{")][-200:]  # O(o)
    obj = None  # O(1)
    for i in reversed(cands):  # the last summary wins | O(o)
        try:  # O(1)
            got, _ = json.JSONDecoder().raw_decode("\n".join(lines[i:]).lstrip())  # O(o)
        except ValueError:  # O(1)
            continue  # O(1)
        sm = got.get("summary") if isinstance(got, dict) else None  # O(1)
        if isinstance(sm, dict) and (_int_key(sm, "passed_tests") is not None or _int_key(sm, "failed_tests") is not None):  # O(1)
            obj = got  # O(1)
            break  # O(1)
    if obj is None:  # O(1)
        return None  # O(1)
    sm = obj["summary"]  # O(1)
    passed, failed, skipped = (_int_key(sm, k) or 0 for k in ("passed_tests", "failed_tests", "skipped_tests"))  # O(1)
    names: list[str] = []  # O(1)
    reasons: dict[str, tuple[str, int]] = {}  # O(1)
    sites: list[tuple[str, int, str]] = []  # O(1)
    entries = obj.get("failed_tests")  # O(1)
    for e in (entries if isinstance(entries, list) else [])[:50]:  # O(1)
        if not isinstance(e, dict):  # O(1)
            continue  # O(1)
        name = str(e.get("test") or "").strip()[:120]  # O(1)
        if not name or name in names:  # O(1)
            continue  # O(1)
        msg = str(e.get("message") or "").strip()[:160]  # O(1)
        line = _int_key(e, "line") or 0  # O(1)
        path = e["file"] if isinstance(e.get("file"), str) else ""  # O(1)
        names.append(name)  # O(1)
        reasons[name] = (msg, line)  # O(1)
        sites.append((path, line, f"{name}: {msg or 'failed'}"))  # O(1)
    failed = max(failed, len(names))  # O(1)
    counted = bool(passed or failed or skipped)  # O(1)
    if not failed and (rc or obj.get("status") == "failed"):  # O(1)
        failed = 1  # O(1)
    mk = _error_marker(lines)  # O(o)
    errs = obj.get("errors")  # O(1)
    first = errs[0] if isinstance(errs, list) and errs and isinstance(errs[0], dict) else None  # O(1)
    if first is not None:  # O(1)
        msg = str(first.get("message") or "").strip()  # O(1)
        path = first.get("file") if isinstance(first.get("file"), str) else ""  # O(1)
        error = f"{path}:{_int_key(first, 'line') or 0}: {msg}" if path else msg  # O(1)
    else:  # O(1)
        error = mk["error"]  # O(1)
    empty = "" if counted else "xcsift summary: 0 passed, 0 failed tests"  # O(1)
    return {"passed": passed, "failed": failed, "skipped": skipped, "names": names, "reasons": reasons, "sites": sites, "counted": counted, "empty": empty, "format": "xcsift", "error": error, "marker": mk["marker"], "tail": lines[-40:]}  # O(1)


def parse_output(text: str, rc: int) -> dict:  # O(o)
    """Best-effort counts and failing test names from a runner's plain output (no JUnit).

    A pytest branch reads the last summary line and the short summary's FAILED/ERROR ids; the remote
    server's `job.sh: waiting for a free job slot` line is dropped before parsing."""
    lines = [ANSI.sub("", ln).replace("\u200b", "").rstrip() for ln in text.splitlines()]  # zero-width spaces prefix some Swift Testing lines | O(o)
    lines = [ln for ln in lines if not NOISE.match(ln)]  # O(o)
    xc = _parse_xcode(lines, rc)  # O(o)
    if xc is not None:  # O(1)
        return xc  # O(1)
    xs = xcsift_summary(lines, rc)  # O(o)
    if xs is not None:  # O(1)
        return xs  # O(1)
    names: list[str] = []  # O(1)
    reasons: dict[str, tuple[str, int]] = {}  # O(1)
    py = _parse_pytest(lines, rc)  # O(o)
    for ln in lines if rc and py is None else []:  # names are failures: only a red exit collects them | O(o)
        for pat in NAME_PATTERNS:  # O(1)
            m = re.match(pat, ln)  # O(w)
            if m and re.search(r"\s[\d.]+s$", m.group(1)):  # go's `FAIL<TAB>package<TAB>0.003s` summary line is not a test | O(1)
                break  # O(1)
            if m and m.group(1) not in names and len(names) < 50:  # O(1)
                names.append(m.group(1)[:120])  # O(1)
                break  # O(1)
    blob = "\n".join(lines)  # O(o)
    summary = [ln for ln in lines if re.match(r"\s*Tests:?\s+\d", ln)]  # vitest `Tests  3 failed | 15 passed (18)`, jest `Tests: 3 failed, 15 passed, 18 total` | O(o)
    if py is not None:  # pytest: the last summary line and the short summary ids | O(1)
        passed, failed, skipped, names, reasons = py  # O(1)
    elif summary:  # the runner's own total wins over per-file and per-test lines | O(1)
        part = lambda word: sum(int(x) for x in re.findall(rf"(\d+)\s+{word}\b", summary[-1]))  # O(w)
        passed, failed, skipped = part("passed"), part("failed"), part("skipped") + part("todo") + part("pending")  # O(w)
    else:  # O(1)
        count = lambda word: sum(int(x) for x in re.findall(rf"(?<![=:])\b(\d+)\s+{word}\b", blob)) + sum(int(x) for x in re.findall(rf"\b{word}\s*[=:]\s*(\d+)", blob, re.I))  # "7 passed", "passed=7", "Passed: 7" | O(o)
        passed = count("passed") + count("passing")  # vitest, jest, cargo, dotnet, mocha, key=value | O(o)
        passed += len(re.findall(r"^ok\s+\S+", blob, re.M))  # go: one line per package | O(o)
        failed = max(count("failed") + count("failing"), len(names) if rc else 0)  # O(o)
        skipped = sum(int(x) for x in re.findall(r"(\d+)\s+(?:skipped|pending)", blob))  # O(o)
    counted = bool(passed or failed or skipped)  # O(1)
    if rc and not failed:  # a red exit with nothing parsed is one failure, not counted | O(1)
        failed = 1  # O(1)
    empty = "" if counted else next((ln.strip() for ln in lines if re.search(r"\bno tests? (?:files? )?(?:found|ran|to run)|\b0 tests? (?:ran|run|found)|\bno matching tests?(?: cases?)?\b", ln, re.I)), "")  # the runner's own "no tests" line | O(o)
    return {"passed": passed, "failed": failed, "skipped": skipped, "names": names, "tail": lines[-40:], "empty": empty, "counted": counted, "reasons": reasons, **_error_marker(lines)}  # O(1)


