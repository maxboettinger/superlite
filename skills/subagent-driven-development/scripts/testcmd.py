def read_config(root: Path):  # O(file)
    p = root / CONFIG  # O(1)
    try:  # O(1)
        d = json.loads(p.read_text(encoding="utf-8"))  # O(file)
    except FileNotFoundError:  # O(1)
        return None  # O(1)
    except (OSError, ValueError) as e:  # the file exists but cannot be used | O(1)
        print(f"test-cmd.json ignored: {e}", file=sys.stderr)  # O(1)
        return None  # O(1)
    if isinstance(d, dict) and d.get("test"):  # O(1)
        return d  # O(1)
    print('test-cmd.json ignored: needs a JSON object with a "test" command', file=sys.stderr)  # O(1)
    return None  # O(1)


def _main_checkout_root(root: Path):  # the main checkout's folder when root is a linked worktree, else None | O(1)
    try:  # O(1)
        out = subprocess.run(["git", "-C", str(root), "rev-parse", "--git-common-dir"], capture_output=True, text=True, timeout=10)  # O(1)
        if out.returncode != 0 or not out.stdout.strip():  # O(1)
            return None  # O(1)
        common = (Path(root) / out.stdout.strip()).resolve()  # O(1)
    except (OSError, ValueError, subprocess.SubprocessError):  # O(1)
        return None  # O(1)
    if common == (Path(root) / ".git").resolve():  # the main checkout itself | O(1)
        return None  # O(1)
    return common.parent  # O(1)


def main_checkout_config(root: Path):  # config of the main checkout when root is a linked worktree | O(file)
    main = _main_checkout_root(root)  # O(1)
    return read_config(main) if main else None  # O(file)


def user_config_path() -> Path:  # read at call time, never cached | O(1)
    env = os.environ.get("SUPERLITE_USER_TEST_CMD")  # O(1)
    return Path(env) if env else Path.home() / ".config" / "superlite" / "test-cmd.json"  # O(1)


def shown(path: Path) -> str:  # the path with the home folder as ~ | O(1)
    s, home = str(path), str(Path.home())  # O(1)
    return "~" + s[len(home):] if s == home or s.startswith(home + os.sep) else s  # O(1)


def read_user_config(language: str):  # the user-level entry for a language, or None | O(file)
    p = user_config_path()  # O(1)
    try:  # O(1)
        d = json.loads(p.read_text(encoding="utf-8"))  # O(file)
    except FileNotFoundError:  # O(1)
        return None  # O(1)
    except (OSError, ValueError) as e:  # O(1)
        print(f"user test-cmd.json ignored ({shown(p)}): {e}", file=sys.stderr)  # O(1)
        return None  # O(1)
    if not isinstance(d, dict):  # O(1)
        print(f"user test-cmd.json ignored ({shown(p)}): needs a JSON object keyed by language", file=sys.stderr)  # O(1)
        return None  # O(1)
    entry = d.get(language)  # O(1)
    if entry is None:  # O(1)
        return None  # O(1)
    if not (isinstance(entry, dict) and isinstance(entry.get("test"), str) and entry["test"]):  # O(1)
        print(f'user test-cmd.json ignored for {language} ({shown(p)}): needs a JSON object with a "test" command', file=sys.stderr)  # O(1)
        return None  # O(1)
    return {**entry, "language": language}  # O(1)


def record_seed(wt) -> bool:  # remember the seeded bytes so config_source can tell an unedited copy | O(file)
    wt = Path(wt)  # O(1)
    src = wt / CONFIG  # O(1)
    if not src.is_file():  # O(1)
        return False  # O(1)
    try:  # O(1)
        dst = wt / SEEDED  # O(1)
        tmp = dst.with_name(dst.name + ".tmp")  # O(1)
        tmp.write_bytes(src.read_bytes())  # O(file)
        os.replace(tmp, dst)  # O(1)
    except OSError as e:  # O(1)
        print(f"test-cmd.json seed not recorded in {wt}: {e}", file=sys.stderr)  # O(1)
        return False  # O(1)
    return True  # O(1)


def _seed_state(root: Path):  # -> (none | same | follows | own, main test-cmd path or None) | O(file)
    copy = Path(root) / CONFIG  # O(1)
    main = _main_checkout_root(Path(root)) if copy.is_file() else None  # O(1)
    if main is None or not (main / CONFIG).is_file():  # O(1)
        return "none", None  # O(1)
    try:  # O(1)
        mine, theirs = copy.read_bytes(), (main / CONFIG).read_bytes()  # O(file)
        rec = (Path(root) / SEEDED).read_bytes() if (Path(root) / SEEDED).is_file() else None  # O(file)
    except OSError:  # O(1)
        return "none", None  # O(1)
    if mine == theirs:  # O(1)
        return "same", main / CONFIG  # O(1)
    return ("follows" if rec is not None and rec == mine else "own"), main / CONFIG  # O(1)


def seed_note(root) -> str:  # one line when the main checkout's test-cmd.json and this worktree's copy are in play together | O(file)
    state, mp = _seed_state(Path(root))  # O(file)
    if state == "own":  # O(1)
        return f"this worktree's .superlite/test-cmd.json differs from the main checkout's {mp} and is the one that runs; delete it to follow the main checkout's"  # O(1)
    if state == "follows" and read_config(mp.parent.parent) is not None:  # O(file)
        return f"the main checkout's {mp} changed since it was seeded here, so runs follow it; if this branch predates that change, merge the default branch first: the new command may need its fixes"  # O(1)
    return ""  # O(1)


_SAID_FILE: set = set()  # (root, origin, key, value) already noted in this process | O(1)
FILE_TYPO = re.compile(r"(?<!\$)\{file\}")  # {file} but not the shell's ${file} | O(1)


def file_slot_note(cfg: dict, origin: str, root: Path) -> None:  # one stderr note per config key that holds {file} | O(1)
    for key in ("test", "test_file"):  # O(1)
        value = cfg.get(key)  # O(1)
        if not isinstance(value, str) or not FILE_TYPO.search(value):  # O(len)
            continue  # O(1)
        mark = (str(Path(root).resolve()), origin, key, value)  # O(1)
        if mark in _SAID_FILE:  # O(1)
            continue  # O(1)
        _SAID_FILE.add(mark)  # O(1)
        print(f'testcmd: {origin}: "{key}" holds {{file}}; the placeholder for --fast paths is {{files}}', file=sys.stderr)  # O(1)


def config_source(root: Path):  # -> (config | None, source, origin): project file, main checkout's, user entry, detection | O(m + f)
    cfg, src, origin = _config_source(root)  # O(m + f)
    if cfg is not None and src in ("test-cmd.json", "user"):  # O(1)
        file_slot_note(cfg, origin, root)  # O(1)
    return cfg, src, origin  # O(1)


def _config_source(root: Path):  # O(m + f)
    root = Path(root)  # O(1)
    cfg = read_config(root)  # O(file)
    if cfg is not None:  # O(1)
        if (root / SEEDED).is_file():  # git is spawned only when a seed record exists | O(1)
            state, mp = _seed_state(root)  # O(file)
            mcfg = read_config(mp.parent.parent) if state == "follows" else None  # O(file)
            if mcfg is not None:  # an unedited seeded copy follows the main checkout's file | O(1)
                return mcfg, "test-cmd.json", str(mp)  # O(1)
        return cfg, "test-cmd.json", CONFIG  # O(1)
    main = _main_checkout_root(root)  # O(1)
    cfg = read_config(main) if main else None  # O(file)
    if cfg is not None:  # O(1)
        return cfg, "test-cmd.json", str(main / CONFIG)  # O(1)
    mx = detect_maxapp(root)  # a .maxapp is the project's own declaration, ahead of the user entry | O(file)
    if mx is not None:  # O(1)
        return mx, "markers", MAXAPP_FILE  # O(1)
    det = detect(root)  # O(m + f)
    lang = det.get("language") if det is not None else None  # O(1)
    if lang is None and root.is_dir() and any(q.name.endswith((".xcodeproj", ".xcworkspace")) for q in root.iterdir()):  # Xcode: no detected command, still swift | O(entries)
        lang = "swift"  # O(1)
    cfg = read_user_config(lang) if lang else None  # O(file)
    if cfg is not None:  # O(1)
        return cfg, "user", shown(user_config_path())  # O(1)
    return (det, "markers", "detection") if det is not None else (None, "markers", "none")  # O(1)


def names_filter(paths) -> str:  # basenames without suffix joined by | | O(p)
    return "|".join(Path(p).stem for p in paths)  # O(p)


SUITE_DECL = re.compile(r"^(?:(?:public|internal|private|fileprivate|open|final|indirect)\s+)*(class|struct|enum|actor|extension)\s+(\w+)([^{]*)")  # O(1)


def strip_swift(text: str) -> str:  # blank comments and string contents, keep length and newlines | O(n)
    out = list(text)  # O(n)
    n = len(text)  # O(1)
    i = 0  # O(1)

    def blank(a: int, b: int) -> None:  # O(b-a)
        for k in range(a, min(b, n)):  # O(b-a)
            if out[k] not in "\r\n":  # O(1)
                out[k] = " "  # O(1)

    def string_at(i: int):  # (first content index, content end, index after the literal) or None for code | O(n)
        h = i  # O(1)
        while h < n and text[h] == "#":  # O(h)
            h += 1  # O(1)
        if h >= n or text[h] != '"':  # O(1)
            return None  # O(1)
        hashes = h - i  # O(1)
        multi = text.startswith('"""', h)  # O(1)
        q = h + (3 if multi else 1)  # first content char | O(1)
        close = ('"""' if multi else '"') + "#" * hashes  # O(1)
        esc = "\\" + "#" * hashes  # O(1)
        j, depth = q, 0  # depth: open parens of an interpolation | O(1)
        while j < n:  # O(n)
            if depth == 0 and text.startswith(close, j):  # O(1)
                break  # O(1)
            if text.startswith(esc, j):  # O(1)
                j += len(esc)  # O(1)
                if depth == 0 and j < n and text[j] == "(":  # interpolation starts | O(1)
                    depth, j = 1, j + 1  # O(1)
                elif j < n:  # escaped char | O(1)
                    j += 1  # O(1)
                continue  # O(1)
            if depth and text[j] in '"#':  # a string nested in the interpolation | O(n)
                inner = string_at(j)  # O(n)
                if inner is not None:  # O(1)
                    j = inner[2]  # O(1)
                    continue  # O(1)
            if depth and text[j] == "(":  # O(1)
                depth += 1  # O(1)
            elif depth and text[j] == ")":  # O(1)
                depth -= 1  # O(1)
            elif not multi and depth == 0 and text[j] in "\r\n":  # unterminated single-line string | O(1)
                break  # O(1)
            j += 1  # O(1)
        return q, j, (min(j + len(close), n) if text.startswith(close, j) else j)  # O(1)

    while i < n:  # O(n)
        c = text[i]  # O(1)
        if text.startswith("//", i):  # line comment | O(1)
            j = i  # O(1)
            while j < n and text[j] not in "\r\n":  # O(n)
                j += 1  # O(1)
            blank(i, j)  # O(n)
            i = j  # O(1)
        elif text.startswith("/*", i):  # block comment, nests | O(1)
            depth, j = 1, i + 2  # O(1)
            while j < n and depth:  # O(n)
                if text.startswith("/*", j):  # O(1)
                    depth, j = depth + 1, j + 2  # O(1)
                elif text.startswith("*/", j):  # O(1)
                    depth, j = depth - 1, j + 2  # O(1)
                else:  # O(1)
                    j += 1  # O(1)
            blank(i, j)  # O(n)
            i = j  # O(1)
        elif c == "#" or c == '"':  # string start, maybe raw | O(1)
            r = string_at(i)  # O(n)
            if r is None:  # a # directive, code | O(1)
                i += 1  # O(1)
                continue  # O(1)
            blank(r[0], r[1])  # O(n)
            i = r[2]  # O(1)
        else:  # O(1)
            i += 1  # O(1)
    return "".join(out)  # O(n)


def _swift_scan(text: str):  # (type entries [name, first, last, marked, xctest, top level, rest of line, opened, depth], free @Test funcs [name, line], stripped lines), 1-based, by brace depth | O(n)
    lines = strip_swift(text).splitlines()  # O(n)
    types: list[list] = []  # O(1)
    frees: list[list] = []  # O(1)
    stack: list[list] = []  # type entries still open, innermost last | O(1)
    attrs: list[str] = []  # attribute lines seen right before a declaration | O(1)
    depth = 0  # O(1)
    for i, raw in enumerate(lines):  # O(n)
        ln = raw.strip()  # O(len)
        if ln.startswith("@") and not re.match(r"@\w+(?:\(.*\))?\s+\S", ln):  # attribute on its own line | O(1)
            attrs.append(ln)  # O(1)
            continue  # O(1)
        head = re.sub(r"^(?:@\w+(?:\((?:[^()]|\((?:[^()]|\([^()]*\))*\))*\))?\s+)+", "", ln)  # attributes inline before the keyword | O(w)
        inline = ln[:len(ln) - len(head)]  # O(1)
        fn = re.match(r"^(?:\w+\s+)*func\s+(\w+)\s*\(", head)  # O(1)
        if fn and depth == 0 and not stack and any(a.startswith("@Test") for a in attrs + [inline]):  # O(a)
            frees.append([fn.group(1) + "()", i + 1])  # O(1)
        m = SUITE_DECL.match(head)  # O(1)
        if m:  # O(1)
            marked = any(a.startswith("@Suite") for a in attrs) or inline.startswith("@Suite")  # O(a)
            entry = [m.group(2), i + 1, len(lines), marked, "XCTestCase" in m.group(3), depth == 0 and not stack, head[m.end(2):], False, depth]  # O(1)
            types.append(entry)  # O(1)
            stack.append(entry)  # O(1)
        if ln:  # any other non-blank line ends the attribute run | O(1)
            attrs = []  # O(1)
        for ch in raw:  # O(len)
            if ch == "{":  # O(1)
                depth += 1  # O(1)
                for e in stack:  # O(s)
                    e[7] = True  # O(1)
            elif ch == "}":  # O(1)
                depth -= 1  # O(1)
                while stack and stack[-1][7] and depth <= stack[-1][8]:  # O(s)
                    stack.pop()[2] = i + 1  # O(1)
    return types, frees, lines  # O(1)


def swift_types(text: str) -> list[tuple[str, int, int]]:  # every class/struct/enum/actor/extension as (name, first line, last line), 1-based, nested ones too, in order | O(n)
    return [(e[0], e[1], e[2]) for e in _swift_scan(text)[0]]  # O(t)


def swift_suites(text: str) -> list[str]:  # outermost test suites at any indent, free @Test funcs as name() | O(n)
    types, frees, lines = _swift_scan(text)  # O(n)
    found: list[tuple[int, str]] = []  # (line, name) | O(1)
    for e in types:  # O(t)
        if not e[5]:  # nested types are covered by their outermost type | O(1)
            continue  # O(1)
        body = "\n".join([e[6]] + lines[e[1]:e[2]])  # the declaration line itself counts, for a one-line type | O(n)
        if e[3] or e[4] or re.search(r"@Test\b|\bfunc test", body):  # O(n)
            found.append((e[1], e[0]))  # O(1)
    found += [(f[1], f[0]) for f in frees]  # O(f)
    out: list[str] = []  # O(1)
    for _, name in sorted(found, key=lambda x: x[0]):  # O(s log s)
        if name not in out:  # O(s)
            out.append(name)  # O(1)
    return out  # O(1)


PLIST_WORD = re.compile(r"[\w$+/:.\-@~]+")  # O(1)
PLIST_DATA = re.compile(r"<[0-9a-fA-F\s]*>")  # O(1)
PLIST_ESC = {"n": "\n", "t": "\t", "r": "\r", "a": "\a", "b": "\b", "f": "\f", "v": "\v"}  # O(1)


def parse_plist(text: str):  # OpenStep (old-style ASCII) plist -> dict | list | str; ValueError when malformed | O(n)
    n = len(text)  # O(1)
    pos = [0]  # O(1)

    def skip() -> None:  # whitespace and comments | O(n)
        while pos[0] < n:  # O(n)
            c = text[pos[0]]  # O(1)
            if c.isspace():  # O(1)
                pos[0] += 1  # O(1)
            elif text.startswith("//", pos[0]):  # O(1)
                e = text.find("\n", pos[0])  # O(n)
                pos[0] = n if e < 0 else e + 1  # O(1)
            elif text.startswith("/*", pos[0]):  # O(1)
                e = text.find("*/", pos[0] + 2)  # O(n)
                if e < 0:  # O(1)
                    raise ValueError("unterminated comment")  # O(1)
                pos[0] = e + 2  # O(1)
            else:  # O(1)
                return  # O(1)

    def string() -> str:  # quoted string at pos | O(n)
        i, out = pos[0] + 1, []  # O(1)
        while i < n:  # O(n)
            c = text[i]  # O(1)
            if c == '"':  # O(1)
                pos[0] = i + 1  # O(1)
                return "".join(out)  # O(n)
            if c == "\\":  # O(1)
                i += 1  # O(1)
                if i >= n:  # O(1)
                    break  # O(1)
                c = text[i]  # O(1)
                if c in "uU" and re.fullmatch(r"[0-9a-fA-F]{4}", text[i + 1:i + 5]):  # O(1)
                    out.append(chr(int(text[i + 1:i + 5], 16)))  # O(1)
                    i += 4  # O(1)
                else:  # O(1)
                    out.append(PLIST_ESC.get(c, c))  # O(1)
            else:  # O(1)
                out.append(c)  # O(1)
            i += 1  # O(1)
        raise ValueError("unterminated string")  # O(1)

    def word() -> str:  # O(w)
        m = PLIST_WORD.match(text, pos[0])  # O(w)
        if not m:  # O(1)
            raise ValueError(f"unexpected character at {pos[0]}")  # O(1)
        pos[0] = m.end()  # O(1)
        return m.group()  # O(1)

    def expect(ch: str) -> None:  # O(1)
        skip()  # O(n)
        if pos[0] >= n or text[pos[0]] != ch:  # O(1)
            raise ValueError(f"expected {ch!r} at {pos[0]}")  # O(1)
        pos[0] += 1  # O(1)

    def value():  # O(n)
        skip()  # O(n)
        if pos[0] >= n:  # O(1)
            raise ValueError("unexpected end")  # O(1)
        c = text[pos[0]]  # O(1)
        if c == "{":  # O(1)
            pos[0] += 1  # O(1)
            d: dict = {}  # O(1)
            while True:  # O(n)
                skip()  # O(n)
                if pos[0] >= n:  # O(1)
                    raise ValueError("unterminated dict")  # O(1)
                if text[pos[0]] == "}":  # O(1)
                    pos[0] += 1  # O(1)
                    return d  # O(1)
                key = string() if text[pos[0]] == '"' else word()  # O(w)
                expect("=")  # O(n)
                d[key] = value()  # O(n)
                expect(";")  # O(n)
        if c == "(":  # O(1)
            pos[0] += 1  # O(1)
            arr: list = []  # O(1)
            while True:  # O(n)
                skip()  # O(n)
                if pos[0] >= n:  # O(1)
                    raise ValueError("unterminated array")  # O(1)
                if text[pos[0]] == ")":  # O(1)
                    pos[0] += 1  # O(1)
                    return arr  # O(1)
                arr.append(value())  # O(n)
                skip()  # O(n)
                if pos[0] < n and text[pos[0]] == ",":  # O(1)
                    pos[0] += 1  # O(1)
                elif pos[0] >= n or text[pos[0]] != ")":  # O(1)
                    raise ValueError(f"expected ',' or ')' at {pos[0]}")  # O(1)
        if c == '"':  # O(1)
            return string()  # O(n)
        if c == "<":  # O(1)
            m = PLIST_DATA.match(text, pos[0])  # O(n)
            if not m:  # O(1)
                raise ValueError(f"bad data at {pos[0]}")  # O(1)
            pos[0] = m.end()  # O(1)
            return m.group()  # O(1)
        return word()  # O(w)

    result = value()  # O(n)
    skip()  # O(n)
    if pos[0] < n:  # O(1)
        raise ValueError(f"trailing text at {pos[0]}")  # O(1)
    return result  # O(1)


TEST_PRODUCTS = {"com.apple.product-type.bundle.unit-test", "com.apple.product-type.bundle.ui-testing"}  # O(1)
NO_SCAN = SKIP_DIRS | {"Pods", "Carthage", "DerivedData"}  # O(1)


def _ids(v) -> list[str]:  # the string members of a plist array, else none | O(len)
    return [x for x in v if isinstance(x, str)] if isinstance(v, list) else []  # O(len)


def pbx_members(pbxproj: Path, root: Path):  # (test target names, file -> targets, folder -> targets) of one project, root-relative | O(objects)
    data = parse_plist(pbxproj.read_text(encoding="utf-8", errors="replace"))  # O(file)
    objs = data.get("objects") if isinstance(data, dict) else None  # O(1)
    if not isinstance(objs, dict):  # O(1)
        return set(), {}, {}  # O(1)
    proj = objs.get(data.get("rootObject")) if isinstance(data.get("rootObject"), str) else None  # O(1)
    proj = proj if isinstance(proj, dict) else {}  # O(1)
    pdp = proj.get("projectDirPath")  # O(1)
    base = os.path.abspath(os.path.join(pbxproj.parent.parent, pdp if isinstance(pdp, str) else ""))  # project folder | O(len)
    rootabs = os.path.abspath(root)  # O(len)
    main = proj.get("mainGroup")  # O(1)
    parent: dict[str, str] = {}  # O(1)
    for oid, o in objs.items():  # O(objects)
        if isinstance(o, dict):  # O(1)
            for c in _ids(o.get("children")):  # O(children)
                parent.setdefault(c, oid)  # O(1)

    def abs_path(oid: str, seen: tuple):  # absolute path of an object through its group chain, else None | O(depth)
        o = objs.get(oid)  # O(1)
        if not isinstance(o, dict) or oid in seen:  # dangling id or parent cycle | O(depth)
            return None  # O(1)
        tree = o.get("sourceTree") if isinstance(o.get("sourceTree"), str) else "<group>"  # O(1)
        p = o.get("path") if isinstance(o.get("path"), str) else ""  # O(1)
        if tree == "<group>":  # O(1)
            par = parent.get(oid)  # O(1)
            b = base if oid == main or par is None else abs_path(par, seen + (oid,))  # O(depth)
            return None if b is None else os.path.normpath(os.path.join(b, p))  # O(len)
        if tree == "SOURCE_ROOT":  # O(1)
            return os.path.normpath(os.path.join(base, p))  # O(len)
        if tree == "<absolute>" and os.path.isabs(p):  # O(1)
            return os.path.normpath(p)  # O(len)
        return None  # O(1)

    def rel(oid) -> str | None:  # root-relative posix path, None outside root | O(depth)
        a = abs_path(oid, ()) if isinstance(oid, str) else None  # O(depth)
        if a is None:  # O(1)
            return None  # O(1)
        r = os.path.relpath(a, rootabs).replace(os.sep, "/")  # O(len)
        return None if r == ".." or r.startswith("../") else r  # O(1)

    tests: set[str] = set()  # O(1)
    files: dict[str, set[str]] = {}  # O(1)
    dirs: dict[str, set[str]] = {}  # O(1)
    for o in objs.values():  # O(objects)
        if not isinstance(o, dict) or o.get("isa") != "PBXNativeTarget" or not isinstance(o.get("name"), str) or not o["name"]:  # O(1)
            continue  # O(1)
        name = o["name"]  # O(1)
        if o.get("productType") in TEST_PRODUCTS:  # O(1)
            tests.add(name)  # O(1)
        for ph in _ids(o.get("buildPhases")):  # O(phases)
            pho = objs.get(ph)  # O(1)
            if not isinstance(pho, dict) or pho.get("isa") != "PBXSourcesBuildPhase":  # O(1)
                continue  # O(1)
            for bf in _ids(pho.get("files")):  # O(files)
                bfo = objs.get(bf)  # O(1)
                r = rel(bfo.get("fileRef")) if isinstance(bfo, dict) else None  # O(depth)
                if r and r != ".":  # O(1)
                    files.setdefault(r, set()).add(name)  # O(1)
                    d = posixpath.dirname(r)  # O(len)
                    if d:  # O(1)
                        dirs.setdefault(d, set()).add(name)  # O(1)
        for g in _ids(o.get("fileSystemSynchronizedGroups")):  # O(groups)
            r = rel(g)  # O(depth)
            if r and r != ".":  # O(1)
                dirs.setdefault(r, set()).add(name)  # O(1)
    return tests, files, dirs  # O(1)


TEST_TARGET_CALL = re.compile(r"\.testTarget\s*\(")  # O(1)
ARG_NAME = re.compile(r'\bname\s*:\s*"')  # O(1)
ARG_PATH = re.compile(r'\bpath\s*:\s*"')  # O(1)


def package_test_targets(text: str):  # [(name, folder relative to the package)] of the .testTarget(...) calls | O(n)
    code = strip_swift(text)  # comments and string contents blanked, same length | O(n)
    out: list[tuple[str, str]] = []  # O(1)
    for m in TEST_TARGET_CALL.finditer(code):  # O(calls)
        depth, i = 1, m.end()  # O(1)
        top = []  # chars of the call's own level: nested brackets blanked | O(n)
        while i < len(code) and depth:  # O(n)
            c = code[i]  # O(1)
            if c in "([{":  # O(1)
                depth += 1  # O(1)
            elif c in ")]}":  # O(1)
                depth -= 1  # O(1)
            top.append(c if depth == 1 and c not in "([{)]}" else " ")  # O(1)
            i += 1  # O(1)
        start = m.end()  # O(1)
        flat = "".join(top)  # O(n)

        def arg(pat):  # the string literal after `label:` at the call's own level, from the original text | O(n)
            a = pat.search(flat)  # O(n)
            if not a:  # O(1)
                return None  # O(1)
            q = start + a.end()  # O(1)
            return text[q:code.find('"', q)]  # O(n)

        name = arg(ARG_NAME)  # O(n)
        if name:  # O(1)
            out.append((name, arg(ARG_PATH) or f"Tests/{name}"))  # O(1)
    return out  # O(1)


def swift_target_map(root: Path) -> dict:  # {"tests": names, "files": file -> targets, "dirs": folder -> targets}, root-relative | O(files)
    root = Path(root)  # O(1)
    tests: set[str] = set()  # O(1)
    files: dict[str, set[str]] = {}  # O(1)
    dirs: dict[str, set[str]] = {}  # O(1)

    def scan(d: Path, depth: int) -> None:  # the root and two folder levels below; never into an .xcodeproj | O(entries)
        try:  # O(1)
            entries = sorted(d.iterdir())  # O(entries)
        except OSError:  # O(1)
            return  # O(1)
        for e in entries:  # O(entries)
            if e.name == "Package.swift" and e.is_file():  # O(1)
                try:  # O(1)
                    found = package_test_targets(e.read_text(encoding="utf-8", errors="replace"))  # O(file)
                except OSError:  # O(1)
                    continue  # O(1)
                prefix = os.path.relpath(d, root).replace(os.sep, "/")  # O(len)
                for name, folder in found:  # O(calls)
                    tests.add(name)  # O(1)
                    key = posixpath.normpath(posixpath.join("" if prefix == "." else prefix, folder))  # O(len)
                    dirs.setdefault(key, set()).add(name)  # O(1)
            elif e.is_dir() and e.name.endswith(".xcodeproj"):  # O(1)
                try:  # O(1)
                    t, f, dd = pbx_members(e / "project.pbxproj", root)  # O(file)
                except (OSError, ValueError):  # unreadable or unparsable project: skipped | O(1)
                    continue  # O(1)
                tests.update(t)  # O(t)
                for src, dst in ((f, files), (dd, dirs)):  # O(1)
                    for k, v in src.items():  # O(k)
                        dst.setdefault(k, set()).update(v)  # O(v)
            elif e.is_dir() and depth < 2 and not e.name.startswith(".") and e.name not in NO_SCAN:  # O(1)
                scan(e, depth + 1)  # O(subtree)

    scan(root, 0)  # O(files)
    return {"tests": tests, "files": files, "dirs": dirs}  # O(1)


def swift_test_targets(root: Path) -> set[str]:  # test target names of Xcode projects and Swift packages | O(files)
    return swift_target_map(root)["tests"]  # O(files)


def owning_test_target(path: str, targets: set[str], members: dict | None = None):  # test target a Swift path belongs to, else None | O(depth)
    p = path.replace("\\", "/")  # O(len)
    dirs = p.split("/")[:-1]  # O(len)
    if members is not None:  # target membership first | O(depth)
        hit = members["files"].get(p)  # O(1)
        if hit is not None:  # O(1)
            return min(hit & members["tests"], default=None)  # O(hit)
        for i in range(len(dirs), 0, -1):  # deepest folder first | O(depth)
            s = members["dirs"].get("/".join(dirs[:i]))  # O(len)
            if s:  # O(1)
                return min(s) if s <= members["tests"] else None  # O(s)
    if targets:  # O(1)
        return next((d for d in reversed(dirs) if d in targets), None)  # O(depth)
    if "Tests" in dirs:  # SwiftPM Tests/<Target>/ | O(depth)
        i = dirs.index("Tests")  # O(depth)
        if i + 1 < len(dirs):  # O(1)
            return dirs[i + 1]  # O(1)
    return next((d for d in reversed(dirs) if d.endswith("Tests") and d != "Tests"), None)  # O(depth)


class UnknownTestName(ValueError):  # test names no Swift test target declares | O(1)
    def __init__(self, names):  # O(n)
        self.names = list(names)  # O(n)
        super().__init__(f"test name not found: {', '.join(self.names)} (no Swift test target declares that suite)")  # O(n)


TEST_NAME = re.compile(r"[A-Za-z_]\w*(?:/[A-Za-z_]\w*(?:\(\))?){0,2}")  # O(1)


def is_test_name(arg: str, root) -> bool:  # a Swift test name (Suite, Suite/test, Target/Suite), not an existing path | O(1)
    return bool(TEST_NAME.fullmatch(arg)) and not (Path(root) / arg).exists()  # O(1)


def suite_index(root, members: dict | None = None) -> dict:  # suite name -> sorted test targets, from the Swift files in test targets | O(files)
    root = Path(root)  # O(1)
    members = members if members is not None else swift_target_map(root)  # O(files)
    found: dict[str, set[str]] = {}  # O(1)
    skip = NO_SCAN | {".build", "DerivedData"}  # O(1)
    for dirpath, dirnames, filenames in os.walk(root):  # O(files)
        dirnames[:] = sorted(d for d in dirnames if not d.startswith(".") and d not in skip)  # O(d log d)
        for fn in sorted(filenames):  # O(f)
            if not fn.endswith(".swift"):  # O(1)
                continue  # O(1)
            rel = os.path.relpath(os.path.join(dirpath, fn), root).replace(os.sep, "/")  # O(len)
            tgt = owning_test_target(rel, members["tests"], members)  # O(depth)
            if tgt is None:  # O(1)
                continue  # O(1)
            try:  # O(1)
                text = (root / rel).read_text(encoding="utf-8", errors="replace")  # O(file)
            except OSError:  # O(1)
                continue  # O(1)
            for name in swift_suites(text):  # O(s)
                if not name.endswith("()"):  # free @Test functions are no suites | O(1)
                    found.setdefault(name, set()).add(tgt)  # O(1)
    return {k: sorted(v) for k, v in found.items()}  # O(s)


def name_ids(root, names: list[str]) -> list[str]:  # Target/Suite[/test] ids of test names; UnknownTestName when none declares one | O(n*files)
    members = swift_target_map(Path(root))  # O(files)
    index = suite_index(root, members)  # O(files)
    out: list[str] = []  # O(1)
    unknown: list[str] = []  # O(1)
    for name in names:  # O(n)
        parts = name.split("/")  # O(len)
        got: list[str] = []  # O(1)
        if parts[0] in members["tests"] and (len(parts) == 1 or parts[0] in index.get(parts[1], [])):  # a target-first name keeps its form | O(t)
            got = [name]  # O(1)
        elif parts[0] in index:  # a suite-first name gets each declaring target | O(t)
            got = [f"{t}/{name}" for t in index[parts[0]]]  # O(t)
        if not got:  # O(1)
            unknown.append(name)  # O(1)
        out += [g for g in got if g not in out]  # O(t*out)
    if unknown:  # O(1)
        raise UnknownTestName(unknown)  # O(1)
    return out  # O(out)


def swift_names(root, paths: list[str]) -> list[str] | None:  # names for a swift test --filter; None when a path is in no test target | O(p*files)
    root = Path(root)  # O(1)
    out: list[str] = []  # O(1)
    members = None  # O(1)
    for p in paths:  # O(p)
        got: list[str] = []  # O(1)
        if is_test_name(p, root):  # O(1)
            name_ids(root, [p])  # validates: UnknownTestName | O(files)
            parts = p.split("/")  # O(len)
            tests = swift_target_map(root)["tests"]  # O(files)
            got = [".".join(parts[:2]) + "".join("/" + x for x in parts[2:])] if parts[0] in tests and len(parts) > 1 else [p]  # O(len)
        else:  # O(1)
            rel = p.replace("\\", "/")  # O(len)
            try:  # O(1)
                text = (root / rel).read_text(encoding="utf-8", errors="replace") if rel.endswith(".swift") else None  # O(file)
            except OSError:  # O(1)
                text = None  # O(1)
            if text is None:  # unreadable or not Swift: its stem | O(1)
                got = [Path(rel).stem]  # O(1)
            else:  # O(1)
                got = [x[:-2] if x.endswith("()") else x for x in swift_suites(text)]  # O(n)
                if not got and re.search(r"Tests?$", Path(rel).stem):  # a suite-less file named like a test class keeps its stem | O(1)
                    got = [Path(rel).stem]  # O(1)
                if not got:  # O(1)
                    members = members or swift_target_map(root)  # O(files)
                    tgt = owning_test_target(posixpath.normpath(rel), members["tests"], members)  # O(depth)
                    if tgt is None:  # O(1)
                        return None  # O(1)
                    got = [tgt]  # O(1)
        out += [g for g in got if g not in out]  # O(g*out)
    return out  # O(out)


def xcode_only_testing(root: Path, paths: list[str], notes: list | None = None):  # -> (shell-quoted -only-testing ids, None) or (None, first unmapped path) | O(p + files)
    root = Path(root)  # O(1)
    members = swift_target_map(root)  # O(files)
    ids: list[str] = []  # O(1)
    for p in paths:  # O(p)
        if is_test_name(p, root):  # a test name maps to ids; UnknownTestName is never widened | O(files)
            for want in name_ids(root, [p]):  # O(t)
                one = shlex.quote(f"-only-testing:{want}")  # O(len)
                if one not in ids:  # O(ids)
                    ids.append(one)  # O(1)
            continue  # O(1)
        rel = p.replace("\\", "/")  # O(len)
        if Path(rel).is_absolute():  # O(1)
            try:  # O(1)
                rel = Path(rel).resolve().relative_to(root.resolve()).as_posix()  # O(len)
            except ValueError:  # outside root, kept as given | O(1)
                pass  # O(1)
        rel = posixpath.normpath(rel)  # "./a" and "a/../a" match the root-relative keys | O(len)
        tgt = owning_test_target(rel, members["tests"], members)  # O(depth)
        if tgt is None:  # O(1)
            return None, rel  # O(1)
        suites: list[str] = []  # O(1)
        if rel.endswith(".swift"):  # O(1)
            try:  # O(1)
                suites = swift_suites((root / rel).read_text(encoding="utf-8", errors="replace"))  # O(file)
            except OSError:  # O(1)
                suites = []  # O(1)
            if not suites and notes is not None:  # O(1)
                notes.append(f"{rel} declares no test suite; using -only-testing:{tgt}")  # O(1)
        for want in ([f"{tgt}/{s}" for s in suites] or [tgt]):  # O(s)
            one = shlex.quote(f"-only-testing:{want}")  # O(len)
            if one not in ids:  # O(ids)
                ids.append(one)  # O(1)
    return " ".join(ids), None  # O(ids)


def only_testing(paths, root=".", notes: list | None = None):  # shell-quoted Target/Suite ids; None when a path is in no test target | O(p*n)
    if not paths:  # O(1)
        return ""  # O(1)
    said: list[str] = notes if notes is not None else []  # O(1)
    ids, unmapped = xcode_only_testing(Path(root), list(paths), said)  # O(p + files)
    if ids is None:  # O(1)
        said.append(f"{unmapped} is not in a test target; running the unfiltered test command")  # O(1)
    if notes is None:  # no list: say it on stderr | O(notes)
        for n in said:  # O(notes)
            print(f"testcmd: {n}", file=sys.stderr)  # O(1)
    return ids  # O(1)


def missing_reason(root) -> str:  # why no test command resolved, with a hint for Xcode projects and the setup proposal | O(entries)
    root = Path(root)  # O(1)
    names = [q.name for q in root.iterdir()] if root.is_dir() else []  # O(entries)
    prop = propose(root)  # O(m + f)
    tail = (f"; /superlite:setup proposes `{prop['config']['test']}` ({prop['from']}) and writes it to {CONFIG}" if prop
            else f"; /superlite:setup writes {CONFIG} from the command you name")  # O(1)
    if any(n.endswith((".xcodeproj", ".xcworkspace")) for n in names):  # O(entries)
        dest = "-destination 'platform=iOS Simulator,name=iPhone 16'"  # O(1)
        return (f'no test command found: add .superlite/test-cmd.json, e.g. {{"language": "swift", "test": "xcodebuild test -scheme <Scheme> {dest}", '
                f'"test_file": "xcodebuild test -scheme <Scheme> {dest} {{only_testing}}"}}; or a "swift" entry in {shown(user_config_path())} for every project without its own' + tail)  # O(1)
    return 'no test command found: add .superlite/test-cmd.json with {"test": ..., "test_file": ...} or a marker file' + tail  # O(1)


SCRIPT_NAMES = ("test.sh", "test", "tests.sh", "tests", "run-tests.sh", "run-tests", "run_tests.sh")  # O(1)
SCRIPT_DIRS = ("scripts", "script", "bin")  # O(1)
MAKE_TEST = re.compile(r"^test\s*:(?!=)", re.M)  # O(1)


def _find_script(root: Path):  # root-relative path of the project's own test script, else None | O(entries)
    try:  # O(1)
        folders = {q.name.lower(): q for q in root.iterdir() if q.is_dir()}  # O(entries)
    except OSError:  # O(1)
        return None  # O(1)
    for name in SCRIPT_NAMES:  # O(1)
        for d in SCRIPT_DIRS:  # O(1)
            folder = folders.get(d)  # O(1)
            if folder is None:  # O(1)
                continue  # O(1)
            try:  # O(1)
                hit = next((q for q in sorted(folder.iterdir()) if q.is_file() and q.name.lower() == name), None)  # O(entries)
            except OSError:  # O(1)
                hit = None  # O(1)
            if hit is not None:  # O(1)
                return f"{folder.name}/{hit.name}", hit  # O(1)
    return None  # O(1)


def _has_swift_markers(root: Path) -> bool:  # an Xcode project here or a Package.swift one or two folder levels down | O(entries)
    try:  # O(1)
        top = list(root.iterdir())  # O(entries)
        if any(q.name.endswith((".xcodeproj", ".xcworkspace")) for q in top) or (root / "Package.swift").exists():  # O(entries)
            return True  # O(1)
        for d in top:  # O(entries)
            if not d.is_dir() or d.name in SKIP_DIRS or d.name.startswith("."):  # O(1)
                continue  # O(1)
            if (d / "Package.swift").exists():  # O(1)
                return True  # O(1)
            for e in d.iterdir():  # O(entries)
                if e.is_dir() and e.name not in SKIP_DIRS and not e.name.startswith(".") and (e / "Package.swift").exists():  # O(1)
                    return True  # O(1)
    except OSError:  # O(1)
        return False  # O(1)
    return False  # O(1)


def _language_for(root: Path, det) -> str | None:  # O(entries)
    if det is not None and det.get("language"):  # O(1)
        return det["language"]  # O(1)
    return "swift" if _has_swift_markers(root) else None  # O(entries)


def propose(root: Path):  # {"config", "from"} for the project's own test command, or None | O(m + f)
    root = Path(root)  # O(1)
    cfg, source, _ = config_source(root)  # O(m + f)
    if source == "test-cmd.json":  # O(1)
        return None  # O(1)
    det = detect(root)  # O(m + f)
    lang = _language_for(root, det)  # O(entries)
    mx = detect_maxapp(root)  # O(file)
    if mx is not None:  # O(1)
        return {"config": {k: v for k, v in mx.items() if v != ""}, "from": MAXAPP_FILE}  # O(1)
    found = _find_script(root)  # O(entries)
    if found is not None:  # O(1)
        rel, path = found  # O(1)
        cmd = rel if os.access(path, os.X_OK) else f"bash {rel}"  # O(1)
        out = {"language": lang} if lang else {}  # O(1)
        out["test"] = cmd  # O(1)
        if lang == "swift":  # O(1)
            try:  # O(1)
                with open(path, encoding="utf-8", errors="ignore") as fh:  # O(1)
                    text = fh.read(65536)  # O(1)
            except OSError:  # O(1)
                text = ""  # O(1)
            if "xcodebuild" in text and "$@" in text:  # O(1)
                out["test_file"] = f"{cmd} {{only_testing}}"  # O(1)
        return {"config": out, "from": f"project test script {rel}"}  # O(1)
    for mk in ("Makefile", "makefile", "GNUmakefile"):  # O(1)
        try:  # O(1)
            text = (root / mk).read_text(encoding="utf-8", errors="ignore")  # O(file)
        except OSError:  # O(1)
            continue  # O(1)
        if MAKE_TEST.search(text):  # O(file)
            out = {"language": lang} if lang else {}  # O(1)
            out["test"] = "make test"  # O(1)
            return {"config": out, "from": "Makefile target test"}  # O(1)
    if det is not None and det.get("language") != "python":  # O(1)
        keep = {k: v for k, v in det.items() if v != "" and not (k == "env" and not v)}  # O(1)
        return {"config": keep, "from": "detection"}  # O(1)
    return None  # O(1)


