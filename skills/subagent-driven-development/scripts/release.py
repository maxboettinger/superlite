#!/usr/bin/env python3
"""Release command: minor and major bumps through `sl release`.

`release.py minor|major [--dry-run] [--no-golden] [--accept-flags] [--root R]`. Order: preflight, scoreboard, golden
run, then bump, validate, commit, tag, push, GitHub release, stable. Exit codes: 0 released or dry run fine, 1 golden
red, 2 refused, 3 a step failed after the bump, 4 scoreboard flags need --accept-flags. Stdlib only.
"""
from __future__ import annotations

import argparse  # O(1)
import json  # O(1)
import os  # O(1)
import re  # O(1)
import subprocess  # O(1)
import sys  # O(1)
import time  # O(1)
from pathlib import Path  # O(1)

sys.path.insert(0, str(Path(__file__).resolve().parent))  # O(1)
import golden  # noqa: E402  O(1)
import golden_case  # noqa: E402  O(1)
import batch_cost  # noqa: E402  O(1)
import release_tag  # noqa: E402  O(1)
import scoreboard  # noqa: E402  O(1)
import ship_lock  # noqa: E402  O(1)

LEVEL_CASES = {"minor": ("small", "typical"), "major": ("small", "typical", "large")}  # O(1)
WORKER_MSG = "release runs only in Max's own session, never in a lead or worker"  # O(1)
GIT_ENV = ("GIT_DIR", "GIT_INDEX_FILE", "GIT_WORK_TREE")  # O(1)


def _run(cmd: list, cwd=None, timeout=None) -> tuple[int, str]:  # O(command)
    """Run one external command; return (exit code, output). A missing binary is 127."""
    env = {k: v for k, v in os.environ.items() if k not in GIT_ENV}  # O(env)
    try:  # O(1)
        p = subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True, timeout=timeout)  # O(command)
    except FileNotFoundError:  # O(1)
        return 127, f"{cmd[0]}: not found"  # O(1)
    except subprocess.TimeoutExpired:  # O(1)
        return 124, f"{cmd[0]}: timed out"  # O(1)
    return p.returncode, p.stdout if p.returncode == 0 else p.stdout + p.stderr  # O(output)


def _ver(v: str) -> tuple:  # O(1)
    if not re.fullmatch(r"\d+\.\d+\.\d+", v):  # O(1)
        raise ValueError(f"bad version {v!r}")  # O(1)
    return tuple(int(x) for x in v.split("."))  # O(1)


def next_version(cur: str, level: str) -> str:  # O(1)
    x, y, z = _ver(cur)  # O(1)
    if level == "minor":  # O(1)
        return f"{x}.{y + 1}.0"  # O(1)
    if level == "major":  # O(1)
        return f"{x + 1}.0.0"  # O(1)
    if level == "patch":  # O(1)
        return f"{x}.{y}.{z + 1}"  # O(1)
    raise ValueError(f"bad level {level!r}")  # O(1)


def _branch(root: Path) -> str:  # O(1)
    rc, out = _run(["git", "symbolic-ref", "--short", "refs/remotes/origin/HEAD"], cwd=root)  # O(1)
    out = out.strip()  # O(1)
    return out[len("origin/"):] if rc == 0 and out.startswith("origin/") and len(out) > 7 else "main"  # O(1)


def preflight(root: Path, env: dict) -> list:  # O(files)
    """Return the reasons a release must not start (empty list: clear)."""
    if env.get("SUPERLITE_FLEET_WORKER"):  # O(1)
        return [WORKER_MSG]  # O(1)
    b, out = _branch(root), []  # O(1)
    rc, cur = _run(["git", "rev-parse", "--abbrev-ref", "HEAD"], cwd=root)  # O(1)
    if rc != 0 or cur.strip() != b:  # O(1)
        out.append(f"not on {b} (on {cur.strip() or '?'})")  # O(1)
    rc, st = _run(["git", "status", "--porcelain"], cwd=root)  # O(files)
    if rc != 0:  # O(1)
        out.append("git status failed")  # O(1)
    out += [f"uncommitted: {ln[3:]}" for ln in st.splitlines() if ln.strip()]  # O(files)
    if _run(["git", "fetch", "origin"], cwd=root)[0] != 0:  # O(1)
        out.append("git fetch origin failed")  # O(1)
        return out  # O(1)
    rc, cnt = _run(["git", "rev-list", "--left-right", "--count", f"HEAD...origin/{b}"], cwd=root)  # O(1)
    parts = cnt.split()  # O(1)
    if rc != 0 or len(parts) != 2 or not all(p.isdigit() for p in parts):  # O(1)
        out.append(f"cannot compare {b} with origin/{b}")  # O(1)
    else:  # O(1)
        if int(parts[1]):  # O(1)
            out.append(f"{b} is behind origin/{b}")  # O(1)
        if int(parts[0]):  # O(1)
            out.append(f"{b} is ahead of origin/{b}")  # O(1)
    return out  # O(1)


def _moved(root: Path, b: str) -> str:  # O(1)
    """Fetch again and return why the tree is no longer level with origin ('' when level)."""
    if _run(["git", "fetch", "origin"], cwd=root)[0] != 0:  # O(1)
        return "git fetch origin failed"  # O(1)
    rc, cnt = _run(["git", "rev-list", "--left-right", "--count", f"HEAD...origin/{b}"], cwd=root)  # O(1)
    parts = cnt.split()  # O(1)
    if rc != 0 or len(parts) != 2 or not all(p.isdigit() for p in parts):  # O(1)
        return f"cannot compare {b} with origin/{b}"  # O(1)
    return f"{b} moved during the golden run; pull and run again" if any(int(p) for p in parts) else ""  # O(1)


def _current_version(root: Path) -> str:  # O(1)
    cfg = json.loads((root / ".version-bump.json").read_text(encoding="utf-8"))  # O(1)
    ent = next(e for e in cfg["files"] if e["path"].endswith(".json"))  # O(files)
    node = json.loads((root / ent["path"]).read_text(encoding="utf-8"))  # O(1)
    for k in ent["field"].split("."):  # O(depth)
        node = node[int(k)] if isinstance(node, list) else node[k]  # O(1)
    return str(node)  # O(1)


def _notes_start(root: Path, tags: list, new: str) -> str | None:  # O(tags)
    """Tag the generated notes start at (#1042): the newest tag below `new` that `sl release` made
    (its commit subject is `Release vX.Y.0`), else the newest vX.Y.Z tag below `new`, else None."""
    below = []  # O(1)
    for t in tags:  # O(tags)
        m = re.fullmatch(r"v(\d+\.\d+\.\d+)", t)  # O(1)
        if m and _ver(m.group(1)) < _ver(new):  # O(1)
            below.append(m.group(1))  # O(1)
    below.sort(key=_ver, reverse=True)  # O(tags log tags)
    for x in below:  # O(tags) one git call per X.Y.0 candidate, newest first
        if _ver(x)[2] == 0:  # O(1)
            rc, subj = _run(["git", "log", "-1", "--format=%s", f"refs/tags/v{x}"], cwd=root)  # O(1)
            if rc == 0 and subj.strip() == f"Release v{x}":  # O(1)
                return f"v{x}"  # O(1)
    return f"v{below[0]}" if below else None  # O(1)


def _err(msg: str) -> None:  # O(1)
    print(msg, file=sys.stderr)  # O(1)


def _golden(root: Path, level: str) -> int:  # O(cases)
    want = LEVEL_CASES[level]  # O(1)
    have = {c["id"]: c for c in golden_case.cases(root)}  # O(cases)
    missing = [i for i in want if i not in have]  # O(1)
    if missing:  # O(1)
        _err(f"golden case missing: {', '.join(missing)}")  # O(1)
        return 2  # O(1)
    out = golden.results_file(root)  # O(1)
    try:  # O(1)
        rows = golden.run([have[i] for i in want], root, out)  # O(cases * run)
    except Exception as e:  # noqa: BLE001  O(1)
        _err(f"golden run failed: {e}")  # O(1)
        return 1  # O(1)
    final = {r.get("case"): r for r in rows}  # O(rows) the last attempt per case decides (a rerun may pass)
    bad = [r for r in final.values() if not r.get("passed")]  # O(rows)
    if bad or any(i not in final for i in want):  # O(1)
        for r in bad:  # O(rows)
            _err(f"golden {r.get('case')} red: {'; '.join(r.get('why') or [])}")  # O(1)
        if not bad:  # O(1)
            _err("golden run returned too few rows")  # O(1)
        return 1  # O(1)
    return 0  # O(1)


def _publish(root: Path, new: str, b: str, notes: str | None) -> int:  # O(steps)
    v, state = f"v{new}", {"commit": False, "pushed": False}  # O(1)

    def fail(what: str, out: str) -> int:  # O(1)
        _err(f"{what} failed: {out.strip()[:300]}")  # O(1)
        if state["pushed"]:  # O(1) bump and tag are public already, a reset would diverge from origin
            _err(f"{v} is pushed; finish by hand (gh release create {v} --generate-notes)")  # O(1)
        elif state["commit"]:  # O(1)
            _err(f"undo: git reset --hard origin/{b} && git tag -d {v}")  # O(1)
        else:  # O(1)
            _err(f"undo: git reset --hard origin/{b}")  # O(1)
        return 3  # O(1)

    rc, out = _run(["bash", str(root / "scripts" / "bump-version.sh"), new], cwd=root)  # O(1)
    if rc != 0:  # O(1)
        return fail("bump", out)  # O(1)
    rc, out = _run(["claude", "plugin", "validate", "--strict", "."], cwd=root)  # O(1)
    if rc == 127:  # O(1)
        _err("validate: skipped (claude not found)")  # O(1)
    elif rc != 0:  # O(1)
        return fail("validate", out)  # O(1)
    rc, out = _run(["git", "commit", "-am", f"Release {v}"], cwd=root)  # O(1)
    if rc != 0:  # O(1)
        return fail("commit", out)  # O(1)
    state["commit"] = True  # O(1)
    rc, sha = _run(["git", "rev-parse", "HEAD"], cwd=root)  # O(1)
    if rc != 0 or not sha.strip():  # O(1)
        return fail("rev-parse HEAD", sha)  # O(1)
    try:  # O(1)
        made = release_tag.tag(root, new, sha.strip(), push=False)  # O(1)
    except Exception as e:  # noqa: BLE001  O(1)
        return fail("tag", str(e))  # O(1)
    if not str(made).endswith("created"):  # O(1) tag() returns a status line, never raises
        return fail("tag", str(made))  # O(1)
    rc, out = _run(["git", "push", "--atomic", "origin", f"HEAD:{b}", f"refs/tags/{v}"], cwd=root)  # O(1)
    if rc != 0:  # O(1)
        return fail("push", out)  # O(1)
    state["pushed"] = True  # O(1)
    cmd = ["gh", "release", "create", v, "--generate-notes", "--title", f"superlite {new}"]  # O(1)
    rc, out = _run(cmd + (["--notes-start-tag", notes] if notes else []), cwd=root)  # O(1)
    if rc != 0:  # O(1)
        return fail("gh release", out)  # O(1)
    rc, out = _run(["git", "push", "origin", f"{v}^{{commit}}:refs/heads/stable"], cwd=root)  # O(1)
    if rc != 0:  # O(1)
        _err(f"warning: stable not moved: {out.strip()[:300]}")  # O(1)
    print(f"released {v}")  # O(1)
    return 0  # O(1)


def _ship_lock(root: Path):  # O(1)
    """The path of the ship lock a lead's `sl backlog ship` takes for this repository, or None when the repo is unknown.

    backlog_ship locks with `ship_lock.lock_path(backlog.json["repo"])` (the nameWithOwner `sl backlog` records from
    `gh repo view`); read the same record, else ask gh the same question, never a different key."""
    import backlog_state as bs  # O(1)
    try:  # O(1)
        repo = bs.load(bs.path(bs.main_root(root))).get("repo")  # O(file)
    except RuntimeError:  # O(1)
        repo = ""  # O(1)
    if not repo:  # O(1)
        rc, out = _run(["gh", "repo", "view", "--json", "nameWithOwner", "-q", ".nameWithOwner"], cwd=root)  # O(1)
        repo = out.strip() if rc == 0 else ""  # O(1)
    try:  # O(1)
        return ship_lock.lock_path(repo) if repo else None  # O(1)
    except ValueError:  # O(1)
        return None  # O(1)


def main(argv: list) -> int:  # O(release)
    ap = argparse.ArgumentParser(prog="release.py", add_help=True)  # O(1)
    ap.add_argument("level", choices=["patch", "minor", "major"])  # O(1)
    ap.add_argument("--dry-run", action="store_true")  # O(1)
    ap.add_argument("--no-golden", action="store_true")  # O(1)
    ap.add_argument("--accept-flags", action="store_true")  # O(1)
    ap.add_argument("--root", default=".")  # O(1)
    try:  # O(1)
        a = ap.parse_args(argv)  # O(1)
    except SystemExit as e:  # O(1)
        return 0 if e.code == 0 else 2  # O(1)
    if a.level == "patch":  # O(1)
        _err("patch versions are released by leads at ship")  # O(1)
        return 2  # O(1)
    if a.no_golden and not a.dry_run:  # O(1)
        _err("--no-golden is only allowed with --dry-run")  # O(1)
        return 2  # O(1)
    root = Path(a.root).resolve()  # O(1)
    problems = preflight(root, os.environ)  # O(files)
    if problems:  # O(1)
        for p in problems:  # O(problems)
            _err(f"refused: {p}")  # O(1)
        return 2  # O(1)
    try:  # O(1)
        cur = _current_version(root)  # O(1)
        new = next_version(cur, a.level)  # O(1)
        if release_tag.level(cur, new) != a.level:  # O(1)
            raise ValueError(f"{cur} -> {new} is not a {a.level} step")  # O(1)
    except (OSError, ValueError, KeyError, StopIteration, IndexError) as e:  # O(1)
        _err(f"refused: {e}")  # O(1)
        return 2  # O(1)
    b, v = _branch(root), f"v{new}"  # O(1)
    rc, tl = _run(["git", "tag", "-l", "v*"], cwd=root)  # O(tags)
    tags = tl.split() if rc == 0 else []  # O(tags)
    if v in tags:  # O(1)
        _err(f"refused: tag {v} exists")  # O(1)
        return 2  # O(1)
    flags = scoreboard.board(batch_cost.read_rows(root)).get("flags") or []  # O(rows)
    if flags and not a.accept_flags:  # O(1)
        _err(f"scoreboard flags: {'; '.join(flags)}; rerun with --accept-flags")  # O(1)
        return 4  # O(1)
    lock = None  # O(1)
    if not a.dry_run:  # O(1) fail before the golden batch when a lead's ship holds the lock
        lock = _ship_lock(root)  # O(1)
        if lock is None:  # O(1)
            _err("refused: cannot name the repository for the ship lock (no backlog repo, gh repo view failed)")  # O(1)
            return 2  # O(1)
        h = ship_lock.holder(lock)  # O(1)
        if h and int(time.time() * 1000) - h["time"] <= ship_lock.STALE_MS:  # O(1) an older lock is stale, as acquire reads it
            _err(f"refused: ship lock held by {h.get('batch', '?')}")  # O(1)
            return 2  # O(1)
    if not a.no_golden:  # O(1)
        rc = _golden(root, a.level)  # O(cases * run)
        if rc:  # O(1)
            return rc  # O(1)
    notes = _notes_start(root, tags, new)  # O(tags)
    if a.dry_run:  # O(1)
        why = _moved(root, b)  # O(1)
        if why:  # O(1)
            _err(f"refused: {why}")  # O(1)
            return 2  # O(1)
        print(f"would release {v} (tag {v}, stable -> {v})")  # O(1)
        if notes:  # O(1)
            print(f"release notes start at {notes}")  # O(1)
        return 0  # O(1)
    owner = {"batch": "release", "lead": "release", "agent": None}  # O(1)
    r = ship_lock.acquire(lock, owner, None, int(time.time() * 1000))  # O(1)
    if not r["acquired"]:  # O(1)
        h = r.get("holder") or {}  # O(1)
        ship_lock.release(lock, "release")  # O(1) drop the queue entry acquire left
        _err(f"refused: ship lock held by {h.get('batch', '?')}")  # O(1)
        return 2  # O(1)
    try:  # O(1)
        why = _moved(root, b)  # O(1)
        if why:  # O(1)
            _err(f"refused: {why}")  # O(1)
            return 2  # O(1)
        return _publish(root, new, b, notes)  # O(steps)
    finally:  # O(1)
        ship_lock.release(lock, "release")  # O(1)


if __name__ == "__main__":  # O(1)
    sys.exit(main(sys.argv[1:]))  # O(1)
