#!/usr/bin/env python3
"""Finds the test or build command a busy worker waits on: its pane's shell, the process tree below it, `ps` (#909)."""

# Complexity notation:
# p = processes listed, w = workers, n = length of an argument line

import re  # O(1)
import subprocess  # O(1)
import sys  # O(1)
from pathlib import Path  # O(1)

sys.path.insert(0, str(Path(__file__).resolve().parent))  # O(1)
import herdr_client as hc  # noqa: E402 | O(1)

LABEL_MAX = 40  # a label is cut to this many characters | O(1)
INTERP = re.compile(r"^(python[\d.]*|bash|sh|node)$")  # programs that run a script named in their arguments | O(1)
BUILD = ("xcodebuild", "gradle", "gradlew")  # a build tool that is a command by itself | O(1)
SUBCMD = ("maxapp", "swift", "cargo", "go")  # a tool whose `test` or `build` is the command | O(1)
NODEPM = ("npm", "pnpm", "yarn", "bun")  # a package manager whose `test` is the command | O(1)


def _cut(text):  # at most LABEL_MAX characters, ended at a word when possible | O(n)
    if len(text) <= LABEL_MAX:  # O(1)
        return text  # O(1)
    head = text[:LABEL_MAX]  # O(1)
    if text[LABEL_MAX] != " " and " " in head:  # O(1)
        head = head.rsplit(" ", 1)[0]  # O(n)
    return head.rstrip()  # O(n)


def _script(words):  # (program, rest) of an interpreter line, or None when it runs inline code | O(n)
    i = 0  # O(1)
    while i < len(words):  # O(n)
        w = words[i]  # O(1)
        if w == "-c":  # O(1)
            return None  # O(1)
        if w == "-m" and i + 1 < len(words):  # O(1)
            return words[i + 1], words[i + 2:]  # O(n)
        if not w.startswith("-"):  # O(1)
            return re.sub(r"\.(py|js|sh)$", "", w.rsplit("/", 1)[-1]), words[i + 1:]  # O(n)
        i += 1  # O(1)
    return None  # O(1)


def label(args):  # the short name of a test or build command line, or None | O(n)
    words = str(args).split()  # O(n)
    if not words:  # O(1)
        return None  # O(1)
    b, rest = words[0].rsplit("/", 1)[-1], words[1:]  # O(n)
    if INTERP.match(b):  # O(1)
        got = _script(rest)  # O(n)
        if got is None:  # O(1)
            return None  # O(1)
        b, rest = got  # O(1)
    first = rest[0] if rest else ""  # O(1)
    if b == "run_tests":  # O(1)
        out = [b] + rest  # O(n)
    elif b == "sl" and first == "run_tests":  # O(1)
        out = rest  # O(1)
    elif b in ("pytest", "py.test"):  # O(1)
        out = ["pytest"] + rest  # O(n)
    elif b in BUILD:  # O(1)
        out = [b] + rest  # O(n)
    elif b in SUBCMD and first in ("test", "build"):  # O(1)
        out = [b] + rest  # O(n)
    elif b in NODEPM and (first == "test" or rest[:2] == ["run", "test"]):  # O(1)
        out = [b] + rest  # O(n)
    else:  # O(1)
        return None  # O(1)
    return _cut(" ".join(out))  # O(n)


def etime_s(text):  # ps etime ([[dd-]hh:]mm:ss) as seconds, or None | O(1)
    m = re.fullmatch(r"(?:(\d+)-)?(?:(\d+):)?(\d+):(\d+)", str(text).strip())  # O(1)
    if not m:  # O(1)
        return None  # O(1)
    d, h, mi, s = (int(x or 0) for x in m.groups())  # O(1)
    return ((d * 24 + h) * 60 + mi) * 60 + s  # O(1)


def waits_on(roots, procs):  # {worker: (label, seconds)} of the matching descendant nearest each root | O(p + w)
    kids = {}  # O(1)
    for pid, ppid, secs, args in procs:  # O(p)
        kids.setdefault(ppid, []).append((pid, secs, args))  # O(1)
    out = {}  # O(1)
    for wid, root in roots.items():  # O(w)
        level, seen = [root], {root}  # O(1)
        while level:  # O(p)
            nxt, hits = [], []  # O(1)
            for node in level:  # O(level)
                for pid, secs, args in kids.get(node, []):  # O(kids)
                    if pid in seen:  # O(1)
                        continue  # O(1)
                    seen.add(pid)  # O(1)
                    nxt.append(pid)  # O(1)
                    lab = label(args)  # O(n)
                    if lab:  # O(1)
                        hits.append((lab, secs))  # O(1)
            if hits:  # O(1)
                out[wid] = max(hits, key=lambda h: h[1])  # O(hits)
                break  # O(1)
            level = nxt  # O(1)
    return out  # O(w)


def _ps():  # one `ps` listing as (pid, ppid, seconds, args) | O(p)
    r = subprocess.run(["ps", "-axo", "pid=,ppid=,etime=,args="], capture_output=True, text=True, timeout=10, check=True)  # O(p)
    rows = []  # O(1)
    for line in r.stdout.splitlines():  # O(p)
        parts = line.split(None, 3)  # O(n)
        if len(parts) < 4 or not parts[0].isdigit() or not parts[1].isdigit():  # O(1)
            continue  # O(1)
        secs = etime_s(parts[2])  # O(1)
        if secs is not None:  # O(1)
            rows.append((int(parts[0]), int(parts[1]), secs, parts[3]))  # O(1)
    return rows  # O(p)


def suffixes(sd, workers):  # {worker: " waits on <label> <time>"} for busy local workers; any failure gives {} | O(w + p)
    roots = {}  # O(1)
    try:  # O(1)
        for wid, w in workers.items():  # O(w)
            if w.get("state") != "busy" or w.get("machine") or not w.get("pane_id"):  # O(1)
                continue  # O(1)
            info = hc._pick(hc.call(["pane", "process-info", "--pane", w["pane_id"]]), "process_info")  # O(1)
            roots[wid] = int(info["shell_pid"])  # O(1)
        if not roots:  # O(1)
            return {}  # O(1)
        found = waits_on(roots, _ps())  # O(p + w)
    except (hc.HerdrError, OSError, subprocess.SubprocessError, KeyError, TypeError, ValueError):  # O(1)
        return {}  # O(1)
    return {wid: f" waits on {lab} " + (f"{secs // 60} min" if secs >= 60 else f"{secs} s") for wid, (lab, secs) in found.items()}  # O(w)
