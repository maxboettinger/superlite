"""Turn shell command text into segments, one per simple command, for the coordinator guard (guard_judge.py).

    split(text) -> list[Segment]

A Segment holds the decoded words (quotes, backslashes and `$'...'` removed; a `$` expansion or backtick is kept as
written and flags the word in `dyn`), the redirects split off even when glued to a word (`rm>/dev/null x`; an fd number
or `{name}` before the operator is dropped), the heredoc bodies in order, the bodies of `$(...)`, backtick, `<(...)` and
`>(...)` substitutions (also those inside an unquoted heredoc body and in a redirect target), a `( ... )` group as one
`subshell` body, and `sep`, the separator after it (`&&`, `||`, `;`, `|`, `&`, a newline as `\\n`, or `""` for the last).
`{ ...; }` is flattened, comments and line continuations are dropped, CRLF reads as LF, `;;` and a stray `)` (a case
pattern) read as `;`. Nothing raises: an unterminated quote, `$(` or `${` makes the rest of the text one dyn word, and
nesting deeper than MAX_DEPTH does the same, so the caller sees an unknown word instead of a crash. No `shlex`: it cannot
keep redirects or heredocs. Stdlib only. A heredoc is read at the next newline of the same level. Each word and redirect
target carries a glob/brace flag (Segment.globs, Redirect.glob): its decoded text is a pattern, not the file it names.
"""
# Complexity notation:
#   n = characters of the text, w = words, d = nesting depth (at most MAX_DEPTH), h = heredocs on one line
import re  # O(1)

from guard_types import Redirect, Segment  # O(1)

__all__ = ["Redirect", "Segment", "split", "MAX_DEPTH"]  # O(1)

MAX_DEPTH = 64  # nested `$(`, `(` and `<(` levels lexed before the rest becomes one dyn word | O(1)
_BLANK = " \t"  # O(1)
_WORD_END = " \t\n;&|()<>"  # characters that end an unquoted word | O(1)
_NAME0 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz_"  # O(1)
_SPECIAL = "@*#?-!$0123456789"  # `$` followed by one of these (or a name start) is an expansion | O(1)
_FD = re.compile(r"\d+|\{[A-Za-z_][A-Za-z0-9_]*\}")  # an fd number or {name} glued before a redirect operator | O(1)
_ANSI = {"a": "\a", "b": "\b", "e": "\x1b", "E": "\x1b", "f": "\f", "n": "\n", "r": "\r", "t": "\t", "v": "\v",
         "\\": "\\", "'": "'", '"': '"', "?": "?"}  # `$'...'` single-character escapes | O(1)
_HEX = "0123456789abcdefABCDEF"  # O(1)
_CONTROL = {"if", "then", "elif", "else", "do", "while", "until", "!", "time", "coproc"}  # words before a command word | O(1)
_ASSIGN = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\+?=")  # a leading `NAME=value` word | O(1)


def _lead(words: list[str]) -> list[str]:  # O(prefix + 3)
    """The first words left after the control words and `NAME=value` assignments that may precede a command word
    (at most three: enough to see `function NAME`)."""
    k = 0  # O(1)
    while k < len(words) and (words[k] in _CONTROL or _ASSIGN.match(words[k])):  # O(prefix)
        k += 1  # O(1)
    return words[k:k + 3]  # O(1)


def _empty(seg: Segment) -> bool:  # O(1)
    return not (seg.words or seg.redirects or seg.subshell is not None)  # O(1)


def _new() -> Segment:  # O(1)
    return Segment([], [], [], [], [], None, "")  # O(1)


class _Lex:  # O(n) over one text, each character read once per nesting level it sits in
    def __init__(self, text: str):  # O(1)
        self.s = text  # O(1)
        self.n = len(text)  # O(1)
        self.i = 0  # O(1)
        self.depth = 0  # O(1)
        self.glob = False  # the last word read has an unquoted `*`, `?` or `[...]` | O(1)
        self.flag = ""  # the last word read: its Segment.globs flag | O(1)
        self.close_at = 0  # index of the `)` that ended the last nested parse (n when none) | O(1)

    # ---- words -------------------------------------------------------------------------------------------------
    def _backtick(self, i: int, bodies: list[str]) -> tuple[str, int]:  # O(n)
        """`i` is after the opening backtick: (original text through the closing one, index after it)."""
        s, n, j, out = self.s, self.n, i, []  # O(1)
        while j < n and s[j] != "`":  # O(n)
            if s[j] == "\\" and j + 1 < n and s[j + 1] in "`\\$":  # O(1)
                out.append(s[j + 1])  # O(1)
                j += 2  # O(1)
            else:  # O(1)
                out.append(s[j])  # O(1)
                j += 1  # O(1)
        bodies.append("".join(out))  # O(n)
        return s[i - 1:j + 1], min(j + 1, n)  # O(n)

    def _paren(self, i: int, bodies: list[str]) -> tuple[str, int, bool]:  # O(n) per level
        """`i` is after `$(`, `<(` or `>(`: (original text through the `)`, index after it, deeper than MAX_DEPTH)."""
        if self.depth >= MAX_DEPTH:  # too deep to lex: the rest stays visible to the caller as one body | O(1)
            bodies.append(self.s[i:])  # O(n)
            return self.s[i - 2:], self.n, True  # O(n)
        self.i = i  # O(1)
        self._parse(True)  # O(n)
        end = self.close_at  # O(1)
        bodies.append(self.s[i:end])  # O(n)
        return self.s[i - 2:end + 1], min(end + 1, self.n), end >= self.n  # O(n)

    def _brace(self, i: int, bodies: list[str], in_dq: bool = False) -> tuple[str, int, bool]:  # O(n)
        """`i` is after `${`: (original text through the matching `}`, index after it, unterminated). In double
        quotes a `'` is a plain character. Nesting through quotes counts toward MAX_DEPTH."""
        if self.depth >= MAX_DEPTH:  # too deep to lex: the rest stays visible to the caller as one body | O(1)
            bodies.append(self.s[i:])  # O(n)
            return self.s[i - 2:], self.n, True  # O(n)
        self.depth += 1  # O(1)
        try:  # O(n)
            return self._brace_scan(i, bodies, in_dq)  # O(n)
        finally:  # O(1)
            self.depth -= 1  # O(1)

    def _brace_scan(self, i: int, bodies: list[str], in_dq: bool) -> tuple[str, int, bool]:  # O(n)
        s, n, j, depth = self.s, self.n, i, 1  # O(1)
        while j < n:  # O(n)
            c = s[j]  # O(1)
            if c == "\\":  # O(1)
                j += 2  # O(1)
            elif c == "'" and not in_dq:  # O(1)
                k = s.find("'", j + 1)  # O(n)
                j = n if k < 0 else k + 1  # O(1)
            elif c == '"':  # O(1)
                j, _, _ = self._dquote(j + 1, [], bodies)  # O(n)
            elif c == "`":  # O(1)
                _, j = self._backtick(j + 1, bodies)  # O(n)
            elif c == "$" and s[j + 1:j + 2] == "(":  # O(1)
                _, j, _ = self._paren(j + 2, bodies)  # O(n)
            elif c == "{":  # O(1)
                depth += 1  # O(1)
                j += 1  # O(1)
            elif c == "}":  # O(1)
                depth -= 1  # O(1)
                j += 1  # O(1)
                if depth == 0:  # O(1)
                    return s[i - 2:j], j, False  # O(n)
            else:  # O(1)
                j += 1  # O(1)
        return s[i - 2:], n, True  # O(n)

    def _dollar(self, i: int, parts: list[str], bodies: list[str], in_dq: bool) -> tuple[int, bool, bool]:  # O(n)
        """`s[i]` is `$`: appends its text to parts; returns (next index, dyn, unterminated)."""
        s = self.s  # O(1)
        nx = s[i + 1:i + 2]  # O(1)
        if nx == "(":  # O(1)
            text, j, bad = self._paren(i + 2, bodies)  # O(n)
            parts.append(text)  # O(1)
            return j, True, bad  # O(1)
        if nx == "{":  # O(1)
            text, j, bad = self._brace(i + 2, bodies, in_dq)  # O(n)
            parts.append(text)  # O(1)
            return j, True, bad  # O(1)
        if nx and (nx in _NAME0 or nx in _SPECIAL or nx == "["):  # O(1)
            parts.append("$" + nx)  # O(1)
            return i + 2, True, False  # O(1)
        if nx == "'" and not in_dq:  # O(1)
            text, j, bad = self._ansi(i + 2)  # O(n)
            parts.append(text)  # O(n)
            return j, bad, bad  # O(1)
        parts.append("$")  # O(1)
        return i + 1, False, False  # O(1)

    def _ansi(self, i: int) -> tuple[str, int, bool]:  # O(n)
        """`i` is after `$'`: (decoded text, index after the closing quote, unterminated). A NUL ends the text like bash."""
        s, n, j = self.s, self.n, i  # O(1)
        out: list[str] = []  # O(1)
        raw = bytearray()  # \x80..\xff bytes, decoded as UTF-8 when text follows | O(1)
        cut = -1  # chunks kept when a NUL was seen | O(1)

        def flush() -> None:  # O(b)
            if raw:  # O(1)
                out.append(raw.decode("utf-8", "replace"))  # O(b)
                raw.clear()  # O(b)

        while j < n and s[j] != "'":  # O(n)
            c = s[j]  # O(1)
            e = s[j + 1] if c == "\\" and j + 1 < n else ""  # O(1)
            if not e:  # a plain character, or a backslash at the very end | O(1)
                flush()  # O(b)
                out.append(c)  # O(1)
                j += 1  # O(1)
            elif e in _ANSI:  # O(1)
                flush()  # O(b)
                out.append(_ANSI[e])  # O(1)
                j += 2  # O(1)
            elif e in "x01234567uU":  # \xHH, \NNN, \uHHHH, \UHHHHHHHH | O(1)
                k, limit, digits = (j + 1, 3, "01234567") if e in "01234567" else (
                    j + 2, {"x": 2, "u": 4, "U": 8}[e], _HEX)  # O(1)
                m = k  # O(1)
                while m < n and m - k < limit and s[m] in digits:  # O(1)
                    m += 1  # O(1)
                if m == k:  # no digits: the escape stays as written | O(1)
                    flush()  # O(b)
                    out.append(s[j:j + 2])  # O(1)
                    j += 2  # O(1)
                    continue  # O(1)
                v = int(s[k:m], 8 if e in "01234567" else 16)  # O(1)
                j = m  # O(1)
                if e in "uU":  # O(1)
                    flush()  # O(b)
                    out.append(chr(v) if 0 < v < 0x110000 else "\ufffd" if v else "")  # O(1)
                    cut = len(out) if v == 0 and cut < 0 else cut  # O(1)
                elif v & 0xFF == 0:  # O(1)
                    flush()  # O(b)
                    cut = len(out) if cut < 0 else cut  # O(1)
                elif v & 0xFF < 0x80:  # O(1)
                    flush()  # O(b)
                    out.append(chr(v & 0xFF))  # O(1)
                else:  # a byte of a multi-byte character | O(1)
                    raw.append(v & 0xFF)  # O(1)
            elif e == "c" and j + 2 < n:  # O(1)
                flush()  # O(b)
                out.append(chr(ord(s[j + 2]) & 0x1F))  # O(1)
                j += 3  # O(1)
            else:  # an unknown escape keeps its backslash | O(1)
                flush()  # O(b)
                out.append(s[j:j + 2])  # O(1)
                j += 2  # O(1)
        flush()  # O(b)
        return "".join(out if cut < 0 else out[:cut]), min(j + 1, n), j >= n  # O(n)

    def _dquote(self, i: int, parts: list[str], bodies: list[str]) -> tuple[int, bool, bool]:  # O(n)
        """`i` is after the opening `"`: appends the decoded text; returns (index after the closing quote, dyn, unterminated)."""
        s, n, j, dyn = self.s, self.n, i, False  # O(1)
        buf: list[str] = []  # O(1)
        while j < n:  # O(n)
            c = s[j]  # O(1)
            if c == '"':  # O(1)
                parts.append("".join(buf))  # O(n)
                return j + 1, dyn, False  # O(1)
            if c == "\\" and j + 1 < n:  # O(1)
                e = s[j + 1]  # O(1)
                if e == "\n":  # O(1)
                    pass  # a continuation joins the lines | O(1)
                elif e in '$`"\\':  # O(1)
                    buf.append(e)  # O(1)
                else:  # O(1)
                    buf.append("\\" + e)  # O(1)
                j += 2  # O(1)
            elif c == "$":  # O(1)
                part: list[str] = []  # O(1)
                j, d, bad = self._dollar(j, part, bodies, True)  # O(n)
                buf.extend(part)  # O(1)
                dyn = dyn or d  # O(1)
                if bad:  # O(1)
                    parts.append("".join(buf))  # O(n)
                    return self.n, True, True  # O(1)
            elif c == "`":  # O(1)
                text, j = self._backtick(j + 1, bodies)  # O(n)
                buf.append(text)  # O(1)
                dyn = True  # O(1)
            else:  # O(1)
                buf.append(c)  # O(1)
                j += 1  # O(1)
        parts.append("".join(buf))  # O(n)
        return n, True, True  # O(1)

    def _word(self, bodies: list[str]) -> tuple[str, bool, bool]:  # O(n)
        """Read one word from self.i: (decoded text, dyn, any part quoted or escaped). Collects substitution bodies."""
        s, n = self.s, self.n  # O(1)
        parts: list[str] = []  # O(1)
        dyn = quoted = False  # O(1)
        unq: list[str] = []  # the unquoted literal characters, for brace expansion and globs | O(1)
        while self.i < n:  # O(n)
            i = self.i  # O(1)
            c = s[i]  # O(1)
            if c in _WORD_END:  # O(1)
                break  # O(1)
            if c == "\\":  # O(1)
                if i + 1 >= n:  # O(1)
                    parts.append("\\")  # O(1)
                    self.i = n  # O(1)
                elif s[i + 1] == "\n":  # a continuation inside a word | O(1)
                    self.i = i + 2  # O(1)
                else:  # O(1)
                    parts.append(s[i + 1])  # O(1)
                    quoted = True  # O(1)
                    self.i = i + 2  # O(1)
            elif c == "'":  # O(1)
                quoted = True  # O(1)
                k = s.find("'", i + 1)  # O(n)
                if k < 0:  # O(1)
                    parts.append(s[i + 1:])  # O(n)
                    self.i = n  # O(1)
                    dyn = True  # O(1)
                else:  # O(1)
                    parts.append(s[i + 1:k])  # O(k - i)
                    self.i = k + 1  # O(1)
            elif c == '"':  # O(1)
                quoted = True  # O(1)
                self.i, d, bad = self._dquote(i + 1, parts, bodies)  # O(n)
                dyn = dyn or d or bad  # O(1)
            elif c == "$":  # O(1)
                if s[i + 1:i + 2] in ("'", '"'):  # O(1)
                    quoted = True  # O(1)
                if s[i + 1:i + 2] == '"':  # `$"..."`: drop the `$`, then the quoted string | O(1)
                    self.i = i + 1  # O(1)
                    continue  # O(1)
                self.i, d, bad = self._dollar(i, parts, bodies, False)  # O(n)
                dyn = dyn or d or bad  # O(1)
            elif c == "`":  # O(1)
                text, self.i = self._backtick(i + 1, bodies)  # O(n)
                parts.append(text)  # O(1)
                dyn = True  # O(1)
            else:  # O(1)
                parts.append(c)  # O(1)
                unq.append(c)  # O(1)
                self.i = i + 1  # O(1)
        u = "".join(unq)  # O(n)
        self.glob = "*" in u or "?" in u or ("[" in u and "]" in u[u.index("[") + 1:])  # a lone `[` is no glob | O(n)
        brace = "{" in u and "}" in u  # O(n)
        self.flag = ("u" if quoted else "b") if brace else ("g" if self.glob else "")  # O(1)
        if "{" in u and ("," in u or ".." in u):  # brace expansion `{rm,x}` builds words the text does not show | O(1)
            dyn = True  # O(1)
        return "".join(parts), dyn, quoted  # O(n)

    # ---- heredocs ----------------------------------------------------------------------------------------------
    def _substitutions(self, body: str) -> list[str]:  # O(len(body))
        """Command substitutions an unquoted heredoc body runs: `$(...)` and backticks, `\\` escapes the next character."""
        lx = _Lex(body)  # O(1)
        out: list[str] = []  # O(1)
        i, n = 0, len(body)  # O(1)
        while i < n:  # O(len(body))
            c = body[i]  # O(1)
            if c == "\\":  # O(1)
                i += 2  # O(1)
            elif c == "$" and body[i + 1:i + 2] == "(":  # O(1)
                _, i, _ = lx._paren(i + 2, out)  # O(len(body))
            elif c == "`":  # O(1)
                _, i = lx._backtick(i + 1, out)  # O(len(body))
            else:  # O(1)
                i += 1  # O(1)
        return out  # O(1)

    def _heredocs(self, pending: list[tuple[Segment, str, bool, bool]]) -> None:  # O(n)
        """Read each pending body, in order, from self.i (the start of the line after the operators' line)."""
        s, n = self.s, self.n  # O(1)
        for seg, delim, strip, quoted in pending:  # O(h)
            lines: list[str] = []  # O(1)
            while self.i < n:  # O(n)
                j = s.find("\n", self.i)  # O(n)
                end = n if j < 0 else j  # O(1)
                line = s[self.i:end]  # O(n)
                self.i = end + 1 if j >= 0 else n  # O(1)
                if strip:  # O(1)
                    line = line.lstrip("\t")  # O(n)
                if line == delim:  # a heredoc ends only on its exact delimiter line | O(1)
                    break  # O(1)
                lines.append(line + "\n")  # O(1)
            body = "".join(lines)  # O(n)
            seg.heredocs.append(body)  # O(1)
            if not quoted:  # O(1)
                seg.bodies.extend(self._substitutions(body))  # O(len(body))

    # ---- segments ----------------------------------------------------------------------------------------------
    def _redirect(self, cur: Segment, op: str, pending: list) -> None:  # O(n)
        """self.i is after the operator: read the target word and record the redirect (and a heredoc to read later)."""
        s, n = self.s, self.n  # O(1)
        while self.i < n and (s[self.i] in _BLANK or s.startswith("\\\n", self.i)):  # O(n)
            self.i += 2 if s[self.i] == "\\" else 1  # O(1)
        target, _, quoted = self._word(cur.bodies)  # O(n)
        cur.redirects.append(Redirect(op, target, self.flag))  # O(1)
        if op in ("<<", "<<-"):  # O(1)
            pending.append((cur, target, op == "<<-", quoted))  # O(1)

    def _parse(self, nested: bool) -> list[Segment]:  # O(n) over the characters it consumes
        """Lex from self.i. A nested parse stops after the `)` that closes it and records close_at."""
        s, n = self.s, self.n  # O(1)
        self.depth += 1  # O(1)
        segs: list[Segment] = []  # O(1)
        cur = _new()  # O(1)
        pending: list[tuple[Segment, str, bool, bool]] = []  # heredocs waiting for the end of their line | O(1)
        closed = False  # the current segment is a finished `( ... )` group: a word starts a new one | O(1)
        found = -1  # index of the `)` that ended a nested parse | O(1)
        lastw = (-1, "", False)  # (end index, text, quoted) of the last word: an fd number glues to a redirect | O(1)

        def finish(sep: str) -> None:  # O(1)
            nonlocal cur, closed  # O(1)
            cur.sep = sep  # O(1)
            segs.append(cur)  # O(1)
            cur = _new()  # O(1)
            closed = False  # O(1)

        while self.i < n:  # O(n)
            i = self.i  # O(1)
            c = s[i]  # O(1)
            if c in _BLANK:  # O(1)
                self.i = i + 1  # O(1)
            elif c == "\\" and s[i + 1:i + 2] == "\n":  # O(1)
                self.i = i + 2  # O(1)
            elif c == "#":  # a comment runs to the end of the line | O(1)
                k = s.find("\n", i)  # O(n)
                self.i = n if k < 0 else k  # O(1)
            elif c == "\n":  # O(1)
                self.i = i + 1  # O(1)
                if pending:  # O(1)
                    self._heredocs(pending)  # O(n)
                    pending = []  # O(1)
                if not _empty(cur):  # O(1)
                    finish("\n")  # O(1)
            elif c == ";":  # `;;`, `;&` and `;;&` end a case clause like `;` | O(1)
                self.i = i + (3 if s.startswith(";;&", i) else 2 if s[i + 1:i + 2] in (";", "&") else 1)  # O(1)
                if not _empty(cur):  # O(1)
                    finish(";")  # O(1)
            elif c == "&" and s[i + 1:i + 2] == ">":  # `&>` and `&>>` | O(1)
                op = "&>>" if s[i + 2:i + 3] == ">" else "&>"  # O(1)
                self.i = i + len(op)  # O(1)
                self._redirect(cur, op, pending)  # O(n)
            elif c == "&" or c == "|":  # O(1)
                two = s[i + 1:i + 2]  # O(1)
                if c == "&" and two == "&":  # O(1)
                    sep, step = "&&", 2  # O(1)
                elif c == "|" and two == "|":  # O(1)
                    sep, step = "||", 2  # O(1)
                elif c == "|" and two == "&":  # `|&` pipes stderr too | O(1)
                    sep, step = "|", 2  # O(1)
                else:  # O(1)
                    sep, step = c, 1  # O(1)
                self.i = i + step  # O(1)
                if not _empty(cur):  # O(1)
                    finish(sep)  # O(1)
            elif c == ")":  # O(1)
                self.i = i + 1  # O(1)
                if nested:  # O(1)
                    found = i  # O(1)
                    break  # O(1)
                if not _empty(cur):  # a stray `)` ends a case pattern | O(1)
                    finish(";")  # O(1)
            elif c == "(":  # a group, or the `()` of a function definition | O(1)
                if not _empty(cur):  # O(1)
                    finish(";")  # O(1)
                if self.depth >= MAX_DEPTH:  # too deep to lex: the rest is one group body for the caller | O(1)
                    cur.subshell = s[i + 1:].strip()  # O(n)
                    closed = True  # O(1)
                    self.i = n  # O(1)
                    continue  # O(1)
                self.i = i + 1  # O(1)
                self._parse(True)  # O(n)
                body = s[i + 1:self.close_at].strip()  # O(n)
                if body:  # an empty `()` is a function definition's parens | O(1)
                    cur.subshell = body  # O(n)
                    closed = True  # O(1)
            elif c in "<>" and s[i + 1:i + 2] == "(":  # process substitution: a word of its own | O(1)
                text, j, _ = self._paren(i + 2, cur.bodies)  # O(n)
                self.i = j  # O(1)
                if closed:  # O(1)
                    finish(";")  # O(1)
                cur.words.append(text)  # O(1)
                cur.dyn.append(True)  # O(1)
                cur.quoted.append(False)  # O(1)
                cur.globs.append("")  # O(1)
                lastw = (j, text, True)  # O(1)
            elif c in "<>":  # a redirect operator | O(1)
                if s.startswith("<<<", i):  # O(1)
                    op = "<<<"  # O(1)
                elif s.startswith("<<-", i):  # O(1)
                    op = "<<-"  # O(1)
                elif s.startswith("<<", i) or s.startswith(">>", i):  # O(1)
                    op = s[i:i + 2]  # O(1)
                elif s[i:i + 2] in ("<&", "<>", ">&", ">|"):  # O(1)
                    op = s[i:i + 2]  # O(1)
                else:  # O(1)
                    op = c  # O(1)
                if lastw[0] == i and not lastw[2] and _FD.fullmatch(lastw[1]) and cur.words \
                        and cur.words[-1] == lastw[1]:  # an fd number glued before the operator is no word | O(1)
                    cur.words.pop()  # O(1)
                    cur.dyn.pop()  # O(1)
                    cur.quoted.pop()  # O(1)
                    cur.globs.pop()  # O(1)
                self.i = i + len(op)  # O(1)
                self._redirect(cur, op, pending)  # O(n)
            else:  # a word | O(1)
                text, dyn, quoted = self._word(cur.bodies)  # O(n)
                flag = self.flag  # O(1)
                lastw = (self.i, text, quoted)  # O(1)
                if closed:  # O(1)
                    finish(";")  # O(1)
                lead = _lead(cur.words) if self.glob or text == "{" else ["-"]  # O(prefix)
                if self.glob and not lead:  # a glob in command position can name any program | O(1)
                    dyn = True  # O(1)
                if not quoted and text == "{" and (not lead or lead[0] == "function" and len(lead) == 2):  # O(1)
                    if lead:  # `function f {`: the definition ends here, its body is the next segment | O(1)
                        finish(";")  # O(1)
                    continue  # `{ ...; }` is flattened, also after `then`, `time`, `!` | O(1)
                if not cur.words and not quoted and text == "}":  # O(1)
                    continue  # O(1)
                cur.words.append(text)  # O(1)
                cur.dyn.append(dyn)  # O(1)
                cur.quoted.append(quoted)  # O(1)
                cur.globs.append(flag)  # O(1)
        if pending:  # a heredoc whose body never started | O(1)
            for seg, _, _, _ in pending:  # O(h)
                seg.heredocs.append("")  # O(1)
        if nested:  # O(1)
            self.close_at = found if found >= 0 else n  # O(1)
        self.depth -= 1  # O(1)
        if not _empty(cur):  # O(1)
            finish("")  # O(1)
        elif segs and segs[-1].sep == "\n":  # a trailing newline separates nothing | O(1)
            segs[-1].sep = ""  # O(1)
        return segs  # O(1)


def split(text: str) -> list[Segment]:  # O(n)
    """Segments of the command text, one per simple command; see the module docstring."""
    return _Lex(text.replace("\r\n", "\n"))._parse(False)  # O(n)
