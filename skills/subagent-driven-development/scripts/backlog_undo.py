#!/usr/bin/env python3
"""Backlog undo (B126): `unskip_issue` takes an issue off the skipped list; `reset_batch` stops a batch's lead, drops its
worktree and branch and sets the batch back to planned (or parks it, keeping the work, when git refuses). Stdlib only."""
import os  # O(1)
import time  # O(1)
from pathlib import Path  # O(1)

POLL_S = 1  # O(1)
STOP_WAIT_S = 10  # O(1)
CLEARED = ("reprompted", "question_reprompted", "gone_seen", "gone_workers", "open_issues", "followups", "undone",
           "cleaned", "parked_by", "parked_at")  # O(1)
START = "sl backlog start {b} starts a fresh lead in a fresh worktree"  # O(1)


def _sleep(s):  # O(s)
    time.sleep(s)  # O(s)


def _ref(n) -> str:  # O(1)
    return f"#{n}" if isinstance(n, int) else str(n)  # O(1)


def _arg(n) -> str:  # O(1)
    return str(n)  # O(1)


def unskip_issue(data: dict, n) -> str:  # O(skipped)
    sk = data.get("skipped", [])  # O(1)
    if n not in sk:  # O(skipped)
        raise ValueError(f"{_ref(n)} is not skipped")  # O(1)
    sk.remove(n)  # O(skipped)
    return (f"unskipped {_ref(n)}: the next sl backlog plan triages it again; "
            f"sl backlog plan --issues {_arg(n)} --add plans it now")  # O(1)


def _last(msg: str) -> str:  # O(len)
    ls = [x for x in str(msg).splitlines() if x.strip()]  # O(len)
    return ls[-1].strip()[:120] if ls else ""  # O(1)


def _refusal(b, bid):  # O(1)
    if os.environ.get("SUPERLITE_FLEET_WORKER"):  # O(1)
        return "refused: sl backlog reset runs only in the main session"  # O(1)
    if b is None:  # O(1)
        return f"refused: unknown batch {bid}"  # O(1)
    if b.get("state") == "shipped":  # O(1)
        return f"refused: {bid} is shipped"  # O(1)
    if b.get("merged") and b.get("pr"):  # O(1)
        return f"refused: {bid} merged PR #{b['pr']}; sl backlog wait records it as shipped"  # O(1)
    if b.get("state") == "planned" and not (b.get("lead") or b.get("worktree") or b.get("agent")):  # O(1)
        return f"refused: {bid} is planned; nothing to reset"  # O(1)
    return ""  # O(1)


def _stop_lead(root: Path, b: dict):  # O(w) | None when stopped, else the BLOCKED line
    import fleet  # O(1)
    import fleet_state  # O(1)
    bid, lead, agent = b["id"], b.get("lead"), b.get("agent")  # O(1)
    sd = Path(root) / ".superlite"  # O(1)
    pane = None  # O(1)
    if lead:  # O(1)
        try:  # O(1)
            pane = (fleet_state.workers(sd).get(lead) or {}).get("pane_id")  # O(w)
        except Exception:  # noqa: BLE001 | O(1)
            pane = None  # O(1)
        try:  # O(1)
            fleet.stop(sd, [lead])  # O(w)
        except (Exception, SystemExit):  # noqa: BLE001 | O(1)
            pass  # O(1)
    wsd = Path(b["worktree"]) / ".superlite" if b.get("worktree") else None  # O(1)
    if wsd is not None and wsd.is_dir() and Path(b["worktree"]).resolve() != Path(root).resolve():  # O(1)
        try:  # O(1)
            fleet.stop(wsd, all_=True)  # O(w)
        except (Exception, SystemExit):  # noqa: BLE001 | O(1)
            pass  # O(1)
    if not agent:  # O(1)
        return None  # O(1)
    try:  # O(1)
        live = agent in fleet.hc.agent_states()  # O(a)
        if live:  # O(1)
            for call, arg in ((fleet.hc.exit_agent, agent), (fleet.hc.close_pane, pane)):  # O(1)
                try:  # O(1)
                    if arg:  # O(1)
                        call(arg)  # O(1)
                except fleet.hc.HerdrError:  # O(1)
                    pass  # O(1)
            for _ in range(STOP_WAIT_S // POLL_S):  # O(STOP_WAIT_S)
                _sleep(POLL_S)  # O(POLL_S)
                live = agent in fleet.hc.agent_states()  # O(a)
                if not live:  # O(1)
                    break  # O(1)
    except fleet.hc.HerdrError as e:  # O(1)
        return f"BLOCKED: Herdr not reachable ({e}); {bid} keeps its state"  # O(1)
    if live:  # O(1)
        return f"BLOCKED: {bid} lead {lead} still runs after stop; close its Herdr pane, then rerun sl backlog reset {bid}"  # O(1)
    return None  # O(1)


def _git(root: Path, b: dict, discard: bool, lines: list) -> list:  # O(cmd) | what was kept
    import backlog_run  # O(1)
    bid, wt, br = b["id"], b.get("worktree"), b.get("branch")  # O(1)
    kept, wt_gone = [], True  # O(1)
    if wt:  # O(1)
        if Path(wt).resolve() == Path(root).resolve():  # O(1)
            lines.append(f"{bid} worktree {wt} kept: it is the main checkout")  # O(1)
            kept.append("worktree")  # O(1)
            wt_gone = False  # O(1)
        elif Path(wt).is_dir():  # O(1)
            fail = backlog_run.project_cleanup(Path(root), Path(wt), br or "", bid)  # O(cmd)
            if fail:  # O(1)
                lines.append(fail)  # O(1)
            rc, msg = backlog_run._run(["git", "worktree", "remove", *(["--force"] if discard else []), str(wt)], root)  # O(cmd)
            if rc:  # O(1)
                lines.append(f"{bid} worktree {wt} kept: {_last(msg)}")  # O(1)
                kept.append("worktree")  # O(1)
                wt_gone = False  # O(1)
            else:  # O(1)
                lines.append(f"{bid} worktree {wt} removed")  # O(1)
        else:  # O(1)
            backlog_run._run(["git", "worktree", "prune"], root)  # O(cmd)
            lines.append(f"{bid} worktree {wt} removed")  # O(1)
    if br and wt_gone:  # O(1)
        rc, _ = backlog_run._run(["git", "branch", "-D" if discard else "-d", br], root)  # O(cmd)
        if rc:  # O(1)
            lines.append(f"{bid} branch {br} kept (not merged)")  # O(1)
            kept.append("branch")  # O(1)
        else:  # O(1)
            lines.append(f"{bid} branch {br} deleted")  # O(1)
    return kept  # O(1)


def reset_batch(root: Path, bid: str, discard: bool = False) -> tuple[int, list[str]]:  # O(cmd + w)
    import backlog_state as bs  # O(1)
    import ship_lock  # O(1)
    root = Path(root)  # O(1)
    p = bs.path(root)  # O(1)
    data = bs.load(p)  # O(size)
    b = next((x for x in data.get("batches", []) if x.get("id") == bid), None)  # O(batches)
    why = _refusal(b, bid)  # O(1)
    if why:  # O(1)
        return 2, [why]  # O(1)
    lines = []  # O(1)
    block = _stop_lead(root, b)  # O(w)
    if block:  # O(1)
        return 3, [block]  # O(1)
    if b.get("lead"):  # O(1)
        lines.append(f"{bid} lead {b['lead']} stopped")  # O(1)
    try:  # O(1)
        ship_lock.release(ship_lock.lock_path(data.get("repo", "")), bid)  # O(1)
    except Exception:  # noqa: BLE001 | O(1)
        pass  # O(1)
    kept = _git(root, b, discard, lines)  # O(cmd)
    if kept:  # O(1)
        what = " and ".join(kept)  # O(1)
        reason = f"reset kept its {what}; sl backlog reset {bid} --discard drops it, sl backlog start {bid} resumes it"  # O(1)

        def park(d):  # O(b)
            x = bs.batch(d, bid)  # O(batches)
            x.update({"state": "parked", "reason": reason, "lead": None, "agent": None, "since": 0,
                      "reprompted": False, "question_reprompted": False})  # O(1)
        bs.update(p, park)  # O(size)
        lines.append(f"BLOCKED: {bid} parked: {reason}")  # O(1)
        return 3, lines  # O(1)

    def clear(d):  # O(b)
        x = bs.batch(d, bid)  # O(batches)
        for k in CLEARED:  # O(1)
            x.pop(k, None)  # O(1)
        x.update({"state": "planned", "lead": None, "agent": None, "worktree": None, "branch": None, "pr": None,
                  "version": None, "since": 0, "ship_runs": 0, "questions": 0, "merged": False, "reason": ""})  # O(1)
    bs.update(p, clear)  # O(size)
    lines.append(f"{bid} reset: planned; {START.format(b=bid)}")  # O(1)
    return 0, lines  # O(1)
