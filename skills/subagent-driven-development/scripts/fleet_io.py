DEST_RE = re.compile(r"""--?destination[ =]+(?:'([^']*)'|"([^"]*)"|([^\s'"`,;.)]+(?:\.[^\s'"`,;.)]+)*))""")  # a destination flag and its value, quoted or bare | O(1)


def named_destinations(text):  # the destinations TEXT names after -destination / --destination, deduped in order | O(len)
    return list(dict.fromkeys(next(g for g in m.groups() if g is not None) for m in DEST_RE.finditer(text or "")))  # O(len)


def task_message(plan, tasks, sl_path, superlite_root, tier="sonnet"):  # O(n + k*s)
    plan = Path(plan).resolve()  # O(1)
    pl = pt.Plan.load(str(plan))  # O(L)
    mine = [pl.by_id[t] for t in tasks]  # O(k)
    ids = ", ".join(tasks)  # O(k)
    owns = [o for t in mine for o in t.owns]  # O(k*o)
    others = list(dict.fromkeys(o for t in pl.tasks if t.id not in tasks for o in t.owns if o not in owns))  # O(n*o*k) own files are never off limits, repeats dropped
    out = [f"# Task{'s' if len(tasks) > 1 else ''} {ids}", "", f"SUPERLITE={superlite_root}", f"PLAN={plan}", f"sl (type it literally in every command): {sl_path}"]  # O(1)
    if tier == "haiku":  # O(1)
        out += ["", "Your task text:", ""] + [taskmod.render(pl, t) for t in tasks]  # O(k*n*q*s)
    else:  # O(1)
        out += ["Your task text: " + " and ".join(f"`{sl_path} task {t} --plan {plan}`" for t in tasks)]  # O(k)
    ext = mine[0].repo if len(mine) == 1 else None  # dispatch never batches an external task | O(k*s)
    own_line = f"Owns (relative to the task's tree of {ext['root']}): {', '.join(mine[0].written_owns)}" if ext else f"Owns: {', '.join(owns)}"  # O(o)
    out += [own_line, f"Do not touch: {', '.join(others) if others else '(nothing else is owned)'}"]  # O(n*o)
    cmds = {t.id: testcmd.task_command(t.field_text("tests")) for t in mine} if not ext else {}  # O(k*s)
    tail = ", then run the printed `wait:` line in the foreground."  # O(1)

    def line(ts, tid, tests, build, code):  # O(o)
        c = cmds.get(tid)  # O(1)
        t = pl.by_id[tid]  # O(1)
        dest = "".join(f" --destination {shlex.quote(d)}" for d in named_destinations(t.field_text("steps") + " " + t.field_text("notes")))  # O(len)
        if c:  # O(1)
            return f"`{sl_path} run_tests --task {tid} --background` (runs its **Tests:** cmd=`{c}`)" + tail  # O(1)
        if build:  # O(1)
            return f"`{sl_path} run_tests --full --task {tid}{dest} --background` (Tests: build, a build check)" + tail  # O(1)
        if not code:  # O(1)
            return None  # O(1)
        return f"`{sl_path} run_tests --fast {' '.join(tests)} --task {tid}{dest} --background`" + tail  # O(o)
    if ext:  # O(1)
        out += [f"Verify: `{sl_path} plan_tools external {tasks[0]} --plan {plan} --test` (its **Repo test:** command in the task's tree), not run_tests."]  # O(1)
    else:  # O(1)
        for t in mine:  # O(k)
            tt = testcmd.verify_paths(t.owns)  # O(o)
            ln = line(None, t.id, tt, t.features.get("tests") == "build", bool(tt))  # O(o)
            out += [("Verify: " if len(mine) == 1 else f"Verify {t.id}: ") + (ln or "no test command (no code file in Owns); check that each owned file exists and says what the task asks.")]  # O(o)
        if len(mine) > 1:  # O(1)
            out += ["Batch: run each task's Verify command on its own (the red run too), never one run_tests for several tasks; a `--task Tn` run may use Tn's own tree, which holds Tn's files but not another member's unfinished ones, so each task's change must work without the other's."]  # O(1)
    out += ["", f"Reply in at most 200 words, starting with `{STATUS_LINE}` (pick one), then files changed, the test command and its result line, and open questions."]  # O(1)
    return "\n".join(out) + "\n"  # O(out)

RISK = ("deep", "numeric", "state", "protocol")  # the Review Focus categories that make a task worth a review | O(1)
LEDGER_COMMIT = re.compile(r"^\s*[-*+]?\s*commit\s+([A-Z]{1,3}\d+[A-Za-z]?)\s+[0-9a-f]{7,40}")  # as commit_task.COMMIT_LINE | O(1)


def ledger_commits(ledger):  # {task: its `commit Tn <sha> ...` lines, oldest first} | O(lines)
    out = {}  # O(1)
    try:  # O(1)
        text = Path(ledger).read_text(encoding="utf-8", errors="replace")  # O(bytes)
    except OSError:  # O(1)
        return out  # O(1)
    for ln in text.splitlines():  # O(lines) iterations
        m = LEDGER_COMMIT.match(ln)  # O(1) regex
        if m:  # O(1)
            out.setdefault(m.group(1), []).append(ln.strip().lstrip("-*+ ").strip())  # O(len)
    return out  # O(1)


def review_reasons(plan, tid):  # why TID is worth a package review; KeyError for a task the plan lacks | O(L + e + k*s)
    pl = pt.Plan.load(str(plan))  # O(L)
    task = pl.by_id[tid]  # KeyError | O(1)
    why = []  # O(1)
    if (task.complexity or 0) >= 5:  # O(s)
        why.append(f"Complexity {task.complexity}")  # O(1)
    try:  # a plan without a taskgraph block has no seams; its exit must not end a dispatch round | O(1)
        seams = nt.taskgraph_full(str(plan))["seams"]  # O(e)
    except SystemExit:  # O(1)
        seams = []  # O(1)
    for seam in seams:  # O(e) iterations
        if tid in seam.split("\u2194"):  # O(len)
            why.append(f"seam {seam}")  # O(1)
    parts = {seg.lower() for o in task.owns for seg in re.split(r"[/.]", o)}  # O(k*s*A)
    hard = sorted({c for pkg, cases in pt.review_focus_cases(pl).items() if pkg in parts for c in cases} & set(RISK))  # O(L + pkgs)
    if hard:  # O(1)
        why.append(f"Review Focus {', '.join(hard)}")  # O(1)
    if not why and len(pl.tasks) == 1:  # fallback reason: a one-task plan has no package review of its own (#595) | O(1)
        why.append("only task")  # O(1)
    return why  # O(1)


def _sections(pl):  # [(package name, [task ids])] of the plan's unfenced `## ` headings | O(L + n)
    heads = [(i, re.sub(r"\s*\([^()]*\)\s*$", "", re.sub(r"(?i)^package:\s*", "", ln[3:].strip())).strip())  # O(L*s)
             for i, ln in enumerate(pl.lines) if not pl.fenced[i] and re.match(r"^## (?!#)", ln)]  # O(L)
    out = [(name, []) for _, name in heads]  # O(h)
    for t in pl.tasks:  # O(n) iterations
        above = [k for k, (i, _) in enumerate(heads) if i <= t.line]  # O(h)
        if above:  # O(1)
            out[above[-1]][1].append(t.id)  # O(1)
    return out  # O(1)


def _pkg_key(name):  # O(s)
    return re.sub(r"\s*\([^()]*\)\s*$", "", str(name).strip()).strip().lower()  # O(s)


def package_tasks(plan, name):  # the task ids of the plan section NAME, in plan order | O(L + n*h)
    want = _pkg_key(name)  # O(s)
    return [t for sec, ids in _sections(pt.Plan.load(str(plan))) if _pkg_key(sec) == want for t in ids]  # O(h + n)


def package_names(plan):  # the section names of the plan that hold tasks, heading case kept | O(L + n*h)
    return [sec for sec, ids in _sections(pt.Plan.load(str(plan))) if ids]  # O(h)


def _hotspots(sd, files):  # the stdout of `incident hotspots` for FILES, or why it failed | O(B + i log i)
    import incident  # lazy: only a review brief needs it | O(module)
    buf = _io.StringIO()  # O(1)
