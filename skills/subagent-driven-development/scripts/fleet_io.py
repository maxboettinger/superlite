def worktree_sl(root, superlite_root, files):  # (Root's sl, [tool names]) when Root is another superlite checkout and FILES change its tools, else None (#513) | O(f)
    root = Path(root).resolve()  # O(d)
    sl = root / "skills" / "subagent-driven-development" / "scripts" / "sl"  # O(1)
    if root == Path(superlite_root).resolve() or not sl.is_file():  # O(d)
        return None  # O(1)
    names = []  # O(1)
    for f in files:  # O(f) iterations
        p = str(f).replace("\\", "/")  # O(len)
        while p.startswith("./"):  # O(len)
            p = p[2:]  # O(len)
        if p.startswith(TOOL_DIRS) and Path(p).stem not in names:  # O(f)
            names.append(Path(p).stem)  # O(1)
    return (str(sl), names) if names else None  # O(1)


RED_PROOF = ("Prove each new test of these tasks can fail: take out or break the code it tests, run the test red through run_tests, "  # O(1)
             "put the code back, and list each red run's summary line under tests; a test that stays green is a finding.")  # O(1)
CONTRACT_LIMIT = 12  # plan lines a review brief lists per task; the rest are counted | O(1)
FAIL_COUNT = re.compile(r"\b(\d+)\s+(?:failed|failing)\b", re.I)  # a red-run line's failure count | O(1)
FAIL_WORD = re.compile(r"fail", re.I)  # O(1)
NAME_SKIP = frozenset({"None", "True", "False", "Self", "Any"})  # O(1)


def _red_names_failure(red):  # a red-run line counts a failure (N failed with some N >= 1), else holds a fail word; errors alone are not red | O(len)
    counts = FAIL_COUNT.findall(red)  # O(len)
    if counts:  # O(1)
        return any(int(n) >= 1 for n in counts)  # O(len)
    return bool(FAIL_WORD.search(red))  # O(len)


def red_gap(sd, tid, owns):  # why TID's newest implementer report proves no red run, else None (no report: None) | O(r*B + o)
    best = None  # (mtime, file name, report) | O(1)
    for p in (Path(sd) / "fleet" / "reports").glob("*.json"):  # O(r) iterations
        try:  # O(1)
            rep = json.loads(p.read_text(encoding="utf-8"))  # O(B)
            when = p.stat().st_mtime  # O(1)
        except (OSError, ValueError):  # O(1)
            continue  # O(1)
        if not isinstance(rep, dict) or rep.get("role") != "implementer":  # O(1)
            continue  # O(1)
        if tid not in [x.strip() for x in str(rep.get("label") or "").split(",")]:  # O(k)
            continue  # O(1)
        if best is None or (when, p.name) >= best[:2]:  # O(1)
            best = (when, p.name, rep)  # O(1)
    if best is None:  # O(1)
        return None  # O(1)
    red = str(best[2].get("red") or "").strip()  # O(len)
    if not red:  # O(1)
        return "its report names no red run"  # O(1)
    if red.lower().startswith("none"):  # O(1)
        tests = [o for o in owns if testcmd.is_test_path(str(o))]  # O(o)
        return f"its report says `{red}`, but it owns test files ({', '.join(tests[:3])})" if tests else None  # O(o)
    return None if _red_names_failure(red) else f"its red run `{red[:120]}` names no failing test"  # O(len)


def _type_names(task):  # the type names TASK defines: the classes of its Produces and the stems of its non-test owned files | O(k*s)
    names = []  # O(1)
    for item in task.produces:  # O(k) iterations
        sig = pt.parse_signature(item)  # O(s)
        if sig and sig.get("cls"):  # O(1)
            names.append(sig["cls"])  # O(1)
        elif not sig:  # O(1)
            head = re.match(r"\s*`?([A-Za-z_][\w.]*)", item)  # O(s)
            names += [seg for seg in head.group(1).split(".") if seg[:1].isupper()] if head else []  # O(s)
    for o in task.owns:  # O(o) iterations
        stem = Path(str(o)).stem  # O(1)
        if re.fullmatch(r"[A-Z][A-Za-z0-9]+", stem) and not testcmd.is_test_path(str(o)):  # O(s)
            names.append(stem)  # O(1)
    return [n for n in dict.fromkeys(names) if len(n) >= 3 and n not in NAME_SKIP]  # O(k)


def contract_mentions(pl, tid, limit=12):  # (type names of TID, [(plan line, "table" | task id, text)] up to LIMIT, all mentions) outside TID's own block | O(L*k)
    task = pl.by_id[tid]  # O(1)
    names = _type_names(task)  # O(k*s)
    if not names:  # O(1)
        return [], [], 0  # O(1)
    pat = re.compile(r"(?<![\w])(?:" + "|".join(re.escape(n) for n in names) + r")(?![\w])")  # O(k)
    own = range(task.line, task.line + task.text.count("\n") + 1)  # O(len)
    skip = set()  # lines of mermaid blocks | O(1)
    for blk in pl.mermaid_blocks():  # O(b) iterations
        skip.update(range(blk.start, blk.end + 1))  # O(len)
    owner = {}  # line index -> task id | O(1)
    for t in pl.tasks:  # O(n) iterations
        for i in range(t.line, t.line + t.text.count("\n") + 1):  # O(len)
            owner[i] = t.id  # O(1)
    found = []  # O(1)
    for i, ln in enumerate(pl.lines):  # O(L) iterations
        if i in skip or i in own or re.match(r"#{1,4}\s", ln) or not pat.search(ln):  # O(s)
            continue  # O(s)
        s = ln.strip()  # O(s)
        who = owner.get(i) or ("table" if s.startswith("|") else None)  # O(1)
        if who:  # O(1)
            found.append((i + 1, who, s[:240]))  # O(s)
    return names, found[:limit], len(found)  # O(limit)


def review_brief(sd, plan, tasks, sl_path, superlite_root, package=None):  # the package-reviewer's brief | O(L + e + k*s + B)
    sd = Path(sd)  # O(1)
    plan_p = Path(plan).resolve()  # O(1)
    pl = pt.Plan.load(str(plan_p))  # O(L)
    root = state.git_root(sd) or sd.parent  # O(d)
    commits = ledger_commits(sd / "progress.md")  # O(lines)
    files = list(dict.fromkeys(o for t in tasks for o in pl.by_id[t].owns))  # O(k*o)
    ids = ", ".join(tasks)  # O(k)
    if package:  # O(1)
        why = f"Why: every committed task of package {package}"  # O(1)
    else:  # O(1)
        why = "Why: " + "; ".join(f"{t}: {'; '.join(review_reasons(plan_p, t)) or 'asked for'}" for t in tasks)  # O(k*(L + e))
    lines = [f"# Review: {ids}" + (f" (package {package})" if package else ""), "", f"SUPERLITE={superlite_root}", f"PLAN={plan_p}", f"Root: {root}",  # O(1)
             f"sl (type it literally in every command): {sl_path}"]  # O(1)
    wt = worktree_sl(root, superlite_root, files)  # O(o)
    if wt:  # O(1)
        lines += [f"Worktree sl (live checks of the tools these tasks add or change: {', '.join(wt[1])}; type it literally): {wt[0]}",  # O(o)
                  WORKTREE_REST]  # O(1)
    lines += [why, "", "Commits:"]  # O(1)
    for t in tasks:  # O(k) iterations
        lines += [f"- {c}" for c in commits.get(t, [])]  # O(c)
    if not any(commits.get(t) for t in tasks):  # O(k)
        lines.append("- (no commit line in progress.md)")  # O(1)
    lines += ["Diffs: `git show <sha>` for each commit above, in Root."]  # O(1)
    lines += [f"Spec slice: `{sl_path} task {t} --plan {plan_p}`" for t in tasks]  # O(k)
    lines += [f"Files in scope: {', '.join(files)}", "",  # O(o)
              f"Incident hotspots (`{sl_path} incident hotspots --files {','.join(files)}`):", _hotspots(sd, files), ""]  # O(B + i log i)
    for t in tasks:  # O(k) iterations
        names, rows, total = contract_mentions(pl, t, CONTRACT_LIMIT)  # O(L*k)
        if total:  # O(1)
            lines.append(f"Plan contract outside {t}'s Produces (other plan lines that name {', '.join(names)}; "  # O(k)
                         "the build must fit each line, a mismatch is a finding):")  # O(1)
            lines += [f"- plan:{n} ({who}): {text}" for n, who, text in rows]  # O(limit)
            if total > len(rows):  # O(1)
                lines.append(f"- ({total - len(rows)} more: grep the plan for {', '.join(names)})")  # O(1)
            lines.append("")  # O(1)
    gaps = [(t, red_gap(sd, t, pl.by_id[t].owns)) for t in tasks]  # O(k*r)
    gaps = [(t, g) for t, g in gaps if g]  # O(k)
    if gaps:  # O(1)
        lines += ["Red runs (task reports):"] + [f"- {t}: {g}" for t, g in gaps] + [RED_PROOF, ""]  # O(k)
    adapter = sd / "probes" / "adapter.py"  # O(1)
    lines.append(f"Probe adapter: {adapter if adapter.is_file() else 'none'}")  # O(1)
    return "\n".join(lines) + "\n"  # O(out)


def review_hints(sd, plan):  # [(task, reasons)] for committed tasks that match a review reason and no worker has reviewed | O(n*(L + e) + w)
    sd = Path(sd)  # O(1)
    pl = pt.Plan.load(str(plan))  # O(L)
    covered = {t for w in (fs.load(sd).get("workers") or {}).values() for t in (w.get("review") or [])}  # O(w*k)
    out = []  # O(1)
    for tid in ledger_commits(sd / "progress.md"):  # O(c) iterations
        if tid not in pl.by_id or tid in covered:  # O(1)
            continue  # O(1)
        why = review_reasons(plan, tid)  # O(L + e + k*s)
        if red_gap(sd, tid, pl.by_id[tid].owns):  # O(r*B)
            why.append("no red run")  # O(1)
        if why:  # O(1)
            out.append((tid, why))  # O(1)
    return sorted(out, key=lambda x: pt.nkey(x[0]))  # O(n log n)


def last_assistant_text(transcript):  # O(T)
    try:  # O(1)
        lines = Path(transcript).read_text(encoding="utf-8", errors="replace").splitlines()  # O(T)
    except OSError:  # O(1)
        return ""  # O(1)
    for line in reversed(lines):  # O(T) iterations
        try:  # O(1)
            e = json.loads(line)  # O(len line)
        except ValueError:  # O(1)
            continue  # O(1)
        if not isinstance(e, dict) or e.get("type") != "assistant":  # O(1)
            continue  # O(1)
        content = (e.get("message") or {}).get("content")  # O(1)
        if isinstance(content, str):  # O(1)
            text = content  # O(1)
        else:  # O(1)
            text = "\n".join(b.get("text", "") for b in content or [] if isinstance(b, dict) and b.get("type") == "text")  # O(len)
        if text.strip():  # O(len)
            return text  # O(1)
    return ""  # O(1)


def _records(transcript):  # O(T)
    try:  # O(1)
        lines = Path(transcript).read_text(encoding="utf-8", errors="replace").splitlines()  # O(T)
    except OSError:  # O(1)
        return []  # O(1)
    out = []  # O(1)
    for line in lines:  # O(T) iterations
        try:  # O(1)
            e = json.loads(line)  # O(len line)
        except ValueError:  # O(1)
            continue  # O(1)
        if isinstance(e, dict):  # O(1)
            out.append(e)  # O(1)
    return out  # O(1)


def _blocks_text(e):  # the text blocks of a message joined; None for a message with a tool_result | O(len)
    content = (e.get("message") or {}).get("content")  # O(1)
    if isinstance(content, str):  # O(1)
        return content  # O(1)
    blocks = [b for b in content or [] if isinstance(b, dict)]  # O(len)
    if any(b.get("type") == "tool_result" for b in blocks):  # O(len)
        return None  # O(1)
    return "\n".join(b.get("text", "") for b in blocks if b.get("type") == "text")  # O(len)


def _starts_turn(e):  # a message from the task sender: not a tool result, hook feedback, meta or task-notification message | O(len)
    if e.get("type") != "user" or e.get("isMeta"):  # O(1)
        return False  # O(1)
    origin = e.get("origin")  # O(1)
    if isinstance(origin, dict) and origin.get("kind") not in (None, "human"):  # O(1)
        return False  # O(1)
    text = _blocks_text(e)  # O(len)
    if not (text and text.strip()):  # O(len)
        return False  # O(1)
    head = text.lstrip()  # O(len)
    return not head.startswith(("Stop hook feedback", "<task-notification>"))  # O(1)


def _has_status(text):  # O(len)
    return bool(mx.STATUS.search(text) or mx.LEAD.search(text.lstrip().split("\n", 1)[0]))  # O(len)


def _rank(text):  # json-valid report 3, a status with a parsed field 2, a status 1, else 0 | O(len)
    rep = fleet_report.parse(text)  # O(len)
    if rep.get("valid"):  # O(1)
        return 3  # O(1)
    if not _has_status(text):  # O(len)
        return 0  # O(1)
    return 2 if any(rep.get(k) for k in ("files", "tests", "summary", "findings", "concerns")) else 1  # O(1)


def report_text(transcript):  # the best text of the latest sender turn (newest of the best rank), else its last text | O(T)
    recs = _records(transcript)  # O(T)
    start = max((i for i, e in enumerate(recs) if _starts_turn(e)), default=0)  # O(T)
    texts = [t for e in recs[start:] if e.get("type") == "assistant" for t in [_blocks_text(e)] if t and t.strip()]  # O(T)
    return max(reversed(texts), key=_rank) if texts else ""  # first maximum = the newest | O(T)


def _stops(sd):  # the stop records of metrics.jsonl in file order | O(m)
    try:  # O(1)
        lines = (Path(sd) / "metrics.jsonl").read_text(encoding="utf-8", errors="replace").splitlines()  # O(m)
    except OSError:  # O(1)
        return []  # O(1)
    out = []  # O(1)
    for line in lines:  # O(m) iterations
        try:  # O(1)
            e = json.loads(line)  # O(len line)
        except ValueError:  # O(1)
            continue  # O(1)
        if isinstance(e, dict) and e.get("ev") == "stop" and isinstance(e.get("t"), int):  # O(1)
            out.append(e)  # O(1)
    return out  # O(1)


def project_dir(path):  # the folder name Claude Code gives a project path | O(len)
    return re.sub(r"[^A-Za-z0-9]", "-", str(path))  # O(len)


def own_stop(rec, worker):  # False for a stop record a child session of the worker's worktree wrote | O(len)
    wt = (worker or {}).get("worktree")  # O(1)
    tr = rec.get("transcript")  # O(1)
    if not wt or not tr:  # O(1)
        return True  # O(1)
    folder = Path(str(tr)).parent.name  # O(1)
    for p in (str(wt), str(Path(wt).resolve())):  # O(1)
        d = project_dir(p)  # O(len)
        if folder == d or (len(d) > 200 and folder.startswith(d[:200])):  # O(len)
            return True  # O(1)
    return False  # O(1)


def latest_stop(sd, wid, after_ms, stops=None):  # the newest own stop record of WID at or after AFTER_MS; STOPS is a pre-read _stops list | O(m + w)
    try:  # O(1)
        worker = fs.load(Path(sd))["workers"].get(wid)  # read once | O(w)
    except (OSError, ValueError, KeyError):  # O(1)
        worker = None  # O(1)
    own = (worker or {}).get("state_dir")  # the folder its stop hook writes to (#580) | O(1)
    if own and Path(own).resolve() != Path(sd).resolve():  # O(1)
        stops = _stops(own)  # O(m)
    elif stops is None:  # O(1)
        stops = _stops(sd)  # O(m)
    found = None  # O(1)
    for e in stops:  # O(m) iterations
        if e.get("agent_id") == wid and e["t"] >= after_ms and (found is None or e["t"] >= found["t"]) and own_stop(e, worker if (worker or {}).get("role") == "lead" else None):  # O(len)
            found = e  # O(1)
    return found  # O(1)


def ready_k(transcript):  # context in thousands after the first turn (READY), from the records before the second turn | O(T)
    recs = _records(transcript)  # O(T)
    if not recs:  # O(1)
        return None  # O(1)
    starts = [i for i, e in enumerate(recs) if _starts_turn(e)]  # O(T)
    cut = recs[:starts[1]] if len(starts) > 1 else recs  # O(T)
    with tempfile.TemporaryDirectory() as td:  # O(1)
        tp = Path(td) / "ready.jsonl"  # O(1)
        tp.write_text("".join(json.dumps(e) + "\n" for e in cut), encoding="utf-8")  # O(T)
        return pool.context_k(tp)  # the token formula stays in pool.py | O(T)


def baseline_k(sd, wid):  # context after READY, cached in fleet.json; None is never cached | O(m + T + w)
    sd = Path(sd)  # O(1)
    cached = fs.load(sd)["workers"].get(wid, {}).get("baseline_k")  # O(w)
    if isinstance(cached, (int, float)):  # O(1)
        return cached  # O(1)
    last = latest_stop(sd, wid, 0)  # every stop of one worker shares its session transcript; ready_k cuts it at the second turn | O(m)
    k = ready_k(last["transcript"]) if last and last.get("transcript") else None  # O(T)
    if k is None:  # O(1)
        return None  # O(1)
    with fs.locked(sd):  # O(1) plus wait
        data = fs.load(sd)  # O(w)
        if wid in data["workers"]:  # O(1)
            data["workers"][wid]["baseline_k"] = k  # O(1)
            fs.save(sd, data)  # O(w)
    return k  # O(1)


def pane_title(sd, wid, label, status=""):  # `<full name of label> <worker> [status]`; a lead is named by its worktree, an unknown worker by the run | O(w)
    w = fs.load(Path(sd))["workers"].get(wid) or {}  # O(w)
    root = Path(w["worktree"]) if w.get("worktree") else None  # O(1)
    return " ".join(x for x in (fs.full_name(sd, label, root), wid, status) if x)  # O(depth)


def pane_label(sd, wid, text, timeout_ms=None):  # rename the worker's Herdr pane; a Herdr failure or an unknown worker never matters, a wrong verb or a missing hc.call does | O(w)
    try:  # O(1)
        pane = fs.load(Path(sd))["workers"][wid]["pane_id"]  # O(w)
        args = ["pane", "rename", pane, text]  # O(len text)
        hc.call(args) if timeout_ms is None else hc.call(args, timeout_ms=timeout_ms)  # a caller's default timeout stays hc's own | O(len text)
        return True  # O(1)
    except (hc.HerdrError, KeyError):  # O(1)
        return False  # O(1)


def stopped(sd, wid, t_ms):  # the stop hook: label the pane reported unless the worker was sent new work after the stop | O(w)
    sd = fs.home(sd)  # a worker started before a move labels its pane in the fleet's new folder | O(w)
    w = fs.load(Path(sd))["workers"].get(wid)  # O(w)
    if w is None or int(w.get("sent") or 0) > t_ms:  # O(1)
        return False  # O(1)
    label = w.get("task") or w.get("last_task") or wid  # O(1)
    return pane_label(sd, wid, pane_title(sd, wid, label, "reported, waiting for coordinator"), 3000)  # O(w)


def _prompt(name, msg):  # prompt NAME; one resend after a stall or a slow reply that did not land | O(len msg)
    try:  # O(1)
        hc.prompt(name, msg, ["working"], 15000)  # O(len msg)
        return  # O(1)
    except hc.HerdrError as e:  # O(1)
        code, text = getattr(e, "code", ""), str(getattr(e, "message", "") or e)  # O(len)
        if code == STALLED:  # O(1)
            pass  # O(1)
        elif SLOW_MSG in text:  # O(len)
            try:  # O(1)
                state = hc.agent_state(name)  # O(1)
            except hc.HerdrError:  # O(1)
                state = None  # O(1)
            if state == "working":  # the prompt landed | O(1)
                return  # O(1)
        else:  # O(1)
            raise  # O(1)
    hc.prompt(name, msg, ["working"], 15000)  # resent once; a second failure propagates | O(len msg)


def send(sd, plan, wid, tasks, sl_path, superlite_root):  # O(w + n + k*s)
    sd = Path(sd)  # O(1)
    data = fs.load(sd)  # O(w)
    if wid not in data["workers"]:  # O(1)
        raise KeyError(wid)  # O(1)
    tier = data["workers"][wid].get("tier", "sonnet")  # O(1)
    msg = task_message(plan, tasks, sl_path, superlite_root, tier)  # O(n + k*s)
    sent = now_ms()  # O(1)
    _prompt(fs.name_of(sd, wid, data["workers"][wid]), msg)  # O(len msg)
    label = ",".join(tasks)  # O(k)
    _busy(sd, wid, label, sent)  # O(w + pool bytes)
    pane_label(sd, wid, pane_title(sd, wid, label))  # O(w)
    print(f"{wid} {label} sent")  # O(1)
    return label  # O(1)


def _busy(sd, wid, label, sent, brief=None):  # worker busy on LABEL since SENT, in the pool too (a worker the pool lacks is fine); BRIEF is remembered for a respawn | O(w + pool bytes)
    pp = Path(sd) / "pool.json"  # O(1)
    with fs.locked(sd):  # serialise the fleet.json and pool.json read-change-save | O(1) plus wait
        data = fs.load(sd)  # O(w)
        if wid not in data["workers"]:  # O(1)
            raise KeyError(wid)  # O(1)
        data["workers"][wid].update({"state": "busy", "task": label, "sent": sent, "brief": brief})  # O(1)
        fs.save(sd, data)  # O(w)
        if pp.exists():  # O(1)
            pdata = pool.load(pp)  # O(pool bytes)
            try:  # O(1)
                pool.busy(pdata, wid, label, sent)  # O(a)
                pool.save(pp, pdata)  # O(pool bytes)
            except KeyError:  # a worker the pool does not know | O(1)
                pass  # O(1)


def send_brief(sd, wid, brief, label="", full=False):  # O(w + len brief path + pool bytes)
    """Tell worker WID to read the brief file and answer as its role's report contract says; returns the label
    (LABEL, else the brief's stem). FileNotFoundError for a missing brief, KeyError for an unknown worker."""
    sd = Path(sd)  # O(1)
    path = Path(brief).resolve()  # O(1)
    if not path.is_file():  # O(1)
        raise FileNotFoundError(str(brief))  # O(1)
    w = fs.load(sd)["workers"][wid]  # KeyError for an unknown worker | O(w)
    role = w.get("role") or "implementer"  # O(1)
    msg = fleet_report.brief_message(role, str(path), full) if full else fleet_report.brief_message(role, str(path))  # O(1)
    label = label or path.stem  # O(1)
    sent = now_ms()  # O(1)
    name = fs.name_of(sd, wid, w)  # O(w)
    _prompt(name, msg)  # O(len msg)
    _busy(sd, wid, label, sent, str(path))  # O(w + pool bytes)
    pane_label(sd, wid, pane_title(sd, wid, label))  # O(w)
    print(f"{wid} {label} sent")  # O(1)
    return label  # O(1)


def send_text(sd, wid, text):  # O(w + len text)
    """Answer a worker with free text. It is busy again on its last task, so a bare `wait` waits for the answer; the pool stays as it was."""
    sd = Path(sd)  # O(1)
    name = fs.worker_name(sd, wid)  # KeyError for an unknown worker | O(w)
    sent = now_ms()  # O(1)
    wrec = fs.load(sd)["workers"].get(wid, {})  # O(w)
    role = wrec.get("role") or "implementer"  # O(1)
    contract = "" if role == "layer" else (fleet_report.REVIEW if role == "final-reviewer" else fleet_report.WORK)  # O(1)
    msg = f"{text}\n\n{contract}" if contract else text  # O(len text)
    brief = Path(str(wrec.get("lead_sd") or "")) / "briefs" / "lead.md"  # O(1)
    last = latest_stop(sd, wid, int(wrec.get("sent") or 0)) if role == "lead" and wrec.get("lead_sd") and brief.is_file() else None  # O(m + w)
    if last is not None and " ".join(str(last.get("last") or "").split()) == "READY":  # the lead stopped after READY alone: its brief never ran | O(len)
        msg = fleet_report.brief_message("lead", str(brief.resolve()))  # O(1)
        print(f"{wid} brief resent (its last stop said only READY)")  # O(1)
    _prompt(name, msg)  # O(len msg)
    task = None  # O(1)
    with fs.locked(sd):  # O(1) plus wait
        data = fs.load(sd)  # O(w)
        w = data["workers"].get(wid)  # O(1)
        if w is not None:  # O(1)
            task = w.get("task") or w.get("last_task") or wid  # O(1)
            w.update({"state": "busy", "task": task, "sent": sent})  # O(1)
            fs.save(sd, data)  # O(w)
    if task:  # O(1)
        pane_label(sd, wid, pane_title(sd, wid, task))  # O(w)
    print(f"{wid} text sent")  # O(1)


def _write(path, text):  # O(len)
    path.parent.mkdir(parents=True, exist_ok=True)  # O(1)
    path.write_text(text, encoding="utf-8")  # O(len)


def _ready(sd, wid, label):  # one lock-held write: ready, no task, LABEL remembered as the last task | O(w)
    with fs.locked(sd):  # O(1) plus wait
        data = fs.load(sd)  # O(w)
        if wid in data["workers"]:  # O(1)
            data["workers"][wid].update({"state": "ready", "task": None, "last_task": label})  # O(1)
            fs.save(sd, data)  # O(w)


def _stop_worker(sd, wid):  # O(w) plus herdr calls
    try:  # a failed stop must not lose the report | O(1)
        importlib.import_module("fleet").stop(sd, [wid])  # O(w)
    except Exception:  # O(1)
        pass  # O(1)


def _lags(text, last, label):  # the transcript text is behind its stop record: empty, or without a status while the cut line has one | O(len)
    if fleet_report.parse(text, label)["status"] != "UNKNOWN":  # O(len)
        return False  # O(1)
    return not text.strip() or fleet_report.parse(last, label)["status"] != "UNKNOWN"  # O(len)


def _finish(sd, wid, w, text, source, tail=None, cut=None):  # " partial" follows an APPROVED that left packet lines unread; TAIL: the last pane lines of a turn that ended without a report; CUT: the stop record line of a transcript that stayed behind | O(len + w)
    label = w.get("task") or wid  # O(1)
    rid = label.split(",")[0]  # O(1)
    rdir = Path(sd) / "fleet" / "reports"  # O(1)
    mp, jp = rdir / f"{rid}.md", rdir / f"{rid}.json"  # O(1)
    if cut is not None:  # O(1)
        body = f"UNKNOWN (transcript empty or behind its stop record after {READ_MS // 1000} s: {cut[0]})\n\n" + (text + "\n\n" if text.strip() else "") + "Stop record line (cut at 160 chars, not the report):\n" + cut[1] + "\n\nLast pane lines:\n" + (tail or "")  # O(len)
    else:  # O(1)
        body = text if tail is None else "UNKNOWN (turn ended without a report)\n\n" + text + "\n\nLast pane lines:\n" + tail  # O(len)
    _write(mp, body)  # O(len)
    rep = fleet_report.parse(text, rid, allow_json=source == "transcript")  # a screen holds no trustworthy json block | O(len)
    part = rep["status"] == "APPROVED" and fleet_report.partial(text)  # O(len)
    _write(jp, json.dumps({**rep, **({"partial": True} if part else {}), "id": wid, "label": label, "role": w.get("role") or "implementer", "source": source, "report": str(mp)}, indent=2) + "\n")  # O(len)
    n = len(rep["findings"])  # O(1)
    nc = len(rep.get("concerns") or [])  # O(1)
    print(f"{wid} {label} {rep['status']} findings={n}" + (f" concerns={nc}" if nc else "") + (" partial" if part else "") + f" {jp}" + (" (screen)" if source == "screen" else "") + (" (turn ended without a report)" if tail is not None else "") + (" (transcript unread)" if cut is not None else ""))  # O(1)
    _ready(sd, wid, label)  # O(w)
    pane_label(sd, wid, pane_title(sd, wid, label, "reported, waiting for coordinator"))  # before the worker may be stopped | O(w)
    if w.get("one_turn") and rep["status"] in FINAL:  # NEEDS_CONTEXT, UNKNOWN and BLOCKED-UI keep the worker | O(1)
        _stop_worker(sd, wid)  # O(w)
    return {"id": wid, "task": label, "status": rep["status"], "report": str(jp), "source": source, "findings": n}  # O(1)


def _pane_tail(sd, wid, w):  # the last pane lines, or the reason there are none | O(s)
    try:  # O(1)
        return hc.read_screen(fs.name_of(sd, wid, w), 20, "recent")  # O(s)
    except hc.HerdrError as e:  # O(1)
        return f"(no screen: {e})"  # O(1)


def _finish_layer(sd, wid, w, r):  # a finished layer worker: its result as json and two lines, then the worker is stopped | O(w)
    label = w.get("task") or wid  # O(1)
    jp = Path(sd) / "fleet" / "reports" / f"{label.split(',')[0]}.json"  # O(1)
    _write(jp, json.dumps({**r, "id": wid, "label": label, "role": "layer"}, indent=2) + "\n")  # O(1)
    print(f"{wid} {label} {r['status']} exit={r['exit']} {r['log']}")  # O(1)
    print(f"  {r['last']}")  # O(1)
    _ready(sd, wid, label)  # O(w)
    _stop_worker(sd, wid)  # O(w)
    return {"id": wid, "task": label, "status": r["status"], "report": str(jp), "source": "layer", "findings": 0}  # O(1)


def _ask(sd, wid, w, after=0):  # ask a worker whose turn ended without a report, once per send; None: not askable, False: Herdr failed | O(w + len)
    role = w.get("role") or "implementer"  # O(1)
    asked = int(w.get("asked") or 0)  # O(1)
    if role in ("lead", "layer") or (asked and asked == int(w.get("sent") or 0)):  # O(1)
        return None  # O(1)
    sent = max(now_ms(), after + 1)  # newer than the stop record it answers, whatever the clocks say | O(1)
    try:  # O(1)
        _prompt(fs.name_of(sd, wid, w), ASK + " " + (fleet_report.REVIEW if role == "final-reviewer" else fleet_report.WORK))  # O(len)
    except hc.HerdrError:  # O(1)
        return False  # O(1)
    label = w.get("task") or wid  # O(1)
    with fs.locked(sd):  # O(1) plus wait
        data = fs.load(sd)  # O(w)
        if wid in data["workers"]:  # O(1)
            data["workers"][wid].update({"state": "busy", "sent": sent, "asked": sent})  # O(1)
            fs.save(sd, data)  # O(w)
    pane_label(sd, wid, pane_title(sd, wid, label))  # O(w)
    print(f"{wid} {label} ASKED (turn ended without a report; asked once)")  # O(1)
    return True  # O(1)


def _blocked(sd, wid, w):  # O(s + w)
    screen = hc.read_screen(fs.name_of(sd, wid, w), 40, "visible")  # O(s)
    sp = Path(sd) / "fleet" / "screens" / f"{wid}.txt"  # O(1)
    _write(sp, screen)  # O(s)
    fs.set_state(sd, wid, "blocked", w.get("task"))  # O(w)
    task = w.get("task") or wid  # O(1)
    pane_label(sd, wid, pane_title(sd, wid, task, "BLOCKED-UI"))  # O(w)
    print(f"{wid} {task} BLOCKED-UI {sp}")  # O(1)
    for line in [x for x in screen.splitlines() if x.strip()][-5:]:  # O(s)
        print(f"  {line}")  # O(1)
    return {"id": wid, "task": task, "status": "BLOCKED-UI", "report": str(sp), "source": "screen"}  # O(1)


def _collected(sd, wid, w):  # True (and a line) when another wait already took WID's report | O(1)
    sent = int(w.get("sent") or 0)  # O(1)
    gone = (w.get("state") == "ready" and w.get("last_task")) or (w.get("state") == "busy" and sent and int(w.get("collected") or 0) == sent)  # O(1)
    if not gone:  # O(1)
        return False  # O(1)
    label = (w.get("task") or w.get("last_task") or wid).split(",")[0]  # O(1)
    print(f"{wid} {w.get('task') or w.get('last_task')} already collected: {Path(sd) / 'fleet' / 'reports' / (label + '.json')}")  # O(1)
    return True  # O(1)


def _take(sd, wid, w):  # claim WID's current send before its report is written; False (and a line) when another wait did | O(w)
    return claim(sd, wid, int(w.get("sent") or 0)) or not _collected(sd, wid, {**w, "state": "busy", "collected": int(w.get("sent") or 0)})  # O(w)


def _fleet():  # the fleet module, loaded on demand | O(1)
    return importlib.import_module("fleet")  # O(1)


def _refusal(sd, wid):  # why a send or keys to WID is refused (a stopped or dead worker), else None; an unknown worker is None | O(w)
    w = fs.load(Path(sd))["workers"].get(wid)  # O(w)
    if w is None or w.get("state") != "stopped":  # O(1)
        return None  # O(1)
    last = w.get("last_task") or w.get("task") or "none"  # O(1)
    why = f"dead (its agent is gone; last task {last})" if w.get("dead") else f"stopped ({w.get('role') or 'implementer'}, last task {last})"  # O(1)
    return f"error: {wid} is {why}; start a fresh one: {_fleet().respawn_hint(sd, wid)}"  # O(w)


def _dead(sd, wid, w):  # end a worker whose agent is gone: stopped, dead, off the pool; the result and its line | O(w)
    task = w.get("task") or wid  # O(1)
    fl = _fleet()  # O(1)
    fl.mark_dead(sd, wid)  # O(w)
    print(f"{wid} {task} DEAD (its agent is gone; no report); start a fresh one: {fl.respawn_hint(sd, wid)}")  # O(w)
    return {"id": wid, "task": task, "status": "DEAD", "report": "", "source": "herdr", "findings": 0}  # O(1)


def _reported(results):  # the suffix naming the finishers of this call | O(r)
    return " (reported: " + ", ".join(f"{r['id']} {r['report']}" for r in results) + ")" if results else ""  # O(r)


def wait(sd, ids, timeout_ms, poll_s=2.0, clock=None, any_=False):  # O(timeout/poll * (w + m))
    sd = Path(sd)  # O(1)
    clock = clock or now_ms  # O(1)
    workers = fs.load(sd)["workers"]  # O(w)
    pending = list(ids) if ids else [k for k, v in workers.items() if v.get("state") == "busy"]  # O(w)
    changed = {}  # wid -> ms the state first read done or idle | O(1)
    seen = {}  # wid -> {t: stop t, first: ms first seen, text, lag}; a flushed transcript is read once per stop record, a lagging one each poll | O(1)
    results = []  # O(1)
    probed = {}  # wid -> ms its agent was last probed for existence | O(1)
    start = clock()  # O(1)
    while pending:  # O(timeout/poll) iterations
        listed = True  # O(1)
        try:  # O(1)
            states = hc.agent_states()  # O(w)
        except hc.HerdrError:  # O(1)
            states, listed = {}, False  # O(1)
        now = clock()  # O(1)
        stops = _stops(sd)  # one metrics read per poll | O(m)
        for wid in list(pending):  # O(w) iterations
            w = fs.load(sd)["workers"].get(wid, {})  # O(w)
            if _collected(sd, wid, w):  # another wait took the report: nothing new to return | O(1)
                pending.remove(wid)  # O(w)
                continue  # O(1)
            if w.get("role") == "layer":  # a shell pane: its exit file tells, herdr has no agent state for it | O(1)
                r = importlib.import_module("fleet_layer").result(sd, wid, w)  # O(l)
                if r is not None:  # O(1)
                    if not _take(sd, wid, w):  # O(w)
                        pending.remove(wid)  # O(w)
                        continue  # O(1)
                    results.append(_finish_layer(sd, wid, w, r))  # O(w)
                    pending.remove(wid)  # O(w)
                continue  # O(1)
            st = states.get(fs.name_of(sd, wid, w))  # herdr lists agents by name, not by worker id | O(1)
            rec = latest_stop(sd, wid, int(w.get("sent") or 0), stops)  # O(m)
            label = (w.get("task") or wid).split(",")[0]  # O(1)
            if rec is not None:  # O(1)
                sn = seen.get(wid)  # O(1)
                if sn is None or sn["t"] != rec["t"]:  # a newer stop record resets | O(1)
                    sn = seen[wid] = {"t": rec["t"], "first": now, "text": "", "lag": True}  # O(1)
                if sn["lag"]:  # read once per stop record, again only while the transcript lags | O(1)
                    tr = rec.get("transcript")  # O(1)
                    text = (report_text(tr) if tr else "") or ("" if tr else rec.get("last", ""))  # O(T)
                    sn["text"], sn["lag"] = text, bool(tr) and _lags(text, rec.get("last", ""), label)  # O(len)
                    if sn["lag"] and now - sn["first"] >= READ_MS:  # the window is over: the cut line is no report | O(1)
                        if not _take(sd, wid, w):  # O(w)
                            pending.remove(wid)  # O(w)
                            continue  # O(1)
                        results.append(_finish(sd, wid, w, text, "transcript", tail=_pane_tail(sd, wid, w), cut=(tr, rec.get("last", ""))))  # O(len)
                        pending.remove(wid)  # O(w)
                        continue  # O(1)
                    if sn["lag"]:  # keep re-reading; neither the blocked screen nor the settle fallback applies to a turn that has a stop record | O(1)
                        continue  # O(1)
            text = seen[wid]["text"] if rec is not None else ""  # O(1)
            reported = rec is not None and fleet_report.parse(text, label)["status"] != "UNKNOWN"  # O(len)
            ended = rec is not None and not reported and (st in ("done", "idle") or (st not in ("working", "blocked") and now - seen[wid]["first"] >= SETTLE_MS))  # O(1)
            if reported or ended:  # a stop record ends the wait in any herdr state once it holds a status | O(1)
                if ended and _ask(sd, wid, w, rec["t"]):  # asked once: the worker is busy again | O(w + len)
                    seen.pop(wid, None)  # O(1)
                    changed.pop(wid, None)  # O(1)
                    continue  # O(1)
                if not _take(sd, wid, w):  # O(w)
                    pending.remove(wid)  # O(w)
                    continue  # O(1)
                results.append(_finish(sd, wid, w, text, "transcript", None if reported else _pane_tail(sd, wid, w)))  # O(len + s)
                pending.remove(wid)  # O(w)
            elif st == "blocked":  # O(1)
                results.append(_blocked(sd, wid, w))  # O(s + w)
                pending.remove(wid)  # O(w)
            elif st in ("done", "idle"):  # O(1)
                changed.setdefault(wid, now)  # O(1)
                if now - changed[wid] >= SETTLE_MS:  # O(1)
                    try:  # O(1)
                        text = hc.read_screen(fs.name_of(sd, wid, w), 80, "recent")  # O(s)
                    except hc.HerdrError as e:  # O(1)
                        text = f"(no screen: {e})"  # O(1)
                    asked = _ask(sd, wid, w) if fleet_report.parse(text, label, allow_json=False)["status"] == "UNKNOWN" else None  # O(len)
                    if asked:  # O(1)
                        seen.pop(wid, None)  # O(1)
                        changed.pop(wid, None)  # O(1)
                        continue  # O(1)
                    if not _take(sd, wid, w):  # O(w)
                        pending.remove(wid)  # O(w)
                        continue  # O(1)
                    results.append(_finish(sd, wid, w, "", "screen", tail=text) if asked is False else _finish(sd, wid, w, text, "screen"))  # O(s)
                    pending.remove(wid)  # O(w)
            else:  # O(1)
                changed.pop(wid, None)  # O(1)
                name = fs.name_of(sd, wid, w)  # O(1)
                if listed and rec is None and st is None and now - probed.get(wid, -PROBE_MS) >= PROBE_MS:  # listed workers exist; probe an unlisted one every PROBE_MS | O(1)
                    probed[wid] = now  # O(1)
                    if _fleet().agent_gone(name, hc):  # only herdr's agent_not_found counts | O(1)
                        results.append(_dead(sd, wid, w))  # O(w)
                        pending.remove(wid)  # O(w)
        if not pending:  # O(1)
            break  # O(1)
        if any_ and results:  # the first finished worker ends the round; the rest stay busy | O(1)
            print("BUSY " + " ".join(pending) + _reported(results))  # O(w)
            break  # O(1)
        if clock() - start >= timeout_ms:  # O(1)
            print("TIMEOUT " + " ".join(pending) + _reported(results))  # O(w)
            break  # O(1)
        sleep(poll_s)  # O(poll_s)
    return results  # O(1)


def main(argv=None):  # O(wait)
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])  # O(1)
    sub = ap.add_subparsers(dest="cmd", required=True)  # O(1)
    sp = sub.add_parser("send")  # O(1)
    sp.add_argument("wid")  # O(1)
    sp.add_argument("tasks", nargs="*")  # O(1)
    sp.add_argument("--text")  # O(1)
    sp.add_argument("--brief")  # O(1)
    sp.add_argument("--label", default="")  # O(1)
    sp.add_argument("--full", action="store_true")  # O(1)
    sp.add_argument("--plan")  # O(1)
    sp.add_argument("--sl", default=str(HERE / "sl"))  # O(1)
    sp.add_argument("--root", default=str(HERE.parents[2]))  # O(1)
    kp = sub.add_parser("keys")  # O(1)
    kp.add_argument("wid")  # O(1)
    kp.add_argument("keys", nargs="+")  # O(1)
    kp.add_argument("--plan")  # O(1)
    stp = sub.add_parser("stopped")  # O(1)
    stp.add_argument("wid")  # O(1)
    stp.add_argument("--sd", required=True)  # O(1)
    stp.add_argument("--t", type=int)  # O(1)
    wp = sub.add_parser("wait")  # O(1)
    wp.add_argument("--timeout", default="540000")  # O(1)
    wp.add_argument("--poll", type=float, default=2.0)  # O(1)
    wp.add_argument("--plan")  # O(1)
    wp.add_argument("--any", action="store_true")  # O(1)
    wp.add_argument("ids", nargs="*")  # O(1)
    a = ap.parse_args(argv)  # O(1)
    if a.cmd == "stopped":  # the hook calls this: it never fails | O(w)
        try:  # O(1)
            stopped(a.sd, a.wid, a.t if a.t is not None else now_ms())  # O(w)
        except Exception:  # O(1)
            pass  # O(1)
        return 0  # O(1)
    if a.cmd == "wait":  # before any state or herdr call | O(len)
        try:  # O(1)
            t_ms = parse_timeout(a.timeout)  # O(len)
        except ValueError:  # O(1)
            print(f"error: --timeout {a.timeout} is no time (use ms, or 580s, 9m)", file=sys.stderr)  # O(1)
            return 2  # O(1)
        if str(a.timeout).strip().isdigit() and 0 < int(a.timeout) < 1000:  # O(1)
            print(f"note: --timeout {a.timeout} read as {a.timeout} s (--timeout is in ms)", file=sys.stderr)  # O(1)
    sd = state.resolve(a.plan) if getattr(a, "plan", None) else state.resolve()  # O(d)
    try:  # O(1)
        if a.cmd == "send" and sum([bool(a.tasks), a.text is not None, a.brief is not None]) > 1:  # before any herdr call or file check | O(1)
            print("error: send takes task ids, --text or --brief, not two of them", file=sys.stderr)  # O(1)
            return 2  # O(1)
        if a.cmd == "send" and a.full and a.brief is None:  # O(1)
            print("error: --full needs --brief", file=sys.stderr)  # O(1)
            return 2  # O(1)
        if a.cmd in ("send", "keys") and (why := _refusal(sd, a.wid)):  # before any herdr call | O(w)
            print(why, file=sys.stderr)  # O(1)
            return 2  # O(1)
        if a.cmd == "keys":  # O(1)
            hc.send_keys(fs.worker_name(sd, a.wid), a.keys)  # O(w + len keys)
            print(f"{a.wid} keys sent")  # O(1)
        elif a.cmd == "wait":  # O(1)
            wait(sd, a.ids or None, t_ms, a.poll, any_=a.any)  # O(wait)
        elif a.text is not None:  # O(1)
            send_text(sd, a.wid, a.text)  # O(w + len text)
        elif a.brief:  # O(1)
            if not Path(a.brief).is_file():  # before any prompt | O(1)
                print(f"error: brief not found: {Path(a.brief).resolve()}", file=sys.stderr)  # O(1)
                return 2  # O(1)
            role = (fs.load(sd)["workers"][a.wid].get("role") or "implementer") if a.full else ""  # KeyError for an unknown worker | O(w)
            if a.full and role != "final-reviewer":  # before any prompt | O(1)
                print(f"error: --full is for a final-reviewer worker ({a.wid} is {role})", file=sys.stderr)  # O(1)
                return 2  # O(1)
            send_brief(sd, a.wid, a.brief, a.label, a.full)  # O(w + pool bytes)
        elif not a.tasks:  # O(1)
            print("error: send needs task ids, --text or --brief", file=sys.stderr)  # O(1)
            return 2  # O(1)
        else:  # O(1)
            send(sd, str(pt.resolve_plan(a.plan)) if a.plan else nt.default_plan(), a.wid, a.tasks, a.sl, a.root)  # O(w + n + k*s)
    except KeyError as e:  # O(1)
        print(f"error: unknown worker or task {e}", file=sys.stderr)  # O(1)
        return 2  # O(1)
    except pt.PlanError as e:  # O(1)
        print(f"error: {e}", file=sys.stderr)  # O(1)
        return 2  # O(1)
    except hc.HerdrError as e:  # O(1)
        if a.cmd in ("send", "keys") and getattr(e, "code", "") == "agent_not_found":  # the agent is gone: mark it, say so | O(w)
            _fleet().mark_dead(sd, a.wid)  # O(w)
            print(_refusal(sd, a.wid), file=sys.stderr)  # O(w)
            return 2  # O(1)
        print(f"error: {e}", file=sys.stderr)  # O(1)
        return 1 if a.cmd != "wait" else 0  # O(1)
    return 0  # O(1)


if __name__ == "__main__":  # O(1)
    sys.exit(main())  # O(1)
