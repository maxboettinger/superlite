#!/usr/bin/env python3
"""sl backlog ship <B> lock|bump|merge|release (phase 3): a batch lead ships its own batch under the ship lock.

`done --pr N [--version X]` runs in the main session: it records a batch main shipped by hand (PR merged).
`merge --from-main` runs in the main session: it ships a parked batch (lock as main, rebase, second bump, maxapp ship, then done's bookkeeping).
A lead resumed after a crash has no fleet env: its ship call parks the batch and names the start command as the fix.

Exit 0 done, 2 refused, 3 BLOCKED, 4 WAIT/RERUN, 5 CONFLICT, 6 RED. Stdlib only.
"""
import argparse  # O(1)
import json  # O(1)
import os  # O(1)
import re  # O(1)
import subprocess  # O(1)
import sys  # O(1)
import time  # O(1)
from pathlib import Path  # O(1)

sys.path.insert(0, str(Path(__file__).resolve().parent))  # O(1)
MAX_RUNS = 5  # O(1)


def _root():  # O(1)
    import backlog_state  # O(1)
    return backlog_state.main_root(Path.cwd())  # O(1)


def _run(cmd, cwd, timeout=None):  # O(output)
    try:  # O(1)
        r = subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True, timeout=timeout)  # O(output)
    except (OSError, subprocess.TimeoutExpired) as e:  # O(1)
        return 127, str(e)  # O(1)
    return r.returncode, (r.stdout or "") + (r.stderr or "")  # O(output)


def _live():  # O(a)
    import herdr_client  # O(1)
    try:  # O(1)
        return {a["name"] for a in herdr_client.agents()}  # O(a)
    except herdr_client.HerdrError:  # O(1)
        return None  # O(1)


def _now_ms():  # O(1)
    return int(time.time() * 1000)  # O(1)


def _sleep(s):  # O(s)
    time.sleep(s)  # O(s)


def _out(rc, text):  # O(len(text))
    print(text)  # O(len(text))
    return rc  # O(1)


def _layers(wt):  # O(output)
    """Names of the stale layers (empty when the checker is absent or clean)."""
    if not (Path(wt) / "scripts" / "test_layers.py").is_file():  # O(1)
        return []  # O(1)
    rc, out = _run(["python3", "scripts/test_layers.py", "check"], wt)  # O(output)
    if rc != 2:  # O(1)
        return []  # O(1)
    return [m.group(1) for m in re.finditer(r"^(\S+) stale:", out, re.M)]  # O(lines)


def _dotted(obj, field):  # O(depth)
    for k in field.split("."):  # O(depth)
        obj = obj.get(k) if isinstance(obj, dict) else None  # O(1)
    return obj  # O(1)


def _current_version(wt):  # O(file)
    try:  # O(1)
        cfg = json.loads((Path(wt) / ".version-bump.json").read_text())  # O(file)
        ent = next(f for f in cfg["files"] if str(f.get("path", "")).endswith(".json"))  # O(files)
        cur = _dotted(json.loads((Path(wt) / ent["path"]).read_text()), ent["field"])  # O(file)
        a, b, c = str(cur).split(".")  # O(1)
        return f"{int(a)}.{int(b)}.{int(c)}"  # O(1)
    except (OSError, ValueError, KeyError, StopIteration, TypeError):  # O(1)
        return None  # O(1)


def _next_version(wt):  # O(file)
    cur = _current_version(wt)  # O(file)
    if not cur:  # O(1)
        return None  # O(1)
    a, b, c = cur.split(".")  # O(1)
    return f"{a}.{b}.{int(c) + 1}"  # O(1)


def _tail(out, n=3):  # O(lines)
    return " / ".join([x.strip() for x in out.splitlines() if x.strip()][-n:])  # O(lines)


def _incident(sd, lead, text):  # O(1)
    import incident  # O(1)
    e = incident.make_entry("backlog_ship.py", 0, text, agent=lead, kind="workaround")  # O(1)
    Path(sd).mkdir(parents=True, exist_ok=True)  # O(1)
    with open(Path(sd) / "incidents.jsonl", "a") as f:  # O(1)
        f.write(json.dumps(e) + "\n")  # O(1)


FOLLOW = re.compile(r"(?i)\bfollow[- ]?ups?\b[^:\n]{0,30}:\s*(\S.*)")  # O(1)
UNDONE = re.compile(r"(?i)^\s*(?:[-*]\s*)?left undone\s*:\s*(\S.*)")  # O(1)
CTRL_KEEP = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")  # O(1)
CTRL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")  # O(1)


def _item(text):  # O(len(text))
    return CTRL.sub("", re.sub(r"\s+", " ", text)).strip()  # O(len(text))


def note_items(notes):  # O(len(notes))
    """Follow-up and left-undone lines of a lead's notes."""
    out = {"followups": [], "undone": []}  # O(1)
    for line in (notes or "").splitlines():  # O(lines)
        m = UNDONE.match(line)  # O(len(line))
        if m:  # O(1)
            out["undone"].append(_item(m.group(1)))  # O(len(line))
            continue  # O(1)
        m = FOLLOW.search(line)  # O(len(line))
        if m:  # O(1)
            out["followups"].append(_item(m.group(1)))  # O(len(line))
    return out  # O(1)


def _keep_notes(sd, bid, notes):  # O(len(notes))
    """Write the full notes to <sd>/backlog/<bid>.notes.md (non-blank only); return the parsed items."""
    clean = CTRL_KEEP.sub("", (notes or "").replace("\r\n", "\n"))  # O(len(notes))
    if clean.strip():  # O(1)
        f = Path(sd) / "backlog" / f"{bid}.notes.md"  # O(1)
        f.parent.mkdir(parents=True, exist_ok=True)  # O(1)
        f.write_text(clean, encoding="utf-8")  # O(len(notes))
    return note_items(clean)  # O(len(notes))


def _set(root, bid, **kw):  # O(batches)
    import backlog_state as bs  # O(1)
    bs.update(bs.path(root), lambda d: bs.batch(d, bid).update(kw))  # O(batches)


def _acquire(a, ctx, owner, again):  # O(wait)
    import ship_lock  # O(1)
    bid, waited = ctx["batch"]["id"], 0  # O(1)
    while True:  # O(wait / 15)
        r = ship_lock.acquire(ctx["lock"], owner, _live(), _now_ms())  # O(1)
        if r["acquired"]:  # O(1)
            break  # O(1)
        h = r["holder"]  # O(1)
        if waited >= a.wait:  # O(1)
            return _out(4, f"WAIT: ship lock held by {h['batch']} ({h['lead']}); run sl backlog ship {bid} {again} again")  # O(1)
        _sleep(15); waited += 15  # O(1)
    if r["took_over"]:  # O(1)
        h = r["holder"]  # O(1)
        ctx["pre"].append(f"took over the stale ship lock of {h['batch']} ({h['lead']})")  # O(1)
        _incident(ctx["sd"], owner["lead"], f"{bid} took over the stale ship lock of {h['batch']} ({h['lead']})")  # O(1)
    return None  # O(1)


def _lock(a, ctx):  # O(wait)
    b, wt = ctx["batch"], ctx["wt"]  # O(1)
    owner = {"batch": b["id"], "lead": b["lead"], "agent": b.get("agent"), "repo": ctx["repo"]}  # O(1)
    lines = ctx["pre"] = []  # O(1)
    rc = _acquire(a, ctx, owner, "lock")  # O(wait)
    if rc is not None:  # O(1)
        return rc  # O(1)
    rc, out = _run(["git", "fetch", "origin"], wt)  # O(output)
    if rc != 0:  # O(1)
        return _out(3, "\n".join(lines + [f"BLOCKED: git fetch origin failed: {_tail(out)}; lock held"]))  # O(1)
    _, ref = _run(["git", "symbolic-ref", "--short", "refs/remotes/origin/HEAD"], wt)  # O(1)
    default = (ref.strip().split("/", 1)[-1] if ref.strip() else "") or "main"  # O(1)
    rc, out = _run(["git", "rebase", f"origin/{default}"], wt)  # O(output)
    if rc != 0:  # O(1)
        _, names = _run(["git", "diff", "--name-only", "--diff-filter=U"], wt)  # O(files)
        return _out(5, "\n".join(lines + [f"CONFLICT: {' '.join(names.split())}; lock held: resolve with fixers, git rebase --continue, then run lock again"]))  # O(files)
    stale = _layers(wt)  # O(output)
    if stale:  # O(1)
        lines.append("LAYERS: " + " ".join(stale))  # O(1)
    lines.append(f"{b['id']} lock held")  # O(1)
    return _out(0, "\n".join(lines))  # O(1)


def _bump(a, ctx):  # O(1)
    b, wt = ctx["batch"], ctx["wt"]  # O(1)
    stale = _layers(wt)  # O(output)
    if stale:  # O(1)
        return _out(2, f"refused: stale layers {' '.join(stale)} (run them first)")  # O(1)
    _, st = _run(["git", "status", "--porcelain"], wt)  # O(files)
    if st.strip():  # O(1)
        return _out(2, "refused: uncommitted changes in the worktree")  # O(1)
    if not (Path(wt) / "scripts" / "bump-version.sh").is_file():  # O(1)
        return _out(0, f"{b['id']} bump: skipped (no scripts/bump-version.sh)")  # O(1)
    if b.get("version") and _current_version(wt) == b["version"]:  # O(file)
        return _out(0, f"{b['id']} version {b['version']} (already bumped)")  # O(1)
    v = a.version or _next_version(wt)  # O(file)
    if not v:  # O(1)
        return _out(3, "BLOCKED: cannot work out the next version; pass --version; lock held")  # O(1)
    for cmd in (["bash", "scripts/bump-version.sh", v], ["git", "commit", "-am", f"Bump version to {v}"]):  # O(1)
        rc, out = _run(cmd, wt)  # O(output)
        if rc != 0:  # O(1)
            return _out(3, f"BLOCKED: {' '.join(cmd[:2])} failed: {_tail(out)}; lock held")  # O(1)
    _set(ctx["root"], b["id"], version=v)  # O(batches)
    return _out(0, f"{b['id']} version {v}")  # O(1)


def with_closes(text, issues):  # O(len(text) * issues)
    """text plus one `Closes #N` line per issue it does not already close."""
    miss = [n for n in issues if not re.search(rf"(?i)\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?):?\s+#{n}\b", text)]  # O(len(text) * issues)
    if not miss:  # O(1)
        return text  # O(1)
    head = text.rstrip()  # O(len(text))
    return head + ("\n\n" if head else "") + "".join(f"Closes #{n}\n" for n in miss)  # O(issues)


def _open_issues(repo, issues, root):  # O(issues)
    def is_open(n):  # O(1)
        rc, out = _run(["gh", "issue", "view", str(n), "-R", repo, "--json", "state", "-q", ".state"], root)  # O(output)
        return rc != 0 or out.strip() == "OPEN"  # O(1)
    left = [n for n in issues if is_open(n)]  # O(issues)
    if left:  # O(1)
        _sleep(10)  # O(1)
        left = [n for n in left if is_open(n)]  # O(issues)
    return left  # O(1)


def _refuse(ctx, text):  # O(1)
    if ctx.get("main"):  # O(1)
        import ship_lock  # O(1)
        ship_lock.release(ctx["lock"], ctx["batch"]["id"])  # O(1)
    return _out(2, text)  # O(1)


def _give_up(ctx, rc, text):  # O(1)
    """Main's ship stopped: release the lock, keep the batch parked with the reason."""
    import ship_lock  # O(1)
    bid = ctx["batch"]["id"]  # O(1)
    ship_lock.release(ctx["lock"], bid)  # O(1)
    _set(ctx["root"], bid, state="parked", reason=text, parked_at=_now_ms())  # O(batches)
    nxt = f"sl backlog start {bid} resumes its lead to fix it" if rc in (5, 6) else f"run sl backlog ship {bid} merge --from-main again"  # O(1)
    return _out(rc, "\n".join(ctx["pre"] + [f"{text}; lock released, {bid} parked: {nxt}"]))  # O(1)


def _version_tuple(v):  # O(1)
    try:  # O(1)
        return tuple(int(x) for x in str(v).split("."))  # O(1)
    except ValueError:  # O(1)
        return None  # O(1)


def _second_bump(ctx, default):  # O(file)
    """After the rebase: bump again when origin/<default> is at or above the batch version. None when fine."""
    b, wt = ctx["batch"], ctx["wt"]  # O(1)
    if not (Path(wt) / "scripts" / "bump-version.sh").is_file():  # O(1)
        return None  # O(1)
    bad = f"BLOCKED: cannot read the version on origin/{default}"  # O(1)
    try:  # O(1)
        cfg = json.loads((Path(wt) / ".version-bump.json").read_text())  # O(file)
        ent = next(f for f in cfg["files"] if str(f.get("path", "")).endswith(".json"))  # O(files)
    except (OSError, ValueError, KeyError, StopIteration, TypeError, AttributeError):  # O(1)
        return _give_up(ctx, 3, bad)  # O(1)
    rc, out = _run(["git", "show", f"origin/{default}:{ent['path']}"], wt)  # O(output)
    try:  # O(1)
        if rc != 0:  # O(1)
            raise ValueError(out)  # O(1)
        base = _version_tuple(_dotted(json.loads(out), ent["field"]))  # O(file)
    except (ValueError, KeyError, TypeError):  # O(1)
        base = None  # O(1)
    if not base or len(base) != 3:  # O(1)
        return _give_up(ctx, 3, bad)  # O(1)
    cur = _version_tuple(_current_version(wt))  # O(file)
    if cur and cur > base:  # O(1)
        return None  # O(1)
    v = f"{base[0]}.{base[1]}.{base[2] + 1}"  # O(1)
    for cmd in (["bash", "scripts/bump-version.sh", v], ["git", "commit", "-am", f"Bump version to {v}"]):  # O(1)
        rc, out = _run(cmd, wt)  # O(output)
        if rc != 0:  # O(1)
            _run(["git", "reset", "--hard", "HEAD"], wt)  # O(files)
            return _give_up(ctx, 3, f"BLOCKED: {' '.join(cmd[:2])} failed: {_tail(out)}")  # O(1)
    _set(ctx["root"], b["id"], version=v)  # O(batches)
    ctx["batch"] = {**b, "version": v}  # O(1)
    ctx["pre"].append(f"{b['id']} version {v} (origin/{default} is at {'.'.join(map(str, base))})")  # O(1)
    return None  # O(1)


def _from_main(a, root, data, b):  # O(wait)
    """merge --from-main: main ships a parked batch under the ship lock; a rerun after RERUN goes straight to maxapp ship."""
    import ship_lock  # O(1)
    bid, repo, wt = b["id"], data.get("repo"), b.get("worktree")  # O(1)
    if os.environ.get("SUPERLITE_FLEET_WORKER"):  # O(1)
        return _out(2, f"refused: sl backlog ship {bid} merge --from-main runs only in the main session")  # O(1)
    if not data.get("approved_ship"):  # O(1)
        return _out(2, "refused: no ship approval recorded (sl backlog decide)")  # O(1)
    if b.get("state") != "parked":  # O(1)
        return _out(2, f"refused: {bid} is {b.get('state')}, not parked (main ships a parked batch only)")  # O(1)
    if not repo or not wt:  # O(1)
        return _out(2, f"refused: {bid} has no repo or worktree recorded")  # O(1)
    wt = Path(wt)  # O(1)
    if not wt.is_dir():  # O(1)
        return _out(2, f"refused: worktree {wt} is gone")  # O(1)
    if (wt / "scripts" / "bump-version.sh").is_file() and not b.get("version"):  # O(1)
        return _out(2, f"refused: {bid} has no version yet (its lead never ran bump)")  # O(1)
    _, st = _run(["git", "status", "--porcelain"], wt)  # O(files)
    if st.strip():  # O(1)
        return _out(2, "refused: uncommitted changes in the worktree")  # O(1)
    ctx = {"root": root, "sd": root / ".superlite", "batch": b, "wt": wt, "lock": ship_lock.lock_path(repo), "repo": repo, "main": True, "pre": []}  # O(1)
    h = ship_lock.holder(ctx["lock"])  # O(1)
    resume = bool(h) and h.get("batch") == bid and h.get("lead") == "main"  # O(1)
    if h and h.get("batch") == bid and h.get("lead") != "main":  # O(1)
        ship_lock.release(ctx["lock"], bid)  # O(1)
    rc = _acquire(a, ctx, {"batch": bid, "lead": "main", "agent": None, "repo": repo}, "merge --from-main")  # O(wait)
    if rc is not None:  # O(1)
        return rc  # O(1)
    if resume:  # O(1)
        return _merge(a, ctx)  # O(1)
    rc, out = _run(["git", "fetch", "origin"], wt)  # O(output)
    if rc != 0:  # O(1)
        return _give_up(ctx, 3, f"BLOCKED: git fetch origin failed: {_tail(out)}")  # O(1)
    _, ref = _run(["git", "symbolic-ref", "--short", "refs/remotes/origin/HEAD"], wt)  # O(1)
    default = (ref.strip().split("/", 1)[-1] if ref.strip() else "") or "main"  # O(1)
    rc, out = _run(["git", "rebase", f"origin/{default}"], wt)  # O(output)
    if rc != 0:  # O(1)
        _, names = _run(["git", "diff", "--name-only", "--diff-filter=U"], wt)  # O(files)
        _run(["git", "rebase", "--abort"], wt)  # O(1)
        return _give_up(ctx, 5, f"CONFLICT: {' '.join(names.split())}; rebase aborted")  # O(files)
    bumped = _second_bump(ctx, default)  # O(file)
    if bumped is not None:  # O(1)
        return bumped  # O(1)
    return _merge(a, ctx)  # O(1)


def _merge(a, ctx):  # O(1)
    import backlog_brief  # O(1)
    import ship_lock  # O(1)
    b, wt, root, sd, bid = ctx["batch"], ctx["wt"], ctx["root"], ctx["sd"], ctx["batch"]["id"]  # O(1)
    title = a.title or f"{bid}: " + " ".join(f"#{n}" for n in b.get("issues", []))  # O(issues)
    if a.body_file:  # O(1)
        try:  # O(1)
            source = Path(a.body_file).read_text(encoding="utf-8")  # O(file)
        except (OSError, ValueError):  # O(1)  ValueError: not UTF-8
            return _refuse(ctx, f"refused: cannot read {a.body_file}")  # O(1)
    else:  # O(1)
        pr_body = Path(wt) / ".superlite" / "pr-body.md"  # O(1)
        try:  # O(1)
            source = pr_body.read_text(encoding="utf-8") if pr_body.is_file() else ""  # O(file)
        except (OSError, ValueError):  # O(1)
            return _refuse(ctx, f"refused: cannot read {pr_body}")  # O(1)
    issues = b.get("issues", [])  # O(1)
    body = Path(sd) / "backlog" / f"{bid}.pr-body.md"  # O(1)
    body.parent.mkdir(parents=True, exist_ok=True)  # O(1)
    body.write_text(with_closes(source, issues), encoding="utf-8")  # O(file)
    cmd = ["maxapp", "ship", "-C", str(wt), "--timeout", "8", "--title", title, "--body-file", str(body)]  # O(1)
    try:  # O(1)  read before the run: maxapp ship -C may remove the lead's own worktree
        notes = (Path(wt) / ".superlite" / "notes.md").read_text(encoding="utf-8")  # O(file)
    except (OSError, ValueError):  # O(1)
        notes = ""  # O(1)
    rc, out = _run(cmd, wt)  # O(output)
    if rc == 0:  # O(1)
        m = re.search(r"(?:merged|shipped) #(\d+)", out)  # O(output)
        if not m:  # O(1)
            if ctx.get("main"):  # O(1)
                return _give_up(ctx, 3, f"BLOCKED: maxapp ship gave no merged PR number ({_tail(out)})")  # O(1)
            return _out(3, f"BLOCKED: maxapp ship gave no merged PR number ({_tail(out)}); lock held")  # O(1)
        n = int(m.group(1))  # O(1)
        s = Path(sd) / "backlog" / f"{bid}.md"  # O(1)
        s.parent.mkdir(parents=True, exist_ok=True)  # O(1)
        items = _keep_notes(sd, bid, notes)  # O(file)
        s.write_text(backlog_brief.summary({**b, "pr": n}, notes), encoding="utf-8")  # O(file)
        left = _open_issues(ctx["repo"], issues, root)  # O(issues)
        _set(root, bid, pr=n, merged=True, open_issues=left, **items)  # O(batches)
        ship_lock.release(ctx["lock"], bid)  # O(1)
        if ctx.get("main"):  # O(1)
            import backlog_run  # O(1)
            import backlog_state as bs  # O(1)
            lines = backlog_run._shipped(bs.path(root), Path(sd), root, {**b, "pr": n, "open_issues": left, **items}, wt)  # O(size)
            return _out(0, "\n".join(ctx["pre"] + lines))  # O(lines)
        return _out(0, "\n".join([f"{bid} shipped PR #{n} {b.get('version') or '-'} summary={s}"] + [f"OPEN #{i}" for i in left]))  # O(issues)
    if ctx.get("main") and rc == 3:  # O(1)
        return _give_up(ctx, 6, f"RED: {_tail(out)}")  # O(1)
    if rc == 3:  # O(1)
        return _out(6, f"RED: {_tail(out)}; lock held: fix with fixers, commit, run merge again")  # O(1)
    if rc == 4:  # O(1)
        runs = (b.get("ship_runs") or 0) + 1  # O(1)
        again = "merge --from-main" if ctx.get("main") else "merge"  # O(1)
        if runs < MAX_RUNS:  # O(1)
            _set(root, bid, ship_runs=runs)  # O(batches)
            return _out(4, "\n".join(ctx.get("pre", []) + [f"RERUN: sl backlog ship {bid} {again} (run {runs} of {MAX_RUNS})"]))  # O(1)
        _set(root, bid, ship_runs=runs, state="parked", reason=f"maxapp ship timed out {MAX_RUNS} times", parked_at=_now_ms())  # O(batches)
        ship_lock.release(ctx["lock"], bid)  # O(1)
        return _out(3, "\n".join(ctx.get("pre", []) + [f"BLOCKED: maxapp ship timed out {MAX_RUNS} times; lock released"]))  # O(1)
    if ctx.get("main"):  # O(1)
        return _give_up(ctx, 3, f"BLOCKED: maxapp ship failed ({_tail(out)})")  # O(1)
    return _out(3, f"BLOCKED: maxapp ship failed ({_tail(out)}); lock held")  # O(1)


def _release(a, ctx):  # O(1)
    import ship_lock  # O(1)
    bid = ctx["batch"]["id"]  # O(1)
    held = ship_lock.release(ctx["lock"], bid)  # O(1)
    text = f"{bid} lock released" if held else f"{bid} lock not held"  # O(1)
    if a.park:  # O(1)
        _set(ctx["root"], bid, state="parked", reason=a.park, parked_at=_now_ms())  # O(batches)
        text += ", parked"  # O(1)
    return _out(0, text)  # O(1)


def _done(a, root, data, b):  # O(issues)
    import backlog_brief  # O(1)
    import backlog_run  # O(1)
    import backlog_state as bs  # O(1)
    import ship_lock  # O(1)
    bid, n = b["id"], a.pr  # O(1)
    if os.environ.get("SUPERLITE_FLEET_WORKER"):  # O(1)
        return _out(2, f"refused: sl backlog ship {bid} done runs only in the main session")  # O(1)
    if not n or n < 1:  # O(1)
        return _out(2, "refused: done needs --pr N")  # O(1)
    if b.get("state") not in ("running", "needs_decision", "parked"):  # O(1)
        return _out(2, f"refused: {bid} is {b.get('state')}, not running or parked")  # O(1)
    repo, wt = data.get("repo"), b.get("worktree")  # O(1)
    if not repo or not wt:  # O(1)
        return _out(2, f"refused: {bid} has no repo or worktree recorded")  # O(1)
    rc, out = _run(["gh", "pr", "view", str(n), "-R", repo, "--json", "state", "-q", ".state"], root)  # O(output)
    if rc != 0:  # O(1)
        return _out(3, f"BLOCKED: cannot read PR #{n} ({_tail(out)})")  # O(1)
    if out.strip() != "MERGED":  # O(1)
        return _out(2, f"refused: PR #{n} is {out.strip() or 'unknown'}, not merged")  # O(1)
    v = a.version or b.get("version") or _current_version(wt)  # O(file)
    try:  # O(1)
        notes = (Path(wt) / ".superlite" / "notes.md").read_text(encoding="utf-8")  # O(file)
    except (OSError, ValueError):  # O(1)
        notes = ""  # O(1)
    s = root / ".superlite" / "backlog" / f"{bid}.md"  # O(1)
    s.parent.mkdir(parents=True, exist_ok=True)  # O(1)
    items = _keep_notes(root / ".superlite", bid, notes)  # O(file)
    s.write_text(backlog_brief.summary({**b, "pr": n, "version": v}, notes), encoding="utf-8")  # O(file)
    left = _open_issues(repo, b.get("issues", []), root)  # O(issues)
    _set(root, bid, pr=n, version=v, merged=True, open_issues=left, **items)  # O(batches)
    try:  # O(1)
        ship_lock.release(ship_lock.lock_path(repo), bid)  # O(1)
    except (OSError, ValueError):  # O(1)
        pass  # O(1)
    lines = backlog_run._shipped(bs.path(root), root / ".superlite", root, {**b, "pr": n, "version": v, "open_issues": left, **items}, wt)  # O(size)
    return _out(0, "\n".join(lines))  # O(lines)


def _env_lost(b):  # O(1)
    if os.environ.get("SUPERLITE_FLEET_ROLE") or os.environ.get("SUPERLITE_FLEET_WORKER"):  # O(1)
        return False  # O(1)
    if b.get("state") != "running" or not b.get("worktree"):  # O(1)
        return False  # O(1)
    wt, cwd = Path(b["worktree"]).resolve(), Path.cwd().resolve()  # O(1)
    return cwd == wt or wt in cwd.parents  # O(depth)


def main(argv=None):  # O(1)
    import backlog_state as bs  # O(1)
    import ship_lock  # O(1)
    p = argparse.ArgumentParser(prog="sl backlog ship")  # O(1)
    p.add_argument("batch"); p.add_argument("action", choices=["lock", "bump", "merge", "release", "done"])  # O(1)
    p.add_argument("--wait", type=int, default=500); p.add_argument("--version"); p.add_argument("--title")  # O(1)
    p.add_argument("--body-file"); p.add_argument("--park"); p.add_argument("--plan"); p.add_argument("--pr", type=int)  # O(1)
    p.add_argument("--from-main", action="store_true")  # O(1)
    a = p.parse_args(argv)  # O(1)
    root = Path(_root())  # O(1)
    data = bs.load(bs.path(root))  # O(size)
    try:  # O(1)
        b = bs.batch(data, a.batch)  # O(batches)
    except KeyError:  # O(1)
        return _out(2, f"refused: unknown batch {a.batch}")  # O(1)
    if a.from_main:  # O(1)
        if a.action != "merge":  # O(1)
            return _out(2, "refused: --from-main goes only with merge")  # O(1)
        return _from_main(a, root, data, b)  # O(wait)
    if a.action == "done":  # O(1)
        return _done(a, root, data, b)  # O(1)
    if os.environ.get("SUPERLITE_FLEET_ROLE") != "lead" or os.environ.get("SUPERLITE_FLEET_WORKER") != b.get("lead"):  # O(1)
        if _env_lost(b):  # O(1)
            if data.get("repo"):  # O(1)
                try:  # O(1)
                    ship_lock.release(ship_lock.lock_path(data["repo"]), a.batch)  # O(1)
                except (OSError, ValueError):  # O(1)
                    pass  # O(1)
            _set(root, a.batch, state="parked", reason=f"lead {b.get('lead')} lost its fleet env (resumed after a crash)", parked_at=_now_ms())  # O(batches)
            return _out(2, "refused: this session has no fleet environment (SUPERLITE_FLEET_ROLE and SUPERLITE_FLEET_WORKER unset), as a lead "  # O(1)
                           f"resumed after a crash has none, so it cannot ship as lead {b.get('lead')}; {a.batch} is parked: end your turn with "  # O(1)
                           f"Status: BLOCKED fleet env lost, then main runs sl backlog start {a.batch}")  # O(1)
        return _out(2, f"refused: sl backlog ship {a.batch} runs only in its lead {b.get('lead')}")  # O(1)
    if not data.get("approved_ship"):  # O(1)
        return _out(2, "refused: no ship approval recorded (sl backlog decide)")  # O(1)
    if b.get("state") != "running":  # O(1)
        return _out(2, f"refused: {a.batch} is {b.get('state')}, not running")  # O(1)
    if not data.get("repo") or not b.get("worktree"):  # O(1)
        return _out(2, f"refused: {a.batch} has no repo or worktree recorded")  # O(1)
    lock = ship_lock.lock_path(data["repo"])  # O(1)
    ctx = {"root": root, "sd": root / ".superlite", "batch": b, "wt": Path(b["worktree"]), "lock": lock, "repo": data["repo"], "pre": []}  # O(1)
    if a.action in ("bump", "merge"):  # O(1)
        h = ship_lock.holder(lock)  # O(1)
        if not h or h.get("batch") != a.batch:  # O(1)
            return _out(2, f"refused: {a.batch} does not hold the ship lock (run lock first)")  # O(1)
    return {"lock": _lock, "bump": _bump, "merge": _merge, "release": _release}[a.action](a, ctx)  # O(1)


if __name__ == "__main__":  # O(1)
    sys.exit(main())  # O(1)
