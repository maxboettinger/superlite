"""Spawn a batch lead: a fleet worker of main's run, role `lead`, in its own worktree with its own run state.

Not a CLI. `backlog_run` calls `spawn_lead`. A lead gets no prime and no pool entry; its brief arrives as the first message.
A lead starts with `--autocompact` set to main's window (`main_window`, #464). A start that stays slow is retried once on another account (#454).
A pane still no shell after that retry is closed and the lead starts once more in a fresh pane (#551).
A folder trust dialog still open after a successful start is accepted (#514).
The lead's fleet.json record carries `launch` ({argv, env, cwd}: the exact start, #577) and `session` (its Claude session id, when herdr reports one) so `fleet restore` can resume it.
A lead whose spawner pins GH_CONFIG_DIR (a sealed golden run) starts with `--settings <lead state>/gh-seal-settings.json`, whose env clears each GitHub token variable the spawner lacks and pins GH_CONFIG_DIR, since a pane's shell profile or a Claude settings env would beat the herdr --env value (#1041).
A sealed lead also starts with `--plugin-dir <the checkout whose scripts spawn it>` (when it holds .claude-plugin/plugin.json), so a golden run, also on `--machine M`, runs the commit under test rather than the plugin installed on the machine (#1051).
"""
import json  # O(1)
import os  # O(1)
import sys  # O(1)
from pathlib import Path  # O(1)

sys.path.insert(0, str(Path(__file__).resolve().parent))  # O(1)
import fleet  # noqa: E402 | O(1)
import run_config  # noqa: E402 | O(1)


NoShell = fleet.NoShell  # moved to fleet.py: workers retry in a fresh pane too | O(1)


DEFAULT_WINDOW = 400000  # O(1) the window /superlite:setup offers
GH_TOKENS = fleet.GH_TOKENS  # O(1) the seal helpers live in fleet.py beside PASS_THROUGH (#1049)
GH_SEAL_FILE = fleet.GH_SEAL_FILE  # O(1)
PLUGIN_ROOT = fleet.PLUGIN_ROOT  # O(1)
gh_seal_env = fleet.gh_seal_env  # O(1)
write_gh_seal = fleet.write_gh_seal  # O(1)
plugin_dir = fleet.plugin_dir  # O(1)


def _pos(v):  # O(1)
    return v if isinstance(v, int) and not isinstance(v, bool) and v > 0 else None  # O(1)


def main_window(env, model):  # O(k) main's auto-compact window: env variable, user settings, model settings, else the default
    try:  # O(1)
        n = _pos(int(env.get("CLAUDE_CODE_AUTO_COMPACT_WINDOW", "")))  # O(1)
    except ValueError:  # O(1)
        n = None  # O(1)
    if n:  # O(1)
        return n  # O(1)
    cdir = env.get("CLAUDE_CONFIG_DIR")  # O(1)
    path = Path(cdir) / "settings.json" if cdir else Path(env.get("HOME") or Path.home()) / ".claude" / "settings.json"  # O(1)
    try:  # O(1)
        data = json.loads(path.read_text(encoding="utf-8"))  # O(file)
    except (OSError, ValueError):  # O(1)
        return DEFAULT_WINDOW  # O(1)
    if not isinstance(data, dict):  # O(1)
        return DEFAULT_WINDOW  # O(1)
    n = _pos(data.get("autoCompactWindow"))  # O(1)
    if n:  # O(1)
        return n  # O(1)
    ms = data.get("modelSettings")  # O(1)
    if isinstance(ms, dict):  # O(1)
        for key in sorted(ms):  # O(k log k)
            if model in key and isinstance(ms[key], dict) and _pos(ms[key].get("autoCompactWindow")):  # O(1)
                return ms[key]["autoCompactWindow"]  # O(1)
    return DEFAULT_WINDOW  # O(1)


def lead_argv(sl_path, model, window=None, effort=None, deny=None, mcp_config=None, ship=True, settings=None, plugin_dir=None):  # O(d)
    argv = ["--model", model] + (["--effort", effort] if effort else [])  # O(1)
    argv += ["--permission-mode", "auto"]  # O(1)
    if settings:  # a sealed lead's gh seal file (#1041) | O(1)
        argv += ["--settings", str(settings)]  # O(1)
    if plugin_dir:  # a sealed lead loads the plugin of the commit under test (#1051) | O(1)
        argv += ["--plugin-dir", str(plugin_dir)]  # O(1)
    if ship:  # a plan lead never ships: main decides the integration (#906) | O(1)
        argv += ["--allowedTools", "Bash(maxapp ship *)", f"Bash({sl_path} backlog ship *)"]  # O(1)
    if deny is not None or mcp_config:  # a lean start: only the servers named, no browser bridge | O(1)
        argv += ["--strict-mcp-config"] + (["--mcp-config", str(mcp_config)] if mcp_config else []) + ["--no-chrome"]  # O(1)
    argv += ["--disallowedTools", "AskUserQuestion", *dict.fromkeys(d for d in (deny or []) if d != "AskUserQuestion")]  # O(d)
    if window is not None:  # O(1)
        argv += ["--autocompact", f"{window // 1000}k" if window % 1000 == 0 else str(window)]  # O(1)
    return argv  # O(1)


def lead_env(main_sd, lead_sd, wid, config_dir, base_env, accounts, ttl=None):  # O(a)
    env = {"SUPERLITE_FLEET_WORKER": wid, "SUPERLITE_FLEET_AGENT": "lead", "SUPERLITE_FLEET_ROLE": "lead",  # O(1)
           "SUPERLITE_STATE_DIR": str(Path(lead_sd).resolve()), "SUPERLITE_FLEET_PARENT_DIR": str(Path(main_sd).resolve()),
           "CLAUDE_CODE_ENABLE_PROMPT_SUGGESTION": "0"}
    if ttl:  # the lead's main-conversation cache TTL, set explicitly | O(1)
        env["CLAUDE_CODE_PROMPT_CACHE_TTL"] = ttl  # O(1)
    if accounts:  # O(1)
        env["SUPERLITE_FLEET_ACCOUNTS"] = ",".join(accounts)  # O(a)
    if not fleet.ac.is_default_dir(config_dir, base_env):  # O(1)
        env["CLAUDE_CONFIG_DIR"] = config_dir  # O(1)
    for k in fleet.PASS_THROUGH:  # O(1)
        if base_env.get(k):  # O(1)
            env[k] = base_env[k]  # O(1)
    return env  # O(1)


def _lead_mcp(rc, wid, worktree, lsd, cdir, base):  # O(n + f) the --mcp-config path for the servers the lead keeps, or None; never raises
    want = rc["lead"].get("mcp")  # O(1)
    if not want:  # O(1)
        return None  # O(1)
    try:  # an MCP error never stops a lead: it starts lean | O(1)
        import fleet_mcp  # noqa: E402 | O(1)
        import mcp_check  # noqa: E402 | O(1)
        cj = fleet.claude_json(cdir, base)  # O(1)
        found, notes = fleet_mcp.servers("implementer", worktree, cj) if want == "project" else fleet_mcp.named(list(want), worktree, cj)  # O(n + f)
        kept = {}  # O(1)
        for n, d in found.items():  # O(k)
            why = mcp_check.check(n, d, lsd, worktree)  # O(1)
            if why:  # O(1)
                notes.append(f"mcp: {n} left out: {why}")  # O(1)
            else:  # O(1)
                kept[n] = d  # O(1)
        for note in notes:  # O(k)
            print(f"{wid} {note}", file=sys.stderr)  # O(1)
        return fleet_mcp.write_config(lsd, kept) if kept else None  # O(k)
    except Exception as e:  # noqa: BLE001 | O(1)
        print(f"{wid} mcp: none: {e}", file=sys.stderr)  # O(1)
        return None  # O(1)


def _session(name):  # O(1) the agent's Claude session id, or None; never raises (older herdr clients lack agent_session)
    try:  # O(1)
        fn = getattr(fleet.hc, "agent_session", None)  # O(1)
        return fn(name) if fn else None  # O(1)
    except Exception:  # noqa: BLE001 | O(1)
        return None  # O(1)


def _record_session(main_sd, wid, session):  # O(w)
    with fleet.fs.locked(main_sd):  # O(1)
        data = fleet.fs.load(main_sd)  # O(w)
        if wid in data["workers"]:  # O(1)
            data["workers"][wid]["session"] = session  # O(1)
            fleet.fs.save(main_sd, data)  # O(w)


def spawn_lead(main_sd, worktree, model=None, env=None, rc=None, plan=None, ship=True):  # O(a * e + w) plus herdr calls
    base = dict(os.environ) if env is None else env  # O(env)
    rc = rc or run_config.resolve()  # O(f)
    model = model or rc["lead"]["model"]  # O(1)
    try:  # O(1)
        return _spawn_lead(main_sd, worktree, model, base, None, rc, plan, ship)  # O(a * e + w)
    except (fleet._Slow, NoShell) as first:  # O(1)
        return _spawn_lead(main_sd, worktree, model, base, first, rc, plan, ship)  # O(a * e + w)


def _spawn_lead(main_sd, worktree, model, base, after, rc, plan=None, ship=True):  # O(a * e + w) plus herdr calls
    fs, hc = fleet.fs, fleet.hc  # O(1)
    main_sd, worktree = Path(main_sd), Path(worktree)  # O(1)
    fresh = isinstance(after, NoShell)  # O(1)
    tail = "" if after is None else f"; retried in a fresh pane after {after.wid}" if fresh else f"; retried after {after.wid} on {after.account}"  # O(1)
    account, cdir, shared = fleet.choose_account(main_sd, model, base, lead=True) if after is None or fresh else fleet._retry_account(main_sd, model, base, after.account, lead=True)  # O(a * e + w)
    if fresh:  # O(1)
        print(f"{after.wid} {after.why}; retrying in a fresh pane", file=sys.stderr)  # O(1)
    elif after is not None:  # O(1)
        print(f"{after.wid} account {after.account} {after.why}; retrying on account {account}", file=sys.stderr)  # O(1)
    wid = fs.next_id(main_sd)  # O(w)
    name = fs.agent_name(main_sd, wid, root=worktree, ident="lead", taken=fleet._live_names())  # O(a)
    worktree.mkdir(parents=True, exist_ok=True)  # O(1)
    lsd = worktree / ".superlite"  # O(1)
    lsd.mkdir(parents=True, exist_ok=True)  # O(1)
    wt, lsd_s = str(worktree.resolve()), str(lsd.resolve())  # O(1)
    lead = rc["lead"]  # O(1)
    seal = write_gh_seal(Path(lsd_s), base)  # O(1)
    wenv = lead_env(main_sd, lsd, wid, cdir, base, fs.load(main_sd).get("accounts") or [], (rc.get("cache_ttl") or {}).get("lead"))  # O(w)
    sl = str(Path(__file__).resolve().parent / "sl")  # O(1)
    mcp = _lead_mcp(rc, wid, worktree, lsd, cdir, base)  # O(n + f)
    argv = lead_argv(sl, model, lead.get("autocompact") or main_window(base, model), lead.get("effort"), list(lead.get("deny") or []), mcp, ship, settings=seal, plugin_dir=plugin_dir() if seal else None)  # O(k)
    run_config.write_active(lsd, rc)  # the run's config snapshot, read by the lead's workers | O(f)
    record = {"name": name, "account": account, "agent": "lead", "tier": model, "state": "starting", "task": None, "role": "lead",  # O(1)
              "one_turn": False, "lead_sd": lsd_s, "worktree": wt, "run_config": rc.get("id"), "launch": {"argv": argv, "env": wenv, "cwd": wt}}
    if plan:  # the plan this lead builds (#906) | O(1)
        record["plan"] = str(Path(plan).resolve())  # O(1)
    try:  # O(1)
        pane = fleet.open_pane(main_sd, wid, wt, wenv, record)  # O(w + p)
        try:  # O(1)
            fs.register_agent(name, shared)  # O(1)
        except OSError:  # O(1)
            pass  # O(1)
    except hc.HerdrError as e:  # O(1)
        fleet._blocked(main_sd, wid, account, f"startup: {e.message or e.code}{tail}")  # O(1)

    def fail(why, screen=None, slow=False, shell=False, signed_out=False):  # O(s + w)
        fs.set_state(main_sd, wid, "blocked")  # O(w)
        if signed_out:  # O(1)
            fleet.mark_signed_out(main_sd, account)  # O(w)
            why = fleet.SIGNED_OUT_WHY  # O(1)
        try:  # O(1)
            hc.close_pane(pane)  # O(1)
        except hc.HerdrError:  # O(1)
            pass  # O(1)
        if signed_out and after is None:  # the caller starts it once more on another account | O(1)
            fleet._keep(main_sd, wid, why, screen, "fleet spawn retry")  # O(s)
            raise fleet._SignedOut(wid, account, why)  # O(1)
        if signed_out:  # O(1)
            var = "" if fleet.ac.is_default_dir(cdir, base) else f"CLAUDE_CONFIG_DIR={cdir} "  # O(1)
            why += f"; sign in once ({var}claude, then /login), then rerun"  # O(1)
        if slow and after is None:  # the caller starts it once more on another account | O(1)
            fleet._keep(main_sd, wid, why, screen, "fleet spawn retry")  # O(s)
            raise fleet._Slow(wid, account, why)  # O(1)
        if shell and after is None:  # the caller starts it once more in a fresh pane | O(1)
            fleet._keep(main_sd, wid, why, screen, "fleet spawn retry")  # O(s)
            raise NoShell(wid, account, why)  # O(1)
        fleet._blocked(main_sd, wid, account, why + tail, screen)  # O(s)

    seen = ""  # the screen after a start with no trust dialog; a failed read is an empty screen | O(1)
    try:  # O(1)
        try:  # O(1)
            retried = fleet.start_on_shell(name, pane, argv)  # O(1)
        except hc.HerdrError as e:  # O(1)
            screen = ""  # O(1)
            try:  # O(1)
                screen = hc.read_screen(name, fleet.SCREEN_ROWS)  # O(s)
            except hc.HerdrError:  # O(1)
                pass  # O(1)
            if fleet.ac.sign_in_screen(screen):  # the account is signed out (#880) | O(s)
                fail("", screen, signed_out=True)  # O(s)
            if e.code != "agent_not_ready" or fleet.TRUST not in screen:  # O(s)
                shell = fleet.SHELL_MSG in (getattr(e, "message", "") or "")  # O(len)
                first = next((x.strip() for x in screen.splitlines() if x.strip()), e.message or e.code)  # O(s)
                fail(f"startup: {e.message + getattr(e, 'retried', '') if shell else first}", screen, slow=fleet._slow(e), shell=shell)  # O(s)
            hc.send_keys(name, ["Down", "Enter"])  # O(1)
            hc.wait_state(name, ["idle"], 60000)  # O(1)
        else:  # O(1)
            try:  # O(1)
                screen = hc.read_screen(name, fleet.SCREEN_ROWS)  # O(s)
            except hc.HerdrError:  # O(1)
                screen = ""  # O(1)
            if fleet.TRUST in screen and not fleet._is_ready(screen):  # O(s)
                hc.send_keys(name, ["Down", "Enter"])  # O(1)
                hc.wait_state(name, ["idle"], 60000)  # O(1)
            else:  # O(1)
                seen = screen  # O(1)
    except hc.HerdrError as e:  # O(1)
        fail(f"startup: {e}", slow=fleet._slow(e))  # O(1)
    if fleet.ac.sign_in_screen(seen):  # the start left the sign-in screen up (#880) | O(s)
        fail("", seen, signed_out=True)  # O(s)
    fs.set_state(main_sd, wid, "ready")  # O(w)
    sid = _session(name)  # O(1)
    if sid:  # O(1)
        _record_session(main_sd, wid, sid)  # O(w)
    fleet._launch_line(main_sd, wid, "lead", model, account, pane)  # O(1)
    print(f"{wid} account={account} pane={pane} agent=lead role=lead")  # O(1)
    return {"id": wid, "name": name, "account": account, "pane_id": pane, "agent": "lead", "model": model, "role": "lead", "lead_sd": lsd_s, "config": rc.get("id")}  # O(1)


