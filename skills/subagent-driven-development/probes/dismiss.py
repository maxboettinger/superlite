"""Dismissal records for probe_run results (#417). Stdlib only.

A coordinator rules a probe failure group no defect: `probe_run --dismiss ID` stores a record in
`<run folder>/probes/dismissed.json`, deletes the generated regression test and closes its incident.
Later runs move failure groups that match a record to `results["dismissed"]`."""
from __future__ import annotations  # O(1)

import json  # O(1)
import os  # O(1)
import re  # O(1)
import sys  # O(1)
import time  # O(1)
from pathlib import Path  # O(1)

GEN_HEADER = '"""Generated by probe_run.py:'  # O(1)
ADAPTER = "_probe_adapter.py"  # O(1)
KIND_MAP = {"crash": "exception", "leak": "exception", "hang": "perf", "setup-error": "spec-ambiguity"}  # O(1)


def sig(key: str) -> str:  # O(len key)
    """Group key without its trailing line number."""  # O(1)
    return re.sub(r":\d+$", "", key)  # O(len key)


def _incident(key: str | None):  # O(len key)
    m = re.match(r"^(.+):(\d+)$", (key or "").split("|")[-1])  # O(len key) last part only
    return {"file": m.group(1), "line": int(m.group(2))} if m else None  # O(1)


def _group_record(g: dict, rid: str) -> dict:  # O(probes)
    return {"id": rid, "category": g.get("category"), "kind": g.get("kind"),  # O(1)
            "sig": sig(g["key"]) if g.get("key") else None, "probes": list(g.get("probes") or []),  # O(probes)
            "test": g.get("regression_test"), "incident": g.get("incident")}  # O(1)


def _header_record(path: Path, root: Path) -> dict | None:  # O(1) two lines
    try:  # O(1)
        with path.open(encoding="utf-8", errors="replace") as f:  # O(1)
            l1, l2 = f.readline(), f.readline()  # O(line length)
    except OSError:  # O(1)
        return None  # O(1)
    m1 = re.match(r'^"""Generated by probe_run\.py: (\S+) (\S+) \((.*)\)\.\s*$', l1)  # O(len l1)
    m2 = re.search(r"; probe (\S+?)\.(?:\s|$)", l2)  # O(len l2)
    if not m1 or not m2:  # O(1)
        return None  # O(1)
    cat, kind, key = m1.groups()  # O(1)
    return {"id": path.stem, "category": cat, "kind": kind, "sig": sig(key), "probes": [m2.group(1)],  # O(1)
            "test": path.relative_to(root).as_posix() if path.is_relative_to(root) else str(path),  # O(parts)
            "incident": _incident(key)}  # O(len key)


def resolve(ident: str, results: dict, root: Path) -> dict | None:  # O(failures * probes)
    """Dismissal record for a test name, group id or probe id; None when nothing matches."""  # O(1)
    fails = (results or {}).get("failures") or []  # O(1)
    name = Path(ident).name  # O(len ident)
    stem = name[:-3] if name.endswith(".py") else name  # O(1)
    if stem.startswith("test_probe_"):  # O(1)
        for g in fails:  # O(failures)
            if Path(g.get("regression_test") or "").stem == stem:  # O(len path)
                return _group_record(g, stem)  # O(probes)
        p = Path(root) / "tests" / "regression" / f"{stem}.py"  # O(1)
        return _header_record(p, Path(root)) if p.is_file() else None  # O(1) two lines
    if re.fullmatch(r"g\d+", ident):  # O(len ident)
        g = next((g for g in fails if g.get("group_id") == ident), None)  # O(failures)
        return _group_record(g, ident) if g else None  # O(probes)
    if "/" in ident:  # O(1)
        g = next((g for g in fails if ident in (g.get("probes") or [])), None)  # O(failures * probes)
        if g:  # O(1)
            return _group_record(g, ident)  # O(probes)
        return {"id": ident, "category": ident.split("/")[0], "kind": None, "sig": None,  # O(len ident)
                "probes": [ident], "test": None, "incident": None}  # O(1)
    return None  # O(1)


def _store(folder: Path) -> Path:  # O(1)
    return Path(folder) / "probes" / "dismissed.json"  # O(1)


def load(folder: Path) -> list[dict]:  # O(file bytes)
    """Stored dismissal records; [] for a missing or corrupt file."""  # O(1)
    try:  # O(1)
        recs = json.loads(_store(folder).read_text(encoding="utf-8"))["dismissed"]  # O(file bytes)
    except (OSError, ValueError, KeyError, TypeError):  # O(1)
        return []  # O(1)
    return [r for r in recs if isinstance(r, dict)] if isinstance(recs, list) else []  # O(records)


def _same(a: dict, b: dict) -> bool:  # O(probes)
    if a.get("category") != b.get("category") or a.get("sig") != b.get("sig"):  # O(1)
        return False  # O(1)
    return a.get("sig") is not None or a.get("probes") == b.get("probes")  # O(probes)


def add(folder: Path, record: dict, reason: str) -> bool:  # O(file bytes)
    """Store a record; True when new, False when it replaced an equivalent one."""  # O(1)
    recs = load(folder)  # O(file bytes)
    new = {**record, "reason": reason, "time": int(time.time())}  # O(1)
    keep = [r for r in recs if not _same(r, new)]  # O(records * probes)
    path = _store(folder)  # O(1)
    path.parent.mkdir(parents=True, exist_ok=True)  # O(1)
    tmp = path.with_name(path.name + f".{os.getpid()}.tmp")  # O(1)
    tmp.write_text(json.dumps({"dismissed": keep + [new]}, indent=1), encoding="utf-8")  # O(file bytes)
    os.replace(tmp, path)  # O(1)
    return len(keep) == len(recs)  # O(1)


def matches(records: list[dict], group: dict) -> dict | None:  # O(records * probes)
    """First record that covers a failure group: same category and sig, or a bare probe id it lists."""  # O(1)
    for r in records:  # O(records)
        if r.get("sig"):  # O(1)
            if r.get("category") == group.get("category") and r["sig"] == sig(group.get("key") or ""):  # O(len key)
                return r  # O(1)
        elif any(p in (group.get("probes") or []) for p in r.get("probes") or []):  # O(probes^2)
            return r  # O(1)
    return None  # O(1)


def remove_generated(root: Path, test: str | None) -> list[str]:  # O(files beside the test)
    """Delete a generated test (header check) and the adapter when no generated test is left."""  # O(1)
    if not test:  # O(1)
        return []  # O(1)
    root = Path(root)  # O(1)
    p = root / test  # O(1)
    gone: list[str] = []  # O(1)
    try:  # O(1)
        with p.open(encoding="utf-8", errors="replace") as f:  # O(1)
            generated = f.readline().startswith(GEN_HEADER)  # O(line length)
    except OSError:  # O(1)
        return []  # O(1)
    if not generated:  # O(1)
        return []  # O(1)
    p.unlink()  # O(1)
    gone.append(p.relative_to(root).as_posix())  # O(parts)
    ad = p.parent / ADAPTER  # O(1)
    if ad.is_file() and not any(p.parent.glob("test_probe_*.py")):  # O(files beside)
        ad.unlink()  # O(1)
        gone.append(ad.relative_to(root).as_posix())  # O(parts)
    return gone  # O(1)


def run(ident: str, reason: str, folder: Path, root: Path, results_path: Path, log_path: Path, log_fn) -> int:  # O(results + file bytes)
    """The `probe_run --dismiss ID` command; returns the exit code."""  # O(1)
    try:  # O(1)
        results = json.loads(Path(results_path).read_text(encoding="utf-8"))  # O(results bytes)
    except (OSError, ValueError):  # O(1)
        results = {}  # O(1)
    if not isinstance(results, dict):  # O(1)
        results = {}  # O(1)
    rec = resolve(ident, results, Path(root))  # O(failures * probes)
    if rec is None:  # O(1)
        print(f"probe_run: --dismiss {ident}: no failure group, regression test or probe id matches", file=sys.stderr)  # O(len ident)
        return 2  # O(1)
    add(folder, rec, reason)  # O(file bytes)
    removed = remove_generated(Path(root), rec.get("test"))  # O(files beside)
    inc = rec.get("incident")  # O(1)
    if inc:  # O(1)
        kind = KIND_MAP.get(rec.get("kind"), "test-failure")  # O(1)
        log_fn(log_path, [(inc["file"], inc["line"], f"wontfix: probe result dismissed ({reason})", kind, "wontfix")])  # O(1) + log append
    store = _store(folder)  # O(1)
    shown = store.relative_to(root).as_posix() if store.is_relative_to(root) else store.as_posix()  # O(parts)
    what = rec["sig"] or ", ".join(rec["probes"])  # O(probes)
    line = f"dismissed {rec['id']}: {rec['category']} {what}"  # O(len what)
    if removed:  # O(1)
        line += "; removed " + ", ".join(removed)  # O(removed)
    if inc:  # O(1)
        line += f"; incident {inc['file']}:{inc['line']} wontfix"  # O(1)
    print(f"{line}; later runs skip it ({shown})")  # O(len line)
    return 0  # O(1)
